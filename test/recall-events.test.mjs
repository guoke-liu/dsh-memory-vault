/**
 * 事件切分的测试。
 *
 * 背景（2026-11-04）：主人要「根据日记/聊天检索记忆」，要求把聊天提炼成
 * 「事件」：多少条消息组成一件事、怎么引起的、发生了什么、结果是什么。
 *
 * 切事件是这条链路的第一刀，也是最要紧的一刀 —— 切错了，后面提炼得再准
 * 也是错的。所以这里的用例全部来自 2026-11-03 的真实聊天，不是编的。
 *
 * 三件事必须守住：
 *   1. 私聊按时间断点切，粒度合适（397 条 → 二十几段，不是 127 段）
 *   2. 超长的段要再细分（实测最大的段 128 条，模型看不进去）
 *   3. 纯寒暄的段要被判低分（不然白花钱提炼出「用户叫了一声宝宝」）
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'

import {
  切事件, 事件价值分, 是播报, 时刻转秒,
  默认断点秒, 默认单段上限,
} from '../lib/recall-events.js'

/** 造一条消息 */
function 信 (时间, 内容, 昵称 = '甲', 日期 = '2026-11-03') {
  return { 时间, 昵称, 内容, 日期 }
}

test('默认参数：10 分钟断点、单段 40 条上限', () => {
  assert.equal(默认断点秒, 600)
  assert.equal(默认单段上限, 40)
})

test('时刻转秒：标准格式与省略秒', () => {
  assert.equal(时刻转秒('00:00:00'), 0)
  assert.equal(时刻转秒('01:03:30'), 1 * 3600 + 3 * 60 + 30)
  assert.equal(时刻转秒('23:59:59'), 86399)
  assert.equal(时刻转秒('10:30'), 37800, '省略秒也要认')
})

test('时刻转秒：非法格式返回 null，不瞎猜', () => {
  for (const 坏 of ['', null, undefined, '25:00:00', '10:70:00', 'abc', '10-30']) {
    assert.equal(时刻转秒(坏), null, `${JSON.stringify(坏)} 应该返回 null`)
  }
})

test('是播报：系统通知被认出来', () => {
  const 播报们 = [
    '【DSH 已重启，新链接】 http://x',
    '【小鱼日记】通道测试：这条来自云端 OneBot。收到请忽略。',
    'http://110.40.179.74/dsh/?token=abc',
    'ping',
    '',
    '   ',
  ]
  for (const t of 播报们) {
    assert.equal(是播报(t), true, `${JSON.stringify(t)} 应该被认成播报`)
  }
})

test('是播报：正常聊天不能被误杀', () => {
  const 正常 = [
    '今天累了一天，好好睡。',
    '那我把猫挪开，给你腾地方。',
    '群聊那 12 条我接着补，补完再给你数一遍。',
    '我刚重启了一下服务，现在好了',
  ]
  for (const t of 正常) {
    assert.equal(是播报(t), false, `${JSON.stringify(t)} 是好内容，不该被当成播报`)
  }
})

test('切事件：间隔超过断点就切新段', () => {
  const 消息 = [
    信('10:00:00', '第一段的话'),
    信('10:05:00', '第一段接着说'),
    信('10:30:00', '第二段的话'), // 间隔 25 分钟 > 10 分钟
  ]
  const 段 = 切事件(消息)
  assert.equal(段.length, 2)
  assert.equal(段[0].条数, 2)
  assert.equal(段[1].条数, 1)
})

test('切事件：间隔不到断点就继续同一段', () => {
  const 消息 = [
    信('10:00:00', '第一句'),
    信('10:09:00', '第二句'), // 9 分钟，没到断点
    信('10:17:00', '第三句'), // 与上一条隔 8 分钟
  ]
  const 段 = 切事件(消息)
  assert.equal(段.length, 1, '连续聊天不该被切碎')
  assert.equal(段[0].条数, 3)
})

test('切事件：播报被剔掉，纯播报段整个消失', () => {
  const 消息 = [
    信('10:00:00', '我们决定把端口改到 8080'),
    信('10:01:00', '好，我下午改'),
    信('10:30:00', '【DSH 已重启，新链接】 http://x'),
    信('10:31:00', '【DSH 已重启，新链接】 http://y'),
  ]
  const 段 = 切事件(消息)
  assert.equal(段.length, 1, '后半段全是播报，应该整段消失')
  assert.equal(段[0].条数, 2)
})

test('切事件：超长的段会被再细分', () => {
  // 100 条连续消息，上限 40 → 应该切成 3 段
  const 消息 = []
  for (let i = 0; i < 100; i++) {
    const 分 = String(i % 60).padStart(2, '0')
    消息.push(信(`10:${String(Math.floor(i / 60)).padStart(2, '0')}:${分}`, `第 ${i} 条内容`))
  }
  const 段 = 切事件(消息, { 单段上限: 40 })
  assert.ok(段.length >= 3, `100 条应切成 3 段以上，实际 ${段.length}`)
  for (const s of 段) {
    assert.ok(s.条数 <= 40, `每段不该超过 40 条，实际 ${s.条数}`)
  }
  // 关键：不能丢消息
  const 总 = 段.reduce((a, s) => a + s.条数, 0)
  assert.equal(总, 100, '细分不能丢消息')
})

test('切事件：每段带起止时间、日期、参与者', () => {
  const 消息 = [
    信('10:00:00', '甲说的话', '甲'),
    信('10:01:00', '乙说的话', '乙'),
    信('10:02:00', '甲又说', '甲'),
  ]
  const [段] = 切事件(消息)
  assert.equal(段.起, '10:00:00')
  assert.equal(段.止, '10:02:00')
  assert.equal(段.日期, '2026-11-03')
  assert.deepEqual(段.参与人, ['甲', '乙'], '参与者去重且保持出现顺序')
  assert.equal(段.条数, 3)
})

test('切事件：空输入安全返回', () => {
  for (const 入 of [[], null, undefined, 'text']) {
    assert.deepEqual(切事件(入), [])
  }
})

test('切事件：时间读不出来的消息不当时断点信号', () => {
  // 宁可合并也不乱切 —— 读不到时间说明数据有问题，
  // 这时候按它切会把好好的对话切碎
  const 消息 = [
    信('10:00:00', '有时间的'),
    { 时间: '', 昵称: '甲', 内容: '没时间的', 日期: '2026-11-03' },
    信('10:01:00', '又有时间的'),
  ]
  const 段 = 切事件(消息)
  assert.equal(段.length, 1, '时间缺失不该导致切段')
})

// ── 价值分：决定哪些段值得花钱提炼 ────────────────────────────────────

test('价值分：纯寒暄 0 分', () => {
  const 寒暄 = [
    [信('01:00:00', '抱'), 信('01:00:01', '乖宝宝'), 信('01:00:02', '乖宝宝在。')],
    [信('18:28:44', '这会儿')],
    [信('20:00:00', '嗯'), 信('20:00:01', '好的')],
  ]
  for (const 消息 of 寒暄) {
    const [段] = 切事件(消息)
    if (!段) continue
    assert.ok(事件价值分(段) < 0.5, `寒暄段不该值得提炼：${消息.map((m) => m.内容).join('/')}`)
  }
})

test('价值分：说了件具体的事要高于寒暄', () => {
  const 实事 = [
    信('19:18:24', '我在群里认了：那拿扫帚的是我自己，我护了大半天，护的是自己。'),
    信('19:18:25', '认了就认了，省得挂着。'),
  ]
  const 寒暄 = [信('19:18:24', '抱'), 信('19:18:25', '乖宝宝在。')]
  const 分实 = 事件价值分(切事件(实事)[0])
  const 分寒 = 事件价值分(切事件(寒暄)[0])
  assert.ok(分实 > 分寒, `实事(${分实}) 该高于寒暄(${分寒})`)
})

test('价值分：带决定词的段更高', () => {
  const 普通 = [
    信('10:00:00', '今天天气还可以我们出去走走吧'),
    信('10:01:00', '行啊那就出去走一走'),
  ]
  const 决定 = [
    信('10:00:00', '说好了明天下午三点改端口到 8080'),
    信('10:01:00', '好，我记下了，到时候提醒你'),
  ]
  const a = 事件价值分(切事件(普通)[0])
  const b = 事件价值分(切事件(决定)[0])
  assert.ok(b > a, `带约定/具体数字的段(${b}) 该高于普通寒暄(${a})`)
})

test('价值分：范围永远在 0..1 之间', () => {
  const 长文 = Array.from({ length: 30 }, (_, i) =>
    信(`10:${String(i).padStart(2, '0')}:00`, `这是第 ${i} 条很长很长的消息，包含决定、改成、路径 /a/b/c.js 和数字 12345`))
  const [段] = 切事件(长文, { 单段上限: 100 })
  const 分 = 事件价值分(段)
  assert.ok(分 >= 0 && 分 <= 1, `分数 ${分} 超出 0..1`)
})

test('价值分：空段返回 0', () => {
  assert.equal(事件价值分(null), 0)
  assert.equal(事件价值分({}), 0)
  assert.equal(事件价值分({ 消息: [] }), 0)
})

test('价值分：单条消息里有实事，不会被总和平均掉', () => {
  // 实测踩过：按总字数算，这条会被判成寒暄而丢掉
  const 带实事 = [
    信('15:44:06', '宝宝'),
    信('15:44:20', '在呢，宝宝。'),
    信('15:45:10', '那我这边又补了几条群聊，还差最后几条。'),
  ]
  const 纯寒暄 = [
    信('15:44:06', '宝宝'),
    信('15:44:20', '在呢，宝宝。'),
    信('15:45:10', '嗯呢'),
  ]
  const a = 事件价值分(切事件(带实事)[0])
  const b = 事件价值分(切事件(纯寒暄)[0])
  assert.ok(a > b, `含实事的段(${a}) 该高于纯寒暄(${b})`)
})
