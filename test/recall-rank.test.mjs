// recall-rank.js 自测：覆盖切词、分词、向量、四因子、检索、置信度
// 跑法：node --test test/recall-rank.test.mjs
//
// 并入记忆仓库时去掉了「与独立版 recall.js 对拍」那一节：独立版已不存在，
// 对拍对象只能是它自己，等于没验。切词的稳定性改由下面的直接断言保证。
import {
  切词, 分词, 嵌入, 余弦, 建索引, 三因子打分, 检索, 判置信度,
  默认停用词, EMBED_DIM, 默认权重,
} from '../lib/recall-rank.js'


import { test } from 'node:test'

let 过 = 0
let 挂 = 0
const 挂的 = []
function 测 (名, 条件, 细节) {
  if (条件) { 过++; console.log(`  ✅ ${名}`) } else { 挂++; 挂的.push(名); console.log(`  ❌ ${名}${细节 ? ' → ' + 细节 : ''}`) }
}
function 近似 (a, b, 容差 = 0.01) { return Math.abs(a - b) <= 容差 }

// ── 构造数据 ────────────────────────────────────────────────────────────
const 今天 = '2026-11-03'
const 天前 = (n) => new Date(Date.parse('2026-11-03T12:00:00Z') - n * 86400000).toISOString()
const 现在 = Date.parse('2026-11-03T12:00:00Z')
const 条目们 = [
  { 来源: 'private', 日期: today(0), id: "d1", title: '腾讯云轻量服务器续费', text: '服务器到期前要续费，腾讯云轻量那台还有两个月。', tags: ['服务器', '腾讯云'], at: 天前(1) },
  { 来源: 'private', 日期: today(30), id: 'd2', title: '机器又被 DDoS 了', text: '那台机器被人打，换了高防。', tags: [], at: 天前(30) },
  { 来源: 'group:730783833', 日期: today(90), id: 'g1', title: '群友聊服务器', text: '群里有人说自己的 vps 挂了，问怎么排查。', tags: ['群聊'], at: 天前(90) },
  { 来源: 'group:730783833', 日期: today(2), id: 'g2', title: '奶茶', text: '今天喝了一杯奶茶，很好喝。', tags: ['奶茶'], at: 天前(2) },
  { 来源: 'private', 日期: today(400), id: 'd3', title: '很久以前的部署记录', text: '第一次部署到这台服务器上，配了 nginx 和证书。', tags: ['部署'], at: 天前(400) },
]
function today (n) {
  return new Date(Date.parse('2026-11-03T12:00:00Z') - n * 86400000).toISOString().slice(0, 10)
}

const 索引 = 建索引(条目们)

console.log('—— 一、切词 ——')
测('中文 2 字滑窗', JSON.stringify(切词('服务器')) === JSON.stringify(['服务', '务器']))
测('英文数字整词', 切词('hello world 123').includes('hello'))
测('短词整段收', 切词('猫').includes('猫'))
测('空串返回空', 切词('').length === 0)

console.log('\n—— 二、最长匹配分词 ——')
const 分1 = 分词('今天去哪里吃饭', 索引)
测('不含跨词碎片「天去」', !分1.includes('天去'), JSON.stringify(分1))
const 分2 = 分词('腾讯云轻量服务器的续费', 索引)
测('能贴上「服务器」', 分2.includes('服务器'), JSON.stringify(分2))
测('停用词「的」被丢掉', !分词('这是我的服务器', 索引).includes('的'))
测('无词表时退回滑窗', 分词('服务器', {}) .length > 0)
测('英文数字整词保留', 分词('vps 挂了 24 小时', 索引).includes('vps'))
测('空文本返回空数组', 分词('', 索引).length === 0)
测('纯停用词返回空', 分词('的 了 是', 索引).length === 0)

console.log('\n—— 三、哈希向量 ——')
const v1 = 嵌入('服务器续费', 索引)
测(`维度是 ${EMBED_DIM}`, v1.length === EMBED_DIM)
测('无 NaN', v1.every((x) => Number.isFinite(x)), [...v1].slice(0, 3).join(','))
测('已归一化（模长≈1）', 近似(Math.sqrt([...v1].reduce((a, x) => a + x * x, 0)), 1))
const 零 = 嵌入('', 索引)
测('空文本返回零向量', [...零].every((x) => x === 0))
测('空文本余弦返回 0 不是 NaN', 余弦(零, 零) === 0)
测('余弦相同文本=1', 近似(余弦(v1, 嵌入('服务器续费', 索引)), 1))
测('相关 > 无关', 余弦(v1, 嵌入('服务器到期续费', 索引)) > 余弦(v1, 嵌入('奶茶好喝', 索引)))
测('余弦结果在 [0,1]', [余弦(v1, 嵌入('奶茶', 索引))].every((x) => x >= 0 && x <= 1))
测('长度不等返回 0', 余弦(new Float32Array(4), new Float32Array(8)) === 0)

console.log('\n—— 四、三因子打分 ——')
const 查 = { 词表: 分词('服务器', 索引), 查询向量: 嵌入('服务器', 索引) }
const 今日 = 三因子打分(条目们[0], 查, { 现在, df: 索引.df, 总数: 索引.总数, 条目向量: 索引.向量 })
const 百日前 = 三因子打分(条目们[2], 查, { 现在, df: 索引.df, 总数: 索引.总数, 条目向量: 索引.向量 })
测('今天的条目词面分 > 0', 今日.词面分 > 0)
测('时效分：今天≈1', 近似(今日.时效分, 1, 0.02), String(今日.时效分))
测('d1 有2个标签 → 重要度 2/3', 近似(今日.重要度分, 2/3, 0.02), String(今日.重要度分))
const 无标条目 = { title: '机器', text: '那台机器被人打', tags: [] }
测('无标签条目重要度=0.5', 近似(三因子打分(无标条目, 查, { 现在 }).重要度分, 0.5))
测('有3个标签重要度=1', 近似(三因子打分({ tags: ['a', 'b', 'c'], text: 'x' }, 查, { 现在 }).重要度分, 1))
测('总分不是 NaN', Number.isFinite(今日.总分))

// 时效衰减在纯时效维度上验证（不受 min-max 影响时用内部公式）
const 时效 = (天) => Math.pow(0.995, 天)
测('0.995^30 ≈ 0.86', 近似(时效(30), 0.86, 0.02), String(时效(30).toFixed(4)))
测('0.995^365 ≈ 0.16', 近似(时效(365), 0.16, 0.02), String(时效(365).toFixed(4)))

console.log('\n—— 五、检索 ——')
const 搜服务器 = 检索(索引, '服务器', { 现在, limit: 10 })
测('能搜到服务器相关条目', 搜服务器.命中数 >= 3, String(搜服务器.命中数))
测('结果不含奶茶无关条目', !搜服务器.结果.some((r) => r.id === 'g2'))
测('排第一的是「服务器续费」', 搜服务器.结果[0].id === 'd1', 搜服务器.结果.map((r) => r.id).join(','))
测('分数在 [0,1]', 搜服务器.结果.every((r) => r.分数.总分 >= 0 && r.分数.总分 <= 1))
测('分数分布最高 == 第一条总分', 近似(搜服务器.分数分布.最高, 搜服务器.结果[0].分数.总分, 0.002))

const 搜机器 = 检索(索引, '机器', { 现在, limit: 10 })
测('「机器」能搜到写机器的条目', 搜机器.结果.some((r) => r.id === 'd2'), 搜机器.结果.map((r) => r.id).join(','))

const 跨来源 = 检索(索引, '服务器', { 现在, 来源: '*', limit: 10 })
测('跨来源包含群聊条目', 跨来源.结果.some((r) => r.来源.startsWith('group:')), 跨来源.结果.map((r) => r.来源).join(','))
const 只群 = 检索(索引, '服务器', { 现在, 来源: 'group:730783833', limit: 10 })
测('来源过滤只有群', 只群.结果.every((r) => r.来源 === 'group:730783833'))

测('空查询是列举模式', 检索(索引, '', { 现在, limit: 10 }).命中数 === 5)
测('空查询按时间倒序', 检索(索引, '', { 现在, limit: 10 }).结果[0].id === 'd1')
测('limit=0 按 20 算（不崩）', 检索(索引, '服务器', { now: 现在, limit: 0 }).结果.length <= 20)
测('limit=999 夹到 100', 检索(索引, '服务器', { 现在, limit: 999 }).结果.length <= 100)
测('空索引不崩', 检索(建索引([]), '服务器', { 现在 }).命中数 === 0)
测('null 输入不崩', 检索(null, 'x', { 现在 }).命中数 === 0)

console.log('\n—— 六、判置信度 ——')
const 零命中 = 判置信度({ 命中数: 0, 分数分布: { 最高: 0, 最低: 0, 中位数: 0 } })
测('0 命中 → 下钻', 零命中.下钻 === true, 零命中.理由)
const 低分 = 判置信度({ 命中数: 2, 分数分布: { 最高: 0.2, 最低: 0.1, 中位数: 0.15 } })
测('最高分低 → 下钻', 低分.下钻 === true, 低分.理由)
const 挤 = 判置信度({ 命中数: 5, 分数分布: { 最高: 0.62, 最低: 0.5, 中位数: 0.59 } })
测('分数挤在一起 → 下钻', 挤.下钻 === true, 挤.理由)
const 正常 = 判置信度({ 命中数: 2, 分数分布: { 最高: 0.8, 最低: 0.4, 中位数: 0.6 } })
测('正常 → 不下钻', 正常.下钻 === false, 正常.理由)
测('边界：恰好 0.35 不下钻', 判置信度({ 命中数: 1, 分数分布: { 最高: 0.35, 最低: 0.35, 中位数: 0.35 } }).下钻 === false)
测('边界：2 条拥挤但不足 3 条不下钻', 判置信度({ 命中数: 2, 分数分布: { 最高: 0.8, 最低: 0.79, 中位数: 0.795 } }).下钻 === false)

console.log('\n—— 七、真实对话验证 ——')
const 真实 = 检索(索引, '服务器', { 现在, 来源: '*' })
console.log(真实.结果.map((r) => `  [${r.分数.总分}] ${r.日期} ${r.id} ${r.标题}`).join('\n'))
console.log('  查询词：', 真实.查询词.join(','))

test('recall-rank 全部断言', () => {
  console.log(`通过 ${过}，失败 ${挂}${挂 ? '：' + 挂的.join(' / ') : ''}`)
  // 必须真的 throw，否则测试框架会把「跑完了」当成「通过了」
  if (挂 > 0) throw new Error(`${挂} 条断言失败：${挂的.join(' / ')}`)
})
