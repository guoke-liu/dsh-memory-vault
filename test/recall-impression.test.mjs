/**
 * 群友印象分的测试。
 *
 * 背景（2026-11-04）：主人要求「根据艾特的内容增加一个群友印象分」，
 * 并且「太好的太坏的都会影响优先级」。
 *
 * 两条设计原则，这文件全部守住：
 *   1. 只认明确的信号 —— 模糊的一律中性，宁可少记不能记错
 *   2. 好话坏话都计分 —— 衡量的是「跟鱼的互动强度」，不是好感度净额
 *
 * 为什么第 1 条这么严：实测数据里全是反讽的坑。
 *   「@肥肥 大聪明」  —— 字面好、实际常是骂
 *   「@迟迟」         —— 只有 @，没有内容
 * 判错就等于把阴阳怪气记成好评，比不记更糟。
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'

import {
  判断印象, 拆艾特, 算印象分, 印象加成, 歧义词,
  解析机器人判断, 机器人艾特提示词,
} from '../lib/recall-impression.js'

// ── 好坏判断 ────────────────────────────────────────────────────────

test('明确的好话被判成「好」', () => {
  for (const t of ['宝宝真乖', '谢谢你', '好棒啊', '爱你', '辛苦了', '好可爱']) {
    assert.equal(判断印象(t).倾向, '好', `${JSON.stringify(t)} 该判成好话`)
  }
})

test('明确的坏话被判成「坏」', () => {
  for (const t of ['滚', '傻逼', '真蠢', '闭嘴', '烦死了', '别烦我']) {
    assert.equal(判断印象(t).倾向, '坏', `${JSON.stringify(t)} 该判成坏话`)
  }
})

test('反讽词一律中性 —— 宁可不记，不记错', () => {
  // 这是本模块最重要的行为。「大聪明」在中文里常是骂人，
  // 判成好话等于把阴阳怪气记成好评。
  for (const w of 歧义词) {
    const r = 判断印象(`${w}啊`)
    assert.equal(r.倾向, '中性', `「${w}」有歧义，不该判成好话`)
    assert.match(r.依据, /歧义/)
  }
})

test('歧义检查优先于好话检查', () => {
  // 即使同一句里既有歧义词又有好话词，也不判
  const r = 判断印象('大聪明，真乖')
  assert.equal(r.倾向, '中性')
})

test('没有明确信号的一律中性', () => {
  for (const t of ['在吗', '昨天进度玩到哪里了', '看看这个链接', '嗯', '好的']) {
    assert.equal(判断印象(t).倾向, '中性', `${JSON.stringify(t)} 不该被判定倾向`)
  }
})

test('空内容中性', () => {
  for (const t of ['', '   ', null, undefined]) {
    assert.equal(判断印象(t).倾向, '中性')
  }
})

// ── 艾特拆解 ────────────────────────────────────────────────────────

test('拆艾特：正常带空格', () => {
  const r = 拆艾特('@小鱼儿 宝宝真乖')
  assert.deepEqual(r.艾特们, ['小鱼儿'])
  assert.equal(r.正文, '宝宝真乖')
})

test('拆艾特：紧贴正文（实测出现过 @迟迟https://...）', () => {
  const r = 拆艾特('@迟迟https://github.com/x 看看这个')
  assert.deepEqual(r.艾特们, ['迟迟https://github.com/x'])
  assert.equal(r.正文, '看看这个')
})

test('拆艾特：只有 @ 没有内容', () => {
  const r = 拆艾特('@肥肥')
  assert.deepEqual(r.艾特们, ['肥肥'])
  assert.equal(r.正文, '')
})

test('拆艾特：多个 @', () => {
  const r = 拆艾特('@甲 @乙 你们看')
  assert.equal(r.艾特们.length, 2)
})

test('拆艾特：没有 @ 时返回空数组', () => {
  const r = 拆艾特('普通的一句话')
  assert.deepEqual(r.艾特们, [])
})

// ── 印象分统计 ──────────────────────────────────────────────────────

const 造 = (昵称, 内容, 日期 = '2026-11-03', 时间 = '10:00:00') => ({ 昵称, 内容, 日期, 时间 })

test('只统计 @ 了鱼的消息', () => {
  const r = 算印象分([
    造('甲', '@小鱼儿 宝宝真乖'),   // 算
    造('乙', '@别人 你好'),          // 不算（没 @ 鱼）
    造('丙', '宝宝真乖'),            // 不算（没 @）
  ])
  assert.equal(r.合计.艾特总数, 1)
  assert.equal(r.按人['甲'].好, 1)
  assert.equal(r.按人['乙'], undefined)
})

test('鱼的多个叫法都能认出来', () => {
  const r = 算印象分([
    造('甲', '@小鱼儿 谢谢'),
    造('乙', '@迟迟 好棒'),
    造('丙', '@肥肥 爱你'),
  ])
  assert.equal(r.合计.艾特总数, 3)
})

test('中性消息不占位、不计分', () => {
  const r = 算印象分([
    造('甲', '@小鱼儿'),
    造('甲', '@小鱼儿 在吗'),
  ])
  assert.equal(r.合计.艾特总数, 2, '两条都被识别为艾特鱼')
  assert.equal(r.按人['甲'], undefined, '但没有明确好坏，不产生印象记录')
})

test('分数 = 好 + 坏（好坏都计，不是净额）', () => {
  const r = 算印象分([
    造('甲', '@小鱼儿 宝宝真乖'),
    造('甲', '@小鱼儿 爱你'),
    造('甲', '@小鱼儿 滚'),
  ])
  const 记 = r.按人['甲']
  assert.equal(记.好, 2)
  assert.equal(记.坏, 1)
  assert.equal(记.分数, 3, '好坏都往上抬，所以是 2+1 不是 2-1')
})

test('夸 10 次骂 10 次不会变成 0 分', () => {
  const 消息 = []
  for (let i = 0; i < 10; i++) 消息.push(造('甲', '@小鱼儿 宝宝真乖'))
  for (let i = 0; i < 10; i++) 消息.push(造('甲', '@小鱼儿 滚'))
  const 记 = 算印象分(消息).按人['甲']
  assert.equal(记.分数, 20, '又爱又恨恰恰是最值得注意的关系，不能互相抵消')
})

test('样例保留原文，能核对为什么这么判', () => {
  const r = 算印象分([造('甲', '@小鱼儿 宝宝真乖')])
  const 样 = r.按人['甲'].样例[0]
  assert.equal(样.倾向, '好')
  assert.ok(样.原文.includes('宝宝真乖'))
  assert.ok(样.依据.includes('宝宝真乖'), '要说明命中哪个词')
})

test('样例有上限，不会无限堆', () => {
  const 消息 = []
  for (let i = 0; i < 10; i++) 消息.push(造('甲', `@小鱼儿 宝宝真乖第${i}次`))
  const 记 = 算印象分(消息, { 最多保留: 3 }).按人['甲']
  assert.equal(记.样例.length, 3)
  assert.equal(记.次数, 10, '但次数要统计全')
})

test('多个人的分数分开算', () => {
  const r = 算印象分([
    造('甲', '@小鱼儿 宝宝真乖'),
    造('乙', '@小鱼儿 滚'),
  ])
  assert.equal(r.按人['甲'].分数, 1)
  assert.equal(r.按人['乙'].分数, 1)
  assert.equal(r.合计.好, 1)
  assert.equal(r.合计.坏, 1)
})

test('空输入安全返回', () => {
  for (const 入 of [[], null, undefined, 'text']) {
    const r = 算印象分(入)
    assert.equal(r.合计.艾特总数, 0)
    assert.deepEqual(r.按人, {})
  }
})

// ── 优先级加成 ──────────────────────────────────────────────────────

test('印象加成：0 条 = 0', () => {
  assert.equal(印象加成(undefined), 0)
  assert.equal(印象加成({ 分数: 0 }), 0)
})

test('印象加成：随条数增长但有上限', () => {
  assert.ok(印象加成({ 分数: 1 }) > 0)
  assert.ok(印象加成({ 分数: 3 }) > 印象加成({ 分数: 1 }))
  assert.equal(印象加成({ 分数: 100 }), 0.15, '封顶 0.15')
})

test('印象加成：最大也不超过 0.15（不能盖过主判据）', () => {
  // 印象分是锦上添花。如果它能到 0.5，一个跟鱼互动多的人
  // 随便说句话就能压掉一条极重要的日记 —— 那就本末倒置了。
  for (const 分 of [1, 5, 50, 500]) {
    assert.ok(印象加成({ 分数: 分 }) <= 0.15, `${分} 分的加成超过 0.15`)
  }
})


// ── 两层分工：@ 鱼用规则，@ 别人家机器人交给模型 ────────────────────
//
// 主人 2026-11-04：「艾特用户自己的机器人的，艾特别人机器人的则由大模型
// 筛选的时候打分」。
//
// 实测群里的例子：
//   [21:37] 柳如烟: @龙娘 我头像叫什么名字
//   [18:54] 灵千梦: @grok is it true
//   [19:03] hah:    @限时接入Gemini 查询好感度
// 这些内容规则判不了好坏（「查询好感度」是好是坏？），得看语境。

test('@ 别人家机器人：不算进规则统计，单独计数留给模型', () => {
  const r = 算印象分([
    造('甲', '@小鱼儿 宝宝真乖'),
    造('乙', '@龙娘 我头像叫什么名字'),
    造('丙', '@grok is it true'),
  ], { 别人机器人: ['龙娘', 'grok'] })
  assert.equal(r.合计.艾特总数, 1, '只有 @鱼 的那条进规则统计')
  assert.equal(r.合计.别人机器人艾特, 2, '两条 @别人机器人 的单独计数')
  assert.equal(r.按人['乙'], undefined, '规则层不给它打分')
  assert.equal(r.按人['丙'], undefined)
})

test('@ 普通群友：两边都不算', () => {
  const r = 算印象分([
    造('甲', '@灰灰 你好'),
  ], { 别人机器人: ['龙娘', 'grok'] })
  assert.equal(r.合计.艾特总数, 0)
  assert.equal(r.合计.别人机器人艾特, 0, '普通群友不是机器人，也不该进模型那一层')
})

test('@ 了鱼又 @ 了别人机器人：按 @鱼 处理', () => {
  const r = 算印象分([
    造('甲', '@小鱼儿 @龙娘 你们两个真乖'),
  ], { 别人机器人: ['龙娘'] })
  assert.equal(r.合计.艾特总数, 1, '只要 @ 了鱼就归规则层')
})

test('解析机器人判断：三种倾向都能认', () => {
  assert.equal(解析机器人判断('{"倾向":"好","理由":"在夸它"}').倾向, '好')
  assert.equal(解析机器人判断('{"倾向":"坏","理由":"在骂它"}').倾向, '坏')
  assert.equal(解析机器人判断('{"倾向":"中性","理由":"只是提问"}').倾向, '中性')
})

test('解析机器人判断：解析失败一律中性（不瞎判）', () => {
  for (const 坏 of ['', '模型胡说', '{}', '[]', '{"倾向":"很坏"}']) {
    const r = 解析机器人判断(坏)
    assert.equal(r.倾向, '中性', `${JSON.stringify(坏)} 该按中性处理`)
    assert.equal(r.解析成功, false)
  }
})

