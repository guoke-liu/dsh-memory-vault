import { test } from 'node:test'
import { 载入词典, 切词最长, 读聊天行, 统计聊天, 找漏记, 拼日记全文 } from '../lib/recall-coverage.js'
let 过=0, 挂=0; const 失败=[]
const 测=(n,c,d)=>{ if(c){过++;console.log('  ✅ '+n)}else{挂++;失败.push(n);console.log('  ❌ '+n+(d?' → '+d:''))} }

const 词典 = await 载入词典()  // 用包内置词表
console.log('词典:', 词典.来源, '| 缺:', 词典.缺.join(',')||'无')
测('词表已载入', 词典.词表.size > 100000)
测('词频已载入', 词典.词频.size > 15000)

console.log('\n—— 切词 ——')
测('最长匹配贴出「重启」', 切词最长('服务器要重启一下', 词典).includes('重启'))
测('不产生「天去」碎片', !切词最长('今天去哪里吃饭', 词典).includes('天去'))
测('无词表退滑窗', 切词最长('服务器', {}).length > 0)

console.log('\n—— 聊天行解析 ——')
const 行们 = 读聊天行('[20:10:10] 小鱼(p83): 可以给画图加个冷却\n[20:11:00] 主人(p1): 好\n垃圾行')
测('解析出 2 行', 行们.length === 2, String(行们.length))
测('抽到 pid', 行们[0].pid === 'p83')
测('抽到内容', 行们[0].内容.includes('画图'))
测('昵称不被当内容', !行们[0].内容.includes('小鱼'))

console.log('\n—— 统计 ——')
const 统计 = 统计聊天(行们, 词典)
测('画图被统计到', 统计.has('画图'))
测('消息数=1', 统计.get('画图').消息数 === 1)

console.log('\n—— 找漏记（核心）——')
// 造 30 条消息提到「重启」，日记里一次没提
const 聊天1 = Array.from({length:30},(_,i)=>({pid:'p'+(i%5), 内容:`第${i}次要重启服务器了`}))
const 统计1 = 统计聊天(聊天1, 词典)
const 漏1 = 找漏记(统计1, '日记里只有别的内容', { 词频: 词典.词频 })
测('「重启」被识别为漏记', 漏1.some(x=>x.词==='重启'), JSON.stringify(漏1.map(x=>x.词)))
测('「服务器」也被识别', 漏1.some(x=>x.词==='服务器'))

// 日记里提过就不再算漏记
const 漏2 = 找漏记(统计1, '今天重启了服务器', { 词频: 词典.词频 })
测('日记提过 → 不算漏记', !漏2.some(x=>x.词==='重启'), JSON.stringify(漏2.map(x=>x.词)))

// 语法功能词要被挡掉
const 聊天3 = Array.from({length:30},(_,i)=>({pid:'p1', 内容:'因为这个所以那个但是已经'}))
const 统计3 = 统计聊天(聊天3, 词典)
const 漏3 = 找漏记(统计3, '空的', { 词频: 词典.词频 })
const 虚词=['因为','所以','但是','已经','这个','那个']
测('连词被稀有度门槛挡掉', !漏3.some(x=>虚词.includes(x.词)), JSON.stringify(漏3.map(x=>x.词)))

// 提及次数不够的不算
const 聊天4 = Array.from({length:5},(_,i)=>({pid:'p1', 内容:'重启重启'}))
测('提及不足 15 次不算漏记', 找漏记(统计聊天(聊天4,词典), '空', {词频:词典.词频}).length===0)

// 没词频表也不崩
测('无词频表降级可用', Array.isArray(找漏记(统计1, '空', {})))

console.log('\n—— 拼日记全文 ——')
测('含标签', 拼日记全文([{text:'正文',tags:['标签A'],title:'标题B'}]).includes('标签A'))
测('含标题', 拼日记全文([{text:'正文',tags:['标签A'],title:'标题B'}]).includes('标题B'))
测('空输入不崩', 拼日记全文(null) === '')

test('recall-coverage 全部断言', () => {
  console.log(`通过 ${过}，失败 ${挂}${挂?'：'+失败.join(' / '):''}`)
  if (挂 > 0) throw new Error(`${挂} 条断言失败：${失败.join(' / ')}`)
})
