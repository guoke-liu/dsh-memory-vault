/**
 * 群聊话题聚类的测试。
 *
 * 背景（2026-11-04）：主人说「群聊因为人多的原因可能多个事件混到一起」，
 * 并要求「群聊可以模糊一些」。所以群聊不做事件切分，只做话题聚类。
 *
 * 为什么群聊不能切事件（实测 2026-11-03 群 730783833 原始对话）：
 *   00:02 企鹅：图其实画出来了但是发不出来，上传超时   ← 事件①
 *   00:05 九尾：按新要求，画一张调月莉音              ← 事件②
 *   00:07 灰灰：中分背带鸡运球？这什么鬼画面          ← 事件③
 *   同一分钟内三条线并行，按时间切必然混成一段。
 *
 * 这个文件守住话题聚类的基本行为，以及**已知的局限**（见最后两个用例）。
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'

import { 聚话题, 抽片段, 话题价值分, 常见词档位 } from '../lib/recall-topics.js'

function 信 (时间, 内容, 昵称 = '甲', 日期 = '2026-11-03') {
  return { 时间, 昵称, 内容, 日期 }
}

test('抽片段：真实词能抽出来', () => {
  const 词 = 抽片段('我写了个新日记插件，token 用了多少')
  assert.ok(词.includes('日记'), '「日记」该被抽出')
  assert.ok(词.includes('token'), '「token」该被抽出')
})

test('抽片段：硬凑的组合被词频表挡掉', () => {
  // 这四个是 2 字滑窗最容易产出的垃圾（实测都在排序前十）
  for (const 垃圾 of ['的是', '是我', '我的', '我这']) {
    const 词 = 抽片段(`这句话里有${垃圾}两个字`)
    assert.ok(!词.includes(垃圾), `${垃圾} 不是真词，不该被抽出来`)
  }
})

test('抽片段：高频虚词被档位门槛挡掉', () => {
  // 「出来」档位 31，低于 45 的门槛 —— 太常见，当话题没有区分度
  const 词 = 抽片段('图已经发出来了')
  assert.ok(!词.includes('出来'), '「出来」太常见，不该当话题词')
  assert.ok(常见词档位 > 0, '门槛要是个正数')
})

test('抽片段：英文与型号按整词抽', () => {
  const 词 = 抽片段('下午给你们开会儿 Claude 和 Gemini，还有 deepseek')
  assert.ok(词.includes('claude'))
  assert.ok(词.includes('gemini'))
  assert.ok(词.includes('deepseek'))
})

test('抽片段：空输入返回空数组', () => {
  for (const 入 of ['', null, undefined, '   ']) {
    assert.deepEqual(抽片段(入), [])
  }
})

test('聚话题：反复出现的词成为话题', () => {
  const 消息 = [
    信('10:00', '我写了个新日记插件', '甲'),
    信('10:01', '日记插件好用吗', '乙'),
    信('10:02', '日记支持检索了', '丙'),
    信('10:03', '这个日记插件不错', '甲'),
    信('10:04', '其他无关的话', '丁'),
  ]
  const 话题 = 聚话题(消息, { 最少次数: 3, 最少人: 2 })
  const t = 话题.find((x) => x.话题 === '日记')
  assert.ok(t, '「日记」应该成为一个话题')
  assert.ok(t.消息数 >= 3, '至少三条消息相关')
})

test('聚话题：一个人反复说的不算话题（防口癖）', () => {
  // 实测：机器人反复写「（晃了晃尾巴）」，「尾巴」出现 90 次
  const 消息 = []
  for (let i = 0; i < 10; i++) {
    消息.push(信(`10:${String(i).padStart(2, '0')}`, '（晃了晃尾巴，笑了一下）', '小鱼儿'))
  }
  const 话题 = 聚话题(消息, { 最少次数: 3, 最少人: 3 })
  assert.equal(话题.find((x) => x.话题 === '尾巴'), undefined, '只有一个人说，不算话题')
})

test('聚话题：纯数字不作为话题', () => {
  const 消息 = [
    信('10:00', '今天用了 2026 个 token', '甲'),
    信('10:01', '2026 好数字', '乙'),
    信('10:02', '2026 确实', '丙'),
  ]
  const 话题 = 聚话题(消息, { 最少次数: 2, 最少人: 2 })
  assert.equal(话题.find((x) => x.话题 === '2026'), undefined, '数字没有区分度，不该成话题')
})

test('聚话题：每个话题只带上限内的消息', () => {
  const 消息 = []
  for (let i = 0; i < 30; i++) {
    消息.push(信(`10:00:${String(i).padStart(2, '0')}`, `日记插件第 ${i} 条`, ['甲', '乙', '丙'][i % 3]))
  }
  const 话题 = 聚话题(消息, { 最少次数: 3, 最少人: 2, 最多消息每话题: 5 })
  for (const t of 话题) {
    assert.ok(t.消息.length <= 5, `话题 ${t.话题} 带的消息超了上限`)
  }
})

test('聚话题：话题数量受上限约束', () => {
  const 消息 = []
  const 词表 = ['日记', '插件', '服务器', '模型', '记忆', '表情', '画图', '重启', '配置', '部署']
  for (let i = 0; i < 100; i++) {
    消息.push(信(`10:00:${String(i).padStart(2, '0')}`, `${词表[i % 词表.length]}又出问题了`, `人${i % 5}`))
  }
  const 话题 = 聚话题(消息, { 最少次数: 2, 最少人: 2, 最多话题: 3 })
  assert.ok(话题.length <= 3, `话题数 ${话题.length} 超过上限 3`)
})

test('聚话题：空输入安全返回', () => {
  for (const 入 of [[], null, undefined, 'text']) {
    assert.deepEqual(聚话题(入), [])
  }
})

test('聚话题：全空内容返回空', () => {
  const 消息 = [信('10:00', '', '甲'), 信('10:01', '   ', '乙')]
  assert.deepEqual(聚话题(消息), [])
})

test('聚话题：话题带人数统计', () => {
  const 消息 = [
    信('10:00', '日记插件写好了', '甲'),
    信('10:01', '日记能检索吗', '乙'),
    信('10:02', '日记支持全文搜索', '丙'),
  ]
  const t = 聚话题(消息, { 最少次数: 2, 最少人: 2 }).find((x) => x.话题 === '日记')
  assert.ok(t)
  assert.equal(t.人数, 3, '三个人都提过日记')
})

test('话题价值分：多个来源多说多写更高', () => {
  const 厚 = {
    话题: '日记',
    命中: 20,
    消息: [
      信('10:00', '日记插件写好了，说好今天合并', '甲'),
      信('10:01', '日记支持检索，改成全文搜索了', '乙'),
      信('10:02', '日记这块我修好了', '丙'),
      信('10:03', '日记的 8080 端口要注意', '丁'),
    ],
  }
  const 薄 = {
    话题: '嗯',
    命中: 20,
    消息: [信('10:00', '嗯', '甲'), 信('10:01', '好', '乙')],
  }
  assert.ok(话题价值分(厚) > 话题价值分(薄))
})

test('话题价值分：空话题 0 分且范围合法', () => {
  assert.equal(话题价值分(null), 0)
  assert.equal(话题价值分({ 消息: [] }), 0)
  const 分 = 话题价值分({ 命中: 5, 消息: [信('10:00', '日记插件写好了，说好要合并', '甲')] })
  assert.ok(分 >= 0 && 分 <= 1)
})

// ── 已知局限：这两条记录的是**当前做不到的事**，不是期望行为 ─────────────
//
// 写下来是为了让后来的人知道这是已知边界，而不是以为是 bug 去修：
// 纯统计方法分不出「描述性用语」和「讨论对象」。
// 「尾巴」出现 90 次、9 个人说过（因为大家描述机器人时都会提到），
// 「这边」出现 47 次、11 个人说过 —— 它们和「日记」「token」在词频、
// 人数上几乎没有区别，但前者不是话题。
//
// 要真正解决得靠语义判断（模型），那是消费档位里的事，不是规则层能做的。

test('已知局限：描述性高频词会被误判成话题（记录现状，不是期望）', () => {
  const 消息 = [
    信('10:00', '（晃了晃尾巴，笑了一下）', '小鱼儿'),
    信('10:01', '画只抱着自己尾巴的小白龙', '龙娘'),
    信('10:02', '尾巴轻轻晃着，这边真热闹', '灰灰'),
    信('10:03', '我这边看不到图，尾巴倒是看见', '甲'),
    信('10:04', '我这边也没图', '乙'),
    信('10:05', '这边一样', '丙'),
  ]
  const 话题 = 聚话题(消息, { 最少次数: 2, 最少人: 2, 最多话题: 10 })
  const 尾巴 = 话题.find((x) => x.话题 === '尾巴')
  // 现状：会被当成话题。这条断言记录的是「已知不完美」，
  // 将来规则改进后这里应当改成 assert.equal(尾巴, undefined)
  assert.ok(尾巴, '当前版本会把「尾巴」当话题 —— 这是已知局限')
})

// ── 时间序（实测踩过的坑）─────────────────────────────────────────────
//
// 聊天文件本身不是严格按时间写的：群 934074044 的 11-03 有 705 行，
// 其中 6 处时间倒挂（12:07 的消息写在 12:53 后面、08:39 排在最后）。
// 按行号排序再算时间窗，会切出「起 12:53:48 → 止 08:39:23」这种段。

test('话题段的时间范围必须是单调的（不受文件乱序影响）', () => {
  // 故意让文件顺序乱掉：12:53 在前、08:39 在后
  const 消息 = [
    信('12:53:48', '尾巴晃了晃', '甲'),
    信('12:54:31', '尾巴又在动', '乙'),
    信('12:55:22', '尾巴真忙', '甲'),
    信('08:39:23', '早上的尾巴', '甲'),
    信('12:07:56', '中午的尾巴', '乙'),
  ]
  const 话题 = 聚话题(消息, { 最少次数: 2, 最少人: 2 })
  assert.ok(话题.length > 0, '该聚出话题')
  for (const t of 话题) {
    assert.ok(t.起 <= t.止, `时间倒挂：${t.话题} ${t.起} -> ${t.止}`)
  }
})

test('话题段内的消息按时间升序排列', () => {
  const 消息 = [
    信('12:53:48', '日记插件在仓库里', '甲'),
    信('12:54:31', '日记插件怎么装', '乙'),
    信('08:39:23', '早上的日记插件', '丙'),
  ]
  const [t] = 聚话题(消息, { 最少次数: 2, 最少人: 2 })
  const 时间们 = t.消息.map((m) => m.时间)
  const 排好 = [...时间们].sort()
  assert.deepEqual(时间们, 排好, `消息没按时间排序：${时间们.join(',')}`)
})
