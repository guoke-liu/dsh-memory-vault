/**
 * 事件提炼的测试。
 *
 * 背景（2026-11-04）：主人要求「按开源的方向来」——
 * 这意味着**没有大模型也必须完整可用**，模型只能是可选增强。
 *
 * 所以规则提炼（不调模型）是主路径，这里主要验它。
 * 模型提炼只验两件事：失败时能干净地退回、JSON 能容错解析。
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'

import {
  规则提炼, 句子权重, 是寒暄, 判断对话类型, 解析事件JSON, 起个事件名,
} from '../lib/recall-event-extract.js'

function 段 (消息, 额外 = {}) {
  return {
    起: 消息[0]?.时间 || '',
    止: 消息[消息.length - 1]?.时间 || '',
    日期: '2026-11-03',
    参与人: [...new Set(消息.map((m) => m.昵称))],
    条数: 消息.length,
    消息,
    ...额外,
  }
}
const 信 = (时间, 内容, 昵称 = '甲') => ({ 时间, 昵称, 内容, 日期: '2026-11-03' })

// ── 寒暄识别 ────────────────────────────────────────────────────────

test('是寒暄：称呼和应答都算', () => {
  for (const t of ['宝宝', '乖', '抱抱', '嗯', '好的', '行', '在呢', '晚安', '爱你', '乖宝宝在。']) {
    assert.equal(是寒暄(t), true, `${JSON.stringify(t)} 该被认成寒暄`)
  }
})

test('是寒暄：带角色旁白的也要认出来', () => {
  assert.equal(是寒暄('（晃了晃尾巴）好'), true)
})

test('是寒暄：有内容的句子不能被误杀', () => {
  for (const t of ['我们决定把端口改到 8080', '图发不出来是因为画质太高', '仓库一共收到过 403 次']) {
    assert.equal(是寒暄(t), false, `${JSON.stringify(t)} 是好内容，不该当寒暄`)
  }
})

test('句子权重：寒暄 0 分，有内容的句子高分', () => {
  assert.equal(句子权重('宝宝'), 0)
  assert.equal(句子权重('嗯'), 0)
  assert.ok(句子权重('我们决定把端口改到 8080') > 0.3)
})

// ── 对话类型判断 ────────────────────────────────────────────────────

test('判断对话类型：有结论词的算「事情」', () => {
  const r = 判断对话类型([
    信('10:00', '端口冲突了怎么办'),
    信('10:01', '那改成 8080 吧，说好了'),
  ])
  assert.equal(r.类型, '事情')
})

test('判断对话类型：纯陪伴算「陪伴」', () => {
  const r = 判断对话类型([
    信('01:00', '好想你'),
    信('01:01', '我也想你，抱抱'),
    信('01:02', '别哭呀，我就在这儿陪你'),
  ])
  assert.equal(r.类型, '陪伴')
})

// ── 规则提炼 ────────────────────────────────────────────────────────

test('规则提炼：一件真事能提取出起因、经过、结果', () => {
  const r = 规则提炼(段([
    信('19:02', '设置页一直报 http404，怎么办'),
    信('19:20', '查到了，是代码里写死了绝对路径'),
    信('19:30', '路径在这几处 /root/.dsh/profiles/web/config.json'),
    信('19:41', '改成相对路径了，搞定'),
  ]))
  assert.equal(r.类型, '事情')
  assert.ok(r.起因.includes('http404'), `起因该是问题那句，实际：${r.起因}`)
  assert.ok(r.结果.includes('搞定') || r.结果.includes('相对路径'), `结果该是结论那句，实际：${r.结果}`)
  assert.ok(r.经过.length > 0, '应该有经过')
  assert.equal(r.提炼方式, '规则')
})

test('规则提炼：经过里不能出现纯寒暄', () => {
  // 实测踩过：第一版经过里出现「宝宝」「晚安，宝宝」
  const r = 规则提炼(段([
    信('01:03', '刚才那盘推到 136 卡住了'),
    信('01:04', '宝宝'),
    信('01:05', '哎，在。'),
    信('01:06', '晚安，宝宝。'),
    信('01:07', '今天累了一天，好好睡。'),
  ]))
  for (const g of r.经过) {
    assert.ok(!['宝宝', '哎，在。', '晚安，宝宝。'].includes(g), `经过里混进了寒暄：${g}`)
  }
})

test('规则提炼：起因和结果不能是同一句（单句段除外）', () => {
  const r = 规则提炼(段([
    信('19:02', '设置页一直报 http404，怎么修'),
    信('19:20', '是路径写死了'),
    信('19:41', '改成相对路径，搞定了'),
  ]))
  assert.notEqual(r.起因, r.结果, '起因和结果不该是同一句')
})

test('规则提炼：陪伴类不编起因和结果', () => {
  const r = 规则提炼(段([
    信('01:00', '好想你'),
    信('01:01', '我也想你，抱抱'),
    信('01:02', '别哭呀，我就在这儿陪你'),
  ]))
  assert.equal(r.类型, '陪伴')
  assert.equal(r.起因, '', '陪伴对话没有起因，留空比编一个诚实')
  assert.equal(r.结果, '')
  assert.ok(r.事件, '至少要有摘要')
})

test('规则提炼：空段安全返回', () => {
  const r = 规则提炼({ 消息: [] })
  assert.equal(r.条数, 0)
  assert.equal(r.起因, '')
})

test('规则提炼：带完整回查坐标，但**不存原文**', () => {
  const r = 规则提炼(段([
    { 时间: '19:02:00', 昵称: '甲', pid: 'p1', 内容: '设置页报错了怎么修', 日期: '2026-11-03' },
    { 时间: '19:41:00', 昵称: '乙', pid: 'p2', 内容: '改成相对路径搞定了', 日期: '2026-11-03' },
  ]))
  assert.equal(r.回查.length, 2)
  assert.equal(r.回查[0].时间, '19:02:00')
  assert.equal(r.回查[0].pid, 'p1')
  // 回查里不该出现正文 —— 原文在 chat/*.txt 里，不重复存
  assert.equal(r.回查[0].内容, undefined, '回查只存坐标，不存内容')
})

test('规则提炼：事件名来自原文，不是编的', () => {
  const 原文 = '设置页一直报 http404，怎么修'
  const r = 规则提炼(段([
    信('19:02', 原文),
    信('19:41', '改成相对路径，搞定了'),
  ]))
  // 事件名里至少要含原文的片段
  assert.ok(r.事件.includes('http404') || r.事件.includes('设置页'), `事件名不像原文：${r.事件}`)
})

// ── 模型 JSON 解析容错 ───────────────────────────────────────────────

test('解析事件JSON：标准 JSON', () => {
  const r = 解析事件JSON('{"事件":"修404","起因":"页面报错","经过":["查路径"],"结果":"修好了"}')
  assert.equal(r.ok, true)
  assert.equal(r.事件.事件, '修404')
  assert.equal(r.事件.经过.length, 1)
})

test('解析事件JSON：包在代码围栏里也能认', () => {
  const r = 解析事件JSON('```json\n{"事件":"修404","起因":"a","经过":[],"结果":"b"}\n```')
  assert.equal(r.ok, true)
  assert.equal(r.事件.事件, '修404')
})

test('解析事件JSON：前后有说明文字也能认', () => {
  const r = 解析事件JSON('好的，这是结果：\n{"事件":"修404","起因":"a","经过":[],"结果":"b"}\n希望有用')
  assert.equal(r.ok, true)
})

test('解析事件JSON：经过是字符串时包成数组', () => {
  const r = 解析事件JSON('{"事件":"x","起因":"a","经过":"只有一步","结果":"b"}')
  assert.equal(r.ok, true)
  assert.deepEqual(r.事件.经过, ['只有一步'])
})

test('解析事件JSON：没有事件名算失败', () => {
  assert.equal(解析事件JSON('{"起因":"a","结果":"b"}').ok, false)
})

test('解析事件JSON：完全不是 JSON 要失败，不抛错', () => {
  for (const 坏 of ['', '模型胡说八道', '[]', 'null', '{}']) {
    assert.doesNotThrow(() => 解析事件JSON(坏))
    assert.equal(解析事件JSON(坏).ok, false, `${JSON.stringify(坏)} 该解析失败`)
  }
})

test('起个事件名：去掉角色旁白', () => {
  const 名 = 起个事件名([], { 内容: '（晃了晃尾巴，笑了一下）谁都眼熟，谁也认不出' }, { 内容: '就这样吧' })
  assert.ok(!名.startsWith('（'), `事件名不该带旁白：${名}`)
})
