/**
 * 分层库容量上限的测试。
 *
 * 背景（2026-11-04）：分层库原来只增不减。按实测密度（10 天 8428 条）
 * 一年就是 30 万条，而检索要全量建索引 —— 实测 10 万条 1.3 秒、
 * 20 万条 2.6 秒。所以加了上限，超出后按「层级 > 时间 > 是否被检索过」
 * 淘汰。
 *
 * 这里守住三件容易做错的事：
 *   1. 淘汰顺序不能只看时间 —— 那会把一年前的核心记忆清光，只留最近闲聊，
 *      正好和记忆检索的目的相反
 *   2. 被检索过的要优先保留 —— 说明它对人有意义
 *   3. 不超限时一条都不能动（这是「默认行为不变」的保证）
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'

import { 裁剪到上限, 默认容量上限 } from '../lib/recall-ingest.js'

/** 造一条扁平条目 */
function 条 ({ 指纹, 层级, 日期, lastHit }) {
  return {
    来源: 'private',
    日期,
    时间: '12:00:00',
    摘要: `占位 ${指纹}`,
    层级,
    指纹,
    ...(lastHit ? { lastHit } : {}),
  }
}

test('默认上限是个合理的数（5 万，实测检索 0.7 秒）', () => {
  assert.equal(默认容量上限, 50000)
})

test('没超上限时一条都不动，且保持原顺序', () => {
  const 原 = [
    条({ 指纹: 'a', 层级: 0, 日期: '2026-11-01' }),
    条({ 指纹: 'b', 层级: 2, 日期: '2026-11-02' }),
    条({ 指纹: 'c', 层级: 1, 日期: '2026-11-03' }),
  ]
  const r = 裁剪到上限(原, 5)
  assert.equal(r.淘汰, 0)
  assert.deepEqual(r.保留.map((x) => x.指纹), ['a', 'b', 'c'], '没超限时不该重排')
  assert.deepEqual(r.保留, 原, '没超限时返回的应该是原样内容')
})

test('上限 <= 0 表示不限制', () => {
  const 原 = Array.from({ length: 10 }, (_, i) =>
    条({ 指纹: String(i), 层级: 0, 日期: '2026-11-01' }))
  for (const 限 of [0, -1, NaN, undefined]) {
    const r = 裁剪到上限(原, 限)
    assert.equal(r.淘汰, 0, `上限 ${String(限)} 不该淘汰任何条目`)
    assert.equal(r.保留.length, 10)
  }
})

test('核心记忆比新闲聊优先 —— 不能把久远但重要的事清光', () => {
  // 3 条旧核心 + 4 条新闲聊，上限 5
  const 原 = [
    条({ 指纹: '核心1', 层级: 2, 日期: '2026-01-01' }),
    条({ 指纹: '核心2', 层级: 2, 日期: '2026-02-01' }),
    条({ 指纹: '核心3', 层级: 2, 日期: '2026-03-01' }),
    条({ 指纹: '闲聊1', 层级: 0, 日期: '2026-11-01' }),
    条({ 指纹: '闲聊2', 层级: 0, 日期: '2026-11-02' }),
    条({ 指纹: '闲聊3', 层级: 0, 日期: '2026-11-03' }),
    条({ 指纹: '闲聊4', 层级: 0, 日期: '2026-11-04' }),
  ]
  const r = 裁剪到上限(原, 5)
  assert.equal(r.保留.length, 5)
  assert.equal(r.淘汰, 2)

  const 留下 = new Set(r.保留.map((x) => x.指纹))
  for (const k of ['核心1', '核心2', '核心3']) {
    assert.ok(留下.has(k), `${k} 是核心记忆，不该被淘汰`)
  }
  // 4 条闲聊只能留 2 条，且必须是最新的两条
  assert.ok(留下.has('闲聊4') && 留下.has('闲聊3'), '同样层级时该留最新的')
  assert.ok(!留下.has('闲聊1') && !留下.has('闲聊2'), '最老的闲聊该先被淘汰')
})

test('同层级同时间时，被检索过的优先保留', () => {
  const 原 = [
    条({ 指纹: '没被搜过', 层级: 1, 日期: '2026-11-01' }),
    条({ 指纹: '被搜过', 层级: 1, 日期: '2026-11-01', lastHit: '2026-11-03T10:00:00.000Z' }),
  ]
  const r = 裁剪到上限(原, 1)
  assert.equal(r.保留.length, 1)
  assert.equal(r.保留[0].指纹, '被搜过', '被检索过的说明对人有意义，该优先留')
})

test('同层级同检索状态时，新的优先保留', () => {
  const 原 = [
    条({ 指纹: '旧', 层级: 1, 日期: '2026-10-01' }),
    条({ 指纹: '新', 层级: 1, 日期: '2026-11-01' }),
  ]
  const r = 裁剪到上限(原, 1)
  assert.equal(r.保留[0].指纹, '新')
})

test('层级优先级高于时间：核心再老也赢过最新的闲聊', () => {
  const 原 = [
    条({ 指纹: '2020核心', 层级: 2, 日期: '2020-01-01' }),
    条({ 指纹: '2026闲聊', 层级: 0, 日期: '2026-11-04' }),
  ]
  const r = 裁剪到上限(原, 1)
  assert.equal(r.保留[0].指纹, '2020核心')
})

test('缺字段的条目不会让排序炸掉', () => {
  const 原 = [
    { 指纹: '全缺' },
    { 指纹: '只有日期', 日期: '2026-11-01' },
    条({ 指纹: '正常', 层级: 1, 日期: '2026-11-02' }),
  ]
  assert.doesNotThrow(() => 裁剪到上限(原, 2))
  const r = 裁剪到上限(原, 2)
  assert.equal(r.保留.length, 2)
  assert.equal(r.淘汰, 1)
})

test('空数组和非法输入都要安全返回', () => {
  for (const 入 of [[], null, undefined, 'not-array']) {
    const r = 裁剪到上限(入, 10)
    assert.deepEqual(r.保留, [])
    assert.equal(r.淘汰, 0)
  }
})

test('大量条目裁剪后数量精确等于上限', () => {
  const 原 = Array.from({ length: 1000 }, (_, i) =>
    条({ 指纹: `f${i}`, 层级: i % 3, 日期: `2026-01-${String((i % 28) + 1).padStart(2, '0')}` }))
  const r = 裁剪到上限(原, 300)
  assert.equal(r.保留.length, 300)
  assert.equal(r.淘汰, 700)
})
