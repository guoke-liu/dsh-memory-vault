// ============================================================================
// recall-events-store.js —— 事件层的组装与存取
//
// 【事件从哪来：三级来源，优先级从高到低】
//
//   ① 鱼写的日记（最高）
//      鱼（模型）每天写的日记本身就是一个一个「事」：有标题、有正文、有情绪判断。
//      实测对比（2026-11-04，同一段聊天）：
//        规则提炼：【爱你 → 嗯，那就这样】起因：爱你 / 结果：嗯，那就这样
//        鱼写的：【光顾着回话】聊了一整天，晚上她问一句「今天的日记写了吗」，
//                我一翻，本子是空的。光顾着回话了，日记一条都没落。
//      信息量差得太远。有日记就用日记，不要用规则凑。
//
//   ② 规则提炼切出的事件（兜底）
//      日记没有覆盖的时段（实测 11-03 聊天 397 行，日记只有 2 条），
//      用 recall-events.js + recall-event-extract.js 从聊天里切出来。
//
//   ③ 原始聊天分层库（底线）
//      已有能力，永远都在，见 recall-ingest.js。
//
// 【层与层之间怎么避免重复】
//   日记是「按天」写的，粒度粗；规则事件是「按段」切的，粒度细。
//   这里不做精确定位对齐（做不到，也没有必要）——
//   只做一件事：**某天有日记，就不再用规则给那天造事件**。
//   这样同一天的同一件事不会出现两份，而日记没覆盖的日子照样有事件。
//
// 【为什么不存原文】
//   与分层库同一原则：事件是索引，不是存档。原文在 chat/*.txt 与日记库里
//   已经有了。事件只带回查坐标（来源 + 日期 + 时间），需要原话时按坐标去捞。
// ============================================================================

import { readFileSync, writeFileSync, renameSync, chmodSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { 算衰减 } from './recall-decay.js'

/** 事件库格式版本。结构变了就加一，读旧版本按不兼容处理。 */
export const 事件库版本 = 1

/**
 * 从各种时间写法里取出 HH:MM:SS。
 *
 * 为什么单独一个函数：日记的 at 是 ISO 时间戳（2026-11-03T05:35:16.754Z），
 * 聊天原文是 05:35:16。回查坐标必须统一成后者，否则去聊天文件里找
 * `[2026-11-]` 永远找不着 —— 这是实测踩过的坑。
 *
 * @param {string} t
 * @returns {string} HH:MM:SS；取不到返回空串
 */
export function 提时钟 (t) {
  const s = String(t ?? '').trim()
  if (!s) return ''
  // 已经是 HH:MM:SS / HH:MM
  const 短 = s.match(/^(\d{1,2}):(\d{2})(?::(\d{2}))?$/)
  if (短) return `${短[1].padStart(2, '0')}:${短[2]}:${短[3] || '00'}`
  // ISO 时间戳（注意取的是时间部分，不是日期）
  const iso = s.match(/T(\d{2}):(\d{2})(?::(\d{2}))?/)
  if (iso) return `${iso[1]}:${iso[2]}:${iso[3] || '00'}`
  return ''
}

/**
 * 从日记库读某一天、某个来源的日记条目，转成「事件」形状。
 *
 * 日记本来就是「一件一件」记的，所以这里几乎不用加工 ——
 * 这正是它作为事件来源最好的地方：结构天然对得上。
 *
 * @param {string} 日记根 日记库根目录（如 ~/.dsh/xiaoyu-diary）
 * @param {string} 来源 'private' 或 'group-xxxx'
 * @param {string} 日期 YYYY-MM-DD
 * @returns {Array<object>} 事件数组（读不到返回空数组，不抛错）
 */
export function 读日记事件 (日记根, 来源, 日期) {
  if (!日记根 || !来源 || !日期) return []
  // 日记库的目录名用的是 group-<id>，而记忆仓库用的是 group:<id>，两种都要认
  const 候选目录 = [
    来源,
    来源.replace('group:', 'group-'),
    来源.replace('group-', 'group:'),
  ]
  for (const 目录名 of 候选目录) {
    const 文件 = join(日记根, 'entries', 目录名, `${日期}.json`)
    if (!existsSync(文件)) continue
    try {
      const d = JSON.parse(readFileSync(文件, 'utf8'))
      const 条 = Array.isArray(d?.entries) ? d.entries : []
      return 条
        .filter((e) => e && (e.title || e.text))
        .map((e, i) => ({
          事件: String(e.title || e.text || '').slice(0, 60),
          起因: '', // 日记不是按三段式写的，不硬拆
          经过: [],
          // 日记正文就是「发生了什么」—— 放在结果位最合适：
          // 它天然是「这件事最后是怎么说/怎么想通的」
          结果: String(e.text || ''),
          摘要: String(e.text || '').slice(0, 120),
          参与人: [],
          // 起/止 只放时刻（HH:MM:SS），日期单独在 日期 字段里。
          //
          // 实测踩过：这里原来存完整的 e.at（'2026-11-03T00:59:38.756Z'），
          // 结果事件标题显示成「2026-11-03T00:59:38.756Z-2026-11-03T00:59:38.756Z」——
          // 日期重复了两遍还带时区后缀。日期归日期、时刻归时刻。
          起: 提时钟(e.at),
          止: 提时钟(e.at),
          日期,
          来源,
          条数: 1,
          提炼方式: '日记',
          类型: '日记',
          标签: Array.isArray(e.tags) ? e.tags.slice(0, 8) : [],
          日记id: String(e.id || `${日期}-${i}`),
          // ⚠️ 日记事件的回查坐标**不能带时间**。
          //
          // 这里踩过两次（2026-11-04）：
          //   第一次直接把 e.at（'2026-11-03T05:35:16.754Z'）塞进「时间」，
          //   回查按 slice(0,8) 得到 '2026-11-'，当然找不到。
          //   第二次改成取 HH:MM:SS 得到 '05:35:16' —— 还是找不到，
          //   因为去聊天文件里一查，11-03 私聊根本没有 05:35 那一段。
          //
          // 原因：日记条目上的 at 是**这条日记被写下来的时间**，
          // 不是「那句话在聊天里出现的时间」。人（和鱼）常常是事后补记，
          // 两个时间对不上是常态，硬拿它去定位等于给出一个错误的坐标 ——
          // 比没有坐标更糟：调用方会以为「回查失败，原文丢了」。
          //
          // 正确做法：日记事件的回查范围是**那天那个来源的全部聊天**。
          // 时间留空，调用方按「来源 + 日期」去翻那天的聊天文件。
          回查: [{
            来源,
            日期,
            时间: '',
            日记id: String(e.id || ''),
            // 写下来的时刻单独存，仅作展示用途，不当作定位依据
            写入时刻: 提时钟(e.at),
          }],
        }))
    } catch {
      // 单天的文件坏了不该让整轮失败 —— 那天就退回规则提炼
      continue
    }
  }
  return []
}

/**
 * 组装事件库：遍历分层库里的日期与来源，按三级优先级取事件。
 *
 * @param {object} 选项
 * @param {string} 选项.日记根 日记库根（可空 —— 空了就全走规则提炼）
 * @param {Array<{来源:string, 日期:string}>} 选项.分组们 分层库里有哪些「来源+日期」
 * @param {Function} 选项.造规则事件 (来源, 日期) => Array<事件> 给没日记的日子造事件
 * @param {Function} [选项.造话题事件] (来源, 日期) => Array<事件>
 *   群聊专用：用话题聚类的产物当事件。
 *
 *   为什么群聊和私聊要分开（2026-11-04 实测）：
 *     群聊按时间切出 66 段「事件」，里面全是
 *       【脸改成小春都没问题 → 有那个同款头环就可以了】
 *     这种两句话拼起来、没有起承转合的碎片 —— 因为群里本来就不是一件事一件事地聊。
 *     改成按话题段产出，10 个话题每个都带明确的时间范围和人，
 *     【日记】10:22-11:35 48 条 4 人 / 【模型】14:47-18:28 28 条 5 人
 *     这才是群里「一次讨论」的真实形状。
 * @param {Function} [选项.日志]
 * @returns {Promise<{ok:boolean, 事件们:Array<object>, 统计:object}>}
 */
export async function 组装事件库 (选项 = {}) {
  const 说 = typeof 选项.日志 === 'function' ? 选项.日志 : () => {}
  const 日记根 = String(选项.日记根 || '')
  const 分组们 = Array.isArray(选项.分组们) ? 选项.分组们 : []
  const 造规则事件 = typeof 选项.造规则事件 === 'function' ? 选项.造规则事件 : () => []
  const 造话题事件 = typeof 选项.造话题事件 === 'function' ? 选项.造话题事件 : null

  const 统计 = { 日记: 0, 规则: 0, 合计: 0, 有日记的天: 0, 用规则的天: 0, 群聊跳过: 0 }
  const 事件们 = []

  // 去重：同一个「来源+日期」只处理一次（分层库分组本来就是唯一的，防一手）
  const seen = new Set()
  for (const g of 分组们) {
    const 来源 = String(g?.来源 || '')
    const 日期 = String(g?.日期 || '')
    if (!来源 || !日期) continue
    const 键 = `${来源}\u0001${日期}`
    if (seen.has(键)) continue
    seen.add(键)

    // ① 先看有没有日记 —— 有就用日记，不再造规则事件
    const 日记事件 = 日记根 ? 读日记事件(日记根, 来源, 日期) : []
    if (日记事件.length > 0) {
      统计.日记 += 日记事件.length
      统计.有日记的天 += 1
      事件们.push(...日记事件)
      continue
    }

    // ② 没日记就用规则提炼。
    //    群聊走话题聚类（造话题事件），私聊走时间切段（造规则事件）——
    //    两者的差别见 造话题事件 参数上的说明。
    统计.用规则的天 += 1
    const 用话题 = 造话题事件 && String(来源).startsWith('group')

    // ⚠️ 群聊有**规模门槛**（主人 2026-11-04 明确要求）：
    //    「群聊本来就是不需要详细记的，小群更是没什么重点可以不用记」
    //
    //    实测各群规模：730783833 平均 1171 行/天、934074044 326 行/天、
    //    859310353 146 行/天。后两个是几百行的零星闲聊，
    //    硬给它们造事件只会产出「【好多（群里 3 条讨论）】」这种没用的东西，
    //    还会挤占检索结果的位置。
    //
    //    所以：一天不到 群聊最少量 条消息的群，**直接不记**。
    //    不是失败，是有意跳过 —— 统计里单独计数，让用户知道为什么没有。
    // ⚠️ 配了模型时，这个门槛要放得很低。
    //
    // 主人 2026-11-04：「交给大模型分辨有没有重点要记的东西」——
    // 既然判断权交给模型，规则就不该再把整天的内容挡在门外。
    // 门槛只在**没配模型**时用来控制质量（规则分不清闲聊，只能按规模砍）。
    // 配了模型时只挡「几乎没人说话」的天（< 20 条），那确实没什么可判的。
    const 有效门槛 = 选项.模型配置 && 选项.模型配置.apiKey ? 20 : Number(选项.群聊最少量)
    if (用话题 && 有效门槛 > 0) {
      const 条数 = typeof 选项.数量探针 === 'function' ? Number(选项.数量探针(来源, 日期)) || 0 : 0
      if (条数 > 0 && 条数 < 有效门槛) {
        统计.群聊跳过 += 1
        说(`群聊跳过：${来源} ${日期} 只有 ${条数} 条，不到门槛 ${有效门槛}`)
        continue
      }
    }

    try {
      const 规则事件 = 用话题 ? 造话题事件(来源, 日期) : 造规则事件(来源, 日期)
      if (Array.isArray(规则事件) && 规则事件.length) {
        统计.规则 += 规则事件.length
        事件们.push(...规则事件)
      }
    } catch (e) {
      说(`规则提炼失败（${来源} ${日期}）：${e?.message || e}`)
    }
  }

  统计.合计 = 事件们.length
  说(`事件库：日记 ${统计.日记} 条（${统计.有日记的天} 天） + 规则 ${统计.规则} 条（${统计.用规则的天} 天） = ${统计.合计} 条`
    + (统计.群聊跳过 > 0 ? `；${统计.群聊跳过} 天群聊因规模太小跳过` : ''))

  return {
    ok: true,
    事件们: 事件们.sort((a, b) => (a.日期 !== b.日期 ? (a.日期 < b.日期 ? 1 : -1) : 0)),
    统计,
  }
}

/**
 * 读事件库文件。没有或格式不对返回空库。
 * @param {string} 文件
 * @returns {{version:number, 生成时间:string, 事件们:Array<object>, 统计:object}}
 */
export function 读事件库 (文件) {
  const 空 = { version: 0, 生成时间: '', 事件们: [], 统计: {} }
  try {
    const v = JSON.parse(readFileSync(文件, 'utf8'))
    if (!v || v.version !== 事件库版本) return 空
    return {
      version: v.version,
      生成时间: String(v.生成时间 || ''),
      事件们: Array.isArray(v.事件们) ? v.事件们 : [],
      统计: v.统计 && typeof v.统计 === 'object' ? v.统计 : {},
    }
  } catch {
    return 空
  }
}

/**
 * 写事件库文件（原子写 + 权限 600）。
 *
 * 事件里带聊天片段，属于隐私数据，权限必须是 600 ——
 * 和 config.json / chat-levels.json 一个待遇。
 *
 * @param {string} 文件
 * @param {{事件们:Array, 统计:object}} 内容
 * @returns {Promise<{ok:boolean, 错误?:string}>}
 */
export async function 写事件库 (文件, 内容) {
  if (!文件) return { ok: false, 错误: '没有文件路径' }
  // 写入时统一裁剪：所有写入口（提炼/救回/遗忘/命中写回）自动受上限约束，
  // 不用每个调用方各管一遍 —— 那样迟早有一个入口忘了管。
  const 上限 = Number.isFinite(Number(内容?.上限)) ? Number(内容.上限) : 默认事件上限
  const 裁 = 裁剪事件(内容?.事件们, 上限)
  // 落盘前剥掉「判断用消息」：那是流水线内部字段，原文不该进索引文件。
  // 剥不干净的话，事件库会重新膨胀成半份聊天记录副本。
  const 净事件们 = 裁.保留.map((e) => {
    if (!e || typeof e !== 'object') return e
    const { 判断用消息, ...其余 } = e
    void 判断用消息
    return 其余
  })
  const 包 = {
    version: 事件库版本,
    生成时间: new Date().toISOString(),
    事件们: 净事件们,
    统计: {
      ...(内容?.统计 && typeof 内容.统计 === 'object' ? 内容.统计 : {}),
      容量上限: 裁.上限,
      本次淘汰: 裁.淘汰,
    },
  }
  const 临时 = `${文件}.tmp-${process.pid}`
  try {
    mkdirSync(dirname(文件), { recursive: true })
    writeFileSync(临时, JSON.stringify(包, null, 0), 'utf8')
    // 先设权限再改名：避免出现「文件已可见但权限还没收」的瞬间
    try { chmodSync(临时, 0o600) } catch { /* 某些文件系统不支持，忽略 */ }
    renameSync(临时, 文件)
    return { ok: true }
  } catch (e) {
    try { renameSync(临时, `${临时}.bad`) } catch { /* 已知失败 */ }
    return { ok: false, 错误: String(e?.message || e) }
  }
}

/**
 * 按条件筛事件 —— 三种检索方式的公共入口。
 *
 * 三种检索（主人 2026-11-04 要求全部支持）：
 *   · 按事件问    「上次修 nginx 那次怎么回事」→ 搜事件名/正文/标签
 *   · 按人问      「宝宝上次说要我做什么」    → 搜参与人
 *   · 按结果问    「那些最后没解决的事」      → 搜结果状态
 *
 * @param {Array<object>} 事件们
 * @param {{查询?:string, 人?:string, 未解决?:boolean, 来源?:string,
 *   起?:string, 止?:string, 上限?:number}} 条件
 * @returns {Array<object>}
 */
export function 筛事件 (事件们, 条件 = {}) {
  const 上限 = Math.max(1, Math.min(Number(条件.上限) || 20, 100))
  const 查 = String(条件.查询 || '').trim().toLowerCase()
  const 人 = String(条件.人 || '').trim()
  const 来源 = String(条件.来源 || '').trim()
  const 起 = String(条件.起 || '').trim()
  const 止 = String(条件.止 || '').trim()

  const 命中 = (Array.isArray(事件们) ? 事件们 : []).filter((e) => {
    if (!e) return false
    // 来源过滤：'private' / 'group:123' / 空=全部
    if (来源 && String(e.来源 || '') !== 来源) return false
    // 日期范围：闭区间
    if (起 && String(e.日期 || '') < 起) return false
    if (止 && String(e.日期 || '') > 止) return false
    // 按人：参与人里包含这个人
    if (人 && !(Array.isArray(e.参与人) ? e.参与人 : []).some((p) => String(p).includes(人))) return false
    // 按结果状态：未解决 = 结果里出现「未解决」或结果为空
    if (条件.未解决 === true) {
      const 结果 = String(e.结果 || '')
      const 像未解决 = !结果.trim() || /未解决|没解决|还没|待定|之后再|下次再|没搞定|没修好/.test(结果)
      if (!像未解决) return false
    }
    // 按查询：事件名 / 结果 / 摘要 / 标签 / 起因 / 经过 任意命中
    if (查) {
      const 池 = [
        String(e.事件 || ''),
        String(e.起因 || ''),
        String(e.结果 || ''),
        String(e.摘要 || ''),
        ...(Array.isArray(e.经过) ? e.经过 : []),
        ...(Array.isArray(e.标签) ? e.标签 : []),
      ].join(' ').toLowerCase()
      if (!池.includes(查)) return false
    }
    return true
  })

  // ── 时间衰减：过久没人提起的事件不再返回 ──────────────────────────
  //
  // 主人 2026-11-04：「事件层也加上时间权重，过久没人提起就不检索」。
  //
  // 复用分层库那套衰减规则（lib/recall-decay.js），保证两层行为一致：
  //   · 每月降一层，最多 12 层（1.0 → 0.3）
  //   · 被检索过 → lastHit 更新 → 回到第 1 层
  //   · 满 12 层（360 天）且再无检索 → 归档，不再返回
  //
  // 和分层库的区别只在于「参照时间」：事件的参照是它自己的时间段起点
  // （聊天发生于何时），而不是入索引的时间 —— 否则一条三年前的聊天
  // 今天刚提炼出来就会显示成「刚刚」，衰减永远不生效。
  //
  // ⚠️ 第 12 层不叫「归档」叫「遗忘层」，而且**不能被悄悄丢掉**。
  //
  // 最初写的是 `if (衰.归档) continue` —— 满 12 层直接不返回。
  // 主人 2026-11-04 指出这不对：「第12层命名为遗忘层，用户可直接看到
  // 遗忘层来选择要不要彻底遗忘这个事件」。
  //
  // 也就是说：遗忘层是**可见的一层**，不是黑洞。用户要能看到
  // 「这些事快被我忘了」，然后自己决定是救回来还是彻底删掉。
  // 直接过滤掉等于替用户做了决定，而且他连知道的机会都没有。
  //
  // 所以现在：超过阈值的进「遗忘层」，默认不在正常检索里出现，
  // 但用 只看遗忘层 就能看见；要救回来就检索它（lastHit 更新，回第 1 层），
  // 要彻底遗忘由用户显式删除。
  const 现在 = Number.isFinite(Number(条件.现在)) ? Number(条件.现在) : Date.now()
  const 只看遗忘层 = 条件.只看遗忘层 === true
  const 活跃 = []
  const 遗忘 = []
  for (const e of 命中) {
    const 参照 = 取事件时间(e)
    const 衰 = 算衰减({ lastHit: e.lastHit, at: 参照 }, 现在)
    const 标记 = { ...e, 衰减层级: 衰.层级, 衰减系数: 衰.系数, 遗忘层: 衰.归档 === true }
    if (衰.归档) 遗忘.push(标记)
    else 活跃.push(标记)
  }

  // 只看遗忘层：只返回快被忘掉的，按最久的排前面
  if (只看遗忘层) {
    return 遗忘
      .sort((a, b) => String(a.日期 || '').localeCompare(String(b.日期 || '')))
      .slice(0, 上限)
  }

  // 排序：先按「日期倒序 × 衰减系数」加权，再让日记事件略占优。
  //
  // 为什么不纯按日期：三个月前的日记和昨天群里的闲聊，
  // 前者更值得翻出来。权重 = 日期分 × 衰减系数，让两边都起作用。
  // 正常检索只在「活跃」里排（遗忘层单独看）
  // 印象分：参与这件事的人里，有没有「跟鱼关系密切」的
  //
  // 主人 2026-11-04：「太好的太坏的都会影响优先级」。
  // 所以好话坏话都往上抬 —— 印象分衡量的是「跟鱼的互动强度」，
  // 不是「好感净额」。天天骂鱼的人和天天夸鱼的人同样值得翻出来。
  //
  // ⚠️ 加成幅度必须小（最多 0.15，见 印象加成 的注释）。
  // 印象分是锦上添花，不能盖过「这件事重不重要」这个主判据 ——
  // 否则一个跟鱼互动多的人随便说句话，就能压掉一条极重要的日记。
  const 印象表 = 条件.印象表 && typeof 条件.印象表 === 'object' ? 条件.印象表 : null
  const 取加成 = (e) => {
    if (!印象表) return 0
    let 最高 = 0
    for (const p of (Array.isArray(e.参与人) ? e.参与人 : [])) {
      const 记 = 印象表[String(p)]
      if (!记) continue
      const 加 = Math.min(0.05 * (Number(记.分数) || 0), 0.15)
      if (加 > 最高) 最高 = 加
    }
    return 最高
  }

  return 活跃
    .sort((a, b) => {
      const 分 = (e) => {
        // 日期越近分越高（0..1），再乘衰减系数
        const 天 = 距今天数(e, 现在)
        const 新近 = Number.isFinite(天) ? Math.max(0, 1 - 天 / 365) : 0
        const 质 = e.提炼方式 === '日记' ? 0.15 : 0 // 日记是人（鱼）筛过的，略占优
        return (新近 + 质) * Number(e.衰减系数 ?? 1) + 取加成(e)
      }
      return 分(b) - 分(a)
    })
    .slice(0, 上限)
}

/**
 * 取事件的参照时间（用于算衰减）。
 *
 * 优先用「事件发生的时间」而不是「入索引的时间」：
 * 一条去年的聊天今天刚被提炼，它仍然是去年的旧事，
 * 不该因为「刚入库」就满权。这是事件层和分层库最大的差别。
 *
 * @param {object} e
 * @returns {string}
 */
function 取事件时间 (e) {
  const 日 = String(e?.日期 || '').trim()
  const 时 = String(e?.起 || '').trim()
  if (!日) return ''
  // 起可能是 HH:MM:SS 或 ISO 时间戳，两种都认
  if (!时) return 日
  if (/^\d{1,2}:\d{2}/.test(时)) return `${日}T${时.length === 5 ? 时 + ':00' : 时}`
  return 时
}

/** 事件距今天数；算不出返回 NaN */
function 距今天数 (e, 现在) {
  const t = Date.parse(取事件时间(e))
  if (!Number.isFinite(t)) return NaN
  return (现在 - t) / 86400000
}

/**
 * 一次性把「聊天 → 事件库」跑完（工具层调这个）。
 *
 * 内部按来源分派：私聊走时间切段 + 规则提炼，群聊走话题聚类。
 * 有日记的日子无论私聊群聊都直接用日记，不造规则事件。
 *
 * @param {object} 选项
 * @param {string} 选项.仓库根 记忆仓库根（chat/ 的上一层）
 * @param {string} 选项.日记根 日记库根（可空）
 * @param {Function} 选项.读分层库 async () => { 分组: [...] } 用来知道有哪些「来源+日期」
 * @param {Function} [选项.日志]
 * @returns {Promise<{ok:boolean, 文件?:string, 统计?:object, 事件们?:Array, 错误?:string}>}
 */
export async function 跑事件提炼 (选项 = {}) {
  const 说 = typeof 选项.日志 === 'function' ? 选项.日志 : () => {}
  const 仓库根 = String(选项.仓库根 || '')
  const 日记根 = String(选项.日记根 || '')
  const 读分层 = typeof 选项.读分层库 === 'function' ? 选项.读分层库 : null
  if (!仓库根) return { ok: false, 错误: '缺少仓库根' }
  if (!读分层) return { ok: false, 错误: '缺少读分层库函数' }

  let 库
  try {
    库 = await 读分层()
  } catch (e) {
    return { ok: false, 错误: `读分层库失败：${e?.message || e}` }
  }

  // 分层库的分组形状：{ 来源, 日期, 条目[] }
  const 分组们 = (Array.isArray(库?.分组) ? 库.分组 : [])
    .map((g) => ({ 来源: String(g?.来源 || ''), 日期: String(g?.日期 || '') }))
    .filter((g) => g.来源 && g.日期)
  if (分组们.length === 0) {
    return { ok: false, 错误: '分层库里没有可分组的聊天（先跑一次 memory_score_chats）' }
  }

  // 按需加载：避免本模块在别的场景被引用时也拖进一堆依赖
  const [{ 切事件, 事件价值分 }, { 规则提炼 }] = await Promise.all([
    import('./recall-events.js'),
    import('./recall-event-extract.js'),
  ])

  const { readFileSync, existsSync } = await import('node:fs')
  const { join } = await import('node:path')

  /** 读某天的聊天原文 */
  const 读那天的 = (来源, 日期) => {
    // 记忆仓库的目录名：private / group/<id>
    const 目录 = String(来源).startsWith('group:')
      ? join(仓库根, 'chat', 'group', String(来源).slice(6))
      : join(仓库根, 'chat', 'private')
    const 文件 = join(目录, `${日期}.txt`)
    if (!existsSync(文件)) return []
    const LINE = /^\[(\d{2}:\d{2}:\d{2})\]\s+([^(]+)\((p\d+)\):\s*(.*)$/
    const 出 = []
    for (const 行 of readFileSync(文件, 'utf8').split('\n')) {
      const t = 行.replace(/\r$/, '')
      if (!t.trim()) continue
      const m = t.match(LINE)
      if (!m) continue
      出.push({ 时间: m[1], 昵称: m[2].trim(), pid: m[3], 内容: m[4], 日期, 来源 })
    }
    return 出
  }

  // 私聊：时间切段 → 价值分过滤 → 规则提炼
  const 造规则事件 = (来源, 日期) => {
    const 消息 = 读那天的(来源, 日期)
    return 切事件(消息)
      .filter((s) => 事件价值分(s) >= 0.5)
      .map((s) => ({ ...规则提炼(s), 来源, 日期 }))
  }

  // 群聊话题要异步 import，所以这里先跑一遍收集待办
  const { 聚话题, 话题价值分 } = await import('./recall-topics.js')
  const 造话题 = (来源, 日期) => {
    const 消息 = 读那天的(来源, 日期)
    if (消息.length === 0) return []

    // ⚠️ 门槛要跟着数据量走，不能写死。
    //
    // 实测踩过（2026-11-04）：固定「最少出现 5 次」，结果 19 个「来源+日期」里
    // 有 8 个一条事件都没产出 —— 全是不太活跃的群（一天几十条到两百多条），
    // 任何词都到不了 5 次。那些天的聊天等于白存，检索永远搜不到。
    //
    // 现在的规则：小群放宽，大群收紧。
    //   消息 < 100  → 出现 2 次就够（不然小群一个话题都没有）
    //   消息 < 500  → 3 次
    //   其余        → 5 次（保持原样，避免大群里碎词成话题）
    const 最少次数 = 消息.length < 100 ? 2 : 消息.length < 500 ? 3 : 5

    // 这里只做**粗筛**（价值分 < 0.2 的一定是纯寒暄，连模型都不用问），
    // 真正的「值不值得记」由主流程里的模型判断决定 ——
    // 见 lib/recall-worth.js 和 跑事件提炼 里的 批量判断。
    //
    // 为什么粗筛线定这么低（0.2 而不是原来的 0.5）：
    // 模型判断要花钱，但比「把真重点当闲聊丢掉」便宜得多。
    // 实测中群的话题分大多在 0.35-0.5，用 0.5 会全部挡掉，
    // 模型根本没机会看到它们 —— 那等于没有交给模型判断。
    const 话题们 = 聚话题(消息, { 最少次数, 最多话题: 8 })
      .map((t) => ({ ...t, 规则分: 话题价值分(t) }))
      .filter((t) => t.规则分 >= 0.2)

    // ── 额外：单独抽「@ 别人家机器人」的消息 ────────────────────────
    //
    // 主人 2026-11-04：「艾特别人机器人的则由大模型筛选的时候打分」。
    //
    // 实测踩过：`@龙娘 你个废物`「@龙娘 滚开」这类话抽不出任何话题词
    // （「滚开」「别烦我」都不在词频表里），话题聚类一条都聚不出来 ——
    // 于是「交给模型判断」这条链路永远收不到数据。
    //
    // 这类消息本来就短、没有话题性，但不该因此被丢掉：它们是「有人在对
    // 别人家的机器人发火」，恰恰是印象分要抓的东西。
    // 所以在这里单独捞出来，按天聚成一段交给模型。
    const 别人机器人词 = ['龙娘', 'grok', 'Gemini', 'gemini', 'claude', 'Claude', 'GPT', '限时接入', '酱酱', '雪雪']
    const 机器人艾特消息 = 消息.filter((m) => {
      const 内容 = String(m?.内容 || '')
      return /@/.test(内容) && 别人机器人词.some((w) => 内容.includes(w))
    })
    if (机器人艾特消息.length >= 2) {
      const 首 = 机器人艾特消息[0]
      const 末 = 机器人艾特消息[机器人艾特消息.length - 1]
      话题们.push({
        话题: '@机器人',
        消息: 机器人艾特消息,
        消息数: 机器人艾特消息.length,
        起: String(首?.时间 || ''),
        止: String(末?.时间 || ''),
        // 规则分故意给 0：这类内容规则判不了，必须由模型判断
        规则分: 0,
        人数: new Set(机器人艾特消息.map((m) => String(m?.昵称 || ''))).size,
      })
    }
    return 话题们
      .map((t) => ({
        // 事件名 = 话题词 + 一句话点出这是群里的讨论
        事件: `${t.话题}（群里 ${t.消息数} 条讨论）`,
        起因: '',
        // 经过取最早的两条，让人看出讨论从哪起头
        经过: t.消息.slice(0, 2).map((m) => String(m?.内容 || '').slice(0, 60)),
        结果: String(t.消息[t.消息.length - 1]?.内容 || '').slice(0, 120),
        摘要: t.消息.map((m) => m.内容).join(' ').slice(0, 120),
        参与人: [...new Set(t.消息.map((m) => String(m?.昵称 || '')).filter(Boolean))],
        起: t.起,
        止: t.止,
        日期,
        来源,
        条数: t.消息数,
        提炼方式: '话题',
        类型: '话题',
        标签: [t.话题],
        // 回查坐标 + 原文片段。
        //
        // ⚠️ 这里必须带内容，不能只带坐标。
        // 实测踩过（2026-11-04）：原来只存 时间/昵称/pid，结果模型判断
        // 拿到的是空正文 —— 完全没依据的盲目判断，而且日志显示「判断完成」，
        // 看起来一切正常。测试也没抓出来，因为假模型是按请求体里的关键词返回的，
        // 请求体是空的时候它照样返回一个结果。
        //
        // 为什么要带内容而不是去读原文：模型判断要逐段看内容，
        // 每次都读文件既慢又容易在文件变动时对不上。这里存的是
        // **这段讨论的原始句子**（截断到 200 字），足够判断有没有重点。
        // ⚠️ 原文片段只在**内存里**带一路（给模型判断用），**不落盘**。
        //
        // 本文件开头写的就是「事件是索引，不是存档」。上一版为了让模型
        // 拿到判断依据，把每段 200 字原文存进了 events.json ——
        // 实测占 23KB/100KB（23%），违背了自己定的原则。
        //
        // 现在的做法：提炼时把原文放在 判断用消息 这个字段里（一趟流水线内有效），
        // 落盘前剥掉（见 写事件库）。下次要判断再从 chat/*.txt 读。
        // 代价是重跑时要多读一次文件，换来的是事件库真的是「索引」。
        判断用消息: t.消息.map((m) => ({
          时间: String(m?.时间 || ''),
          昵称: String(m?.昵称 || ''),
          内容: String(m?.内容 || '').slice(0, 200),
        })),
        回查: t.消息.map((m) => ({
          时间: String(m?.时间 || ''),
          昵称: String(m?.昵称 || ''),
          pid: String(m?.pid || ''),
        })),
      }))
  }
  // 群聊规模门槛：一天不足这么多条消息的群，直接不记。
  //
  // 默认 800 的依据（实测各群规模 + 实测话题质量）：
  //   730783833  1171 行/天  ← 大群，话题有内容（【日记】【模型】【gemini】）
  //   934074044   326 行/天  ← 话题全是闲聊：【米饭】【吃饭】【笑话】【尾巴】
  //   859310353   146 行/天  ← 话题全是闲聊
  //
  // 一开始定的是 300，结果 934074044 刚好在线上，产出 24 条「米饭」「笑话」
  // 这种话题 —— 它们会挤占检索结果的位置。门槛必须定在「话题有内容」
  // 和「话题是闲聊」之间的那条线上，实测下来是 800 左右。
  //
  // 主人原话：「群聊本来就是不需要详细记的，小群更是没什么重点可以不用记」。
  //
  // 注意这是**按天**判断，不是按整个群的平均值 ——
  // 中群 934074044 平均 326 行/天，但它某一天有 698 行，
  // 按平均值会漏掉那种"那天特别热闹"的情况，产出「米饭」「游戏」这种话题。
  const 群聊最少量 = Number.isFinite(Number(选项.群聊最少量)) ? Number(选项.群聊最少量) : 800

  const 结果 = await 组装事件库({
    日记根,
    分组们,
    造规则事件,
    造话题事件: 造话题,
    群聊最少量,
    // 模型配置要传进去：门槛高低取决于「有没有模型来判值不值得记」
    模型配置: 选项.模型配置,
    数量探针: (来源, 日期) => 读那天的(来源, 日期).length,
    日志: 说,
  })

  // ── 模型判断：纯闲聊的不要记 ──────────────────────────────────────
  //
  // 主人 2026-11-04：「交给大模型分辨有没有重点要记的东西，纯闲聊的话不要记」。
  //
  // 只判断规则产出的那部分（话题 + 规则提炼），**不动日记事件** ——
  // 日记是鱼自己决定写的，本来就经过了它的判断，没必要再让另一个模型
  // 复核一遍（问了也可能不同意，反而把该记的删了）。
  //
  // 没配模型时整段跳过，行为与之前完全一致。
  let 事件们 = 结果.事件们
  let 判断统计 = null
  if (选项.模型配置 && 选项.模型配置.apiKey) {
    const { 批量判断 } = await import('./recall-worth.js')
    const { 读账本文件, 写账本, 已投喂, 取结论, 批量记投喂, 事件身份 } = await import('./recall-fed.js')

    // ⚠️ 事件判断也要记账，否则每跑一次就重花一次钱。
    //
    // 实测踩过（2026-11-04）：事件层原来完全没接投喂账本 ——
    // 每跑一次 memory_build_events，所有话题都会重新送模型判断一遍。
    // 这正是「避免反复投喂」要防的事，却发生在另一条链路上。
    //
    // 账本单独一个文件：两者的身份键不同（消息指纹 vs 事件身份），
    // 混在一本账里会互相干扰。
    const 账文件 = join(dirname(String(选项.输出文件 || join(仓库根, 'events.json'))), 'events-feed.json')
    const 账本 = await 读账本文件(账文件)
    // ⚠️ 原事件要挂在**段**上，不能挂在候选对象上 ——
    // 批量判断 返回的是 { 段, 判断 }，段里才有原事件的引用。
    // 挂在候选对象上会拿不到，实测报过 undefined。
    const 待判 = 事件们
      .filter((e) => e.提炼方式 !== '日记')
      .map((e) => ({
        段: { 消息: 事件消息(e), ...e, 原事件: e },
        规则分: Number(e.规则分 ?? 0.5),
      }))
    const 判 = await 批量判断(待判, 选项.模型配置, {
      粗筛线: 0.2,
      并发: Number(选项.并发) || 3,
      日志: 说,
      指纹: 事件身份,
      // 判过的跳过，不重复花钱
      已判断: (指纹) => 已投喂(账本, 指纹, '判断'),
      // 判完立刻记账：只要问过模型就花了钱，不管结论是记还是不记
      每段判完: (指纹, 判定) => 批量记投喂(账本, [指纹], '判断', { 值得记: 判定?.值得记 === true }),
      // 重跑时用上次的结论还原去留（只记「判过」不记「判成什么」，
      // 那些事件会凭空消失 —— 实测踩过，事件数从 1 变 0）
      取上次结论: (指纹) => 取结论(账本, 指纹, '判断'),
      // 含 @ 别人家机器人的段，规则分再低也不能粗筛掉 ——
      // 规则判不了这类内容才要交给模型，不能被规则先挡在门外。
      含机器人艾特: (段) => {
        const 文本 = (Array.isArray(段?.判断用消息) ? 段.判断用消息 : (段?.消息 || []))
          .map((m) => String(m?.内容 || '')).join(' ')
        return /@/.test(文本) && /龙娘|grok|Gemini|claude|GPT|限时接入|雪雪|酱酱/.test(文本)
      },
    })
    // 跑完落盘。中途崩溃只有最后一批没记上，下次会重判一次 ——
    // 这点重复花销可以接受，比「每次都全量重判」好得多。
    await 写账本(账文件, 账本)
    判断统计 = 判.统计
    // 判断为「值得记」的留下；日记事件原样保留。
    //
    // ⚠️ 不能用对象引用比较：事件对象在 组装事件库 里已经被复制过一轮
    // （组装时 push 进去的和这里拿到的是不同引用），用 Set<对象> 比永远不相等，
    // 表现就是「日志说保留了 1 段，结果却是 0 条」。实测踩过。
    // 改用「来源+日期+事件名+起始时间」当作身份键。
    const 身份 = (e) => `${e.来源}${e.日期}${e.事件}${e.起}`
    const 通过 = new Set(判.保留.map((x) => 身份(x.段.原事件)))
    事件们 = 事件们.filter((e) => e.提炼方式 === '日记' || 通过.has(身份(e)))
    // ── 机器人态度：同一次调用顺带拿到的，不额外花钱 ────────────────
    //
    // 主人 2026-11-04：「喂聊天记录给大模型的时候直接打分不要二次投喂了」。
    //
    // 上一版我把「@ 别人家机器人」的态度做成了独立的一次模型调用 ——
    // 同一段聊天被问了两次，白花一倍的钱。现在这个字段跟着
    // 「值不值得记」一起回来，一次调用两个结果。
    const 态度表 = new Map()
    for (const x of 判.保留) {
      if (x.判断 && x.判断.机器人态度 && x.判断.机器人态度 !== '中性') {
        态度表.set(身份(x.段.原事件), { 态度: x.判断.机器人态度, 理由: x.判断.态度理由 || '' })
      }
    }
    if (态度表.size > 0) {
      事件们 = 事件们.map((e) => {
        const a = 态度表.get(身份(e))
        return a ? { ...e, 机器人态度: a.态度, 态度理由: a.理由 } : e
      })
    }

    说(`模型判断：${判.统计.送模型} 段送模型，判为闲聊 ${判.统计.模型判闲聊} 段，最终 ${事件们.length} 条事件`
      + (态度表.size > 0 ? `；其中 ${态度表.size} 段带机器人态度（同一次调用顺带判断的，没多花钱）` : ''))
  }

  /** 从事件里还原出「消息」形状，供模型判断用 */
  /**
   * 从事件里还原出「消息」形状，供模型判断用。
   *
   * 取数优先级：消息（话题事件带原文）> 三段式 > 摘要 > 回查。
   *
   * ⚠️ 这里的顺序是实测调出来的：话题事件的「经过」只有两条（开头两句），
   * 拿它去判断「整段有没有重点」信息量不足；而 消息 里是这段讨论的
   * 全部原始句子（截断到 200 字），判断依据最完整。
   */
  function 事件消息 (e) {
    // ① 话题事件：带的是 判断用消息（内存里的那份，不落盘）
    const 源数组 = Array.isArray(e.判断用消息) ? e.判断用消息 : (Array.isArray(e.消息) ? e.消息 : [])
    if (源数组.length) {
      const 有内容 = 源数组.filter((m) => String(m?.内容 || '').trim())
      if (有内容.length) return 有内容.map((m) => ({ 内容: String(m.内容).slice(0, 200), 昵称: String(m.昵称 || '') }))
    }
    // ② 三段式（日记/规则事件）
    const 行们 = [
      ...(e.起因 ? [e.起因] : []),
      ...(Array.isArray(e.经过) ? e.经过 : []),
      ...(e.结果 ? [e.结果] : []),
    ].filter((t) => String(t || '').trim())
    if (行们.length) return 行们.map((t) => ({ 内容: String(t), 昵称: (e.参与人 || [])[0] || '' }))
    // ③ 摘要
    if (String(e.摘要 || '').trim()) return [{ 内容: String(e.摘要), 昵称: '' }]
    // ④ 回查里万一带了内容
    return Array.isArray(e.回查)
      ? e.回查.slice(0, 20).map((c) => ({ 内容: String(c?.内容 || ''), 昵称: String(c?.昵称 || '') })).filter((m) => m.内容)
      : []
  }

  // 落盘
  const 文件 = String(选项.输出文件 || join(仓库根, 'events.json'))
  const 最终统计 = { ...结果.统计, 合计: 事件们.length }
  if (判断统计) 最终统计.模型判断 = 判断统计
  const w = await 写事件库(文件, { 事件们, 统计: 最终统计 })
  if (!w.ok) return { ok: false, 错误: `写事件库失败：${w.错误}` }

  return { ok: true, 文件, 统计: 最终统计, 事件们 }
}

/**
 * 把「这次被检索到了」写回事件库（更新 lastHit）。
 *
 * 【为什么必须有这一步】
 *
 * 没有它，时间衰减是**不可逆的**：事件一路往下沉，沉到遗忘层就再也回不来，
 * 因为「被提及」这个本该救命的信号从来没被记下。用户明明搜到了、
 * 用了它、也看到了，系统却当他从没问过。
 *
 * 实测踩过（2026-11-04）：事件层检索只返回结果，完全没写回 lastHit，
 * 所以 40 条事件永远停在第 1 层的样子是假象 —— 一个月后它们会一起沉底，
 * 谁都救不回来。
 *
 * 只改 lastHit，不碰任何内容。写库失败只记日志、不影响检索结果 ——
 * 用户来是要答案的，不能因为«记一笔»失败就让他拿不到东西。
 *
 * @param {string} 文件 事件库路径
 * @param {Array<object>} 命中事件 本次返回给用户的事件（要有 来源/日期/事件/起）
 * @param {number} [现在]
 * @returns {Promise<{ok:boolean, 更新:number, 错误?:string}>}
 */
export async function 记事件命中 (文件, 命中事件, 现在 = Date.now()) {
  const 要记 = new Set(
    (Array.isArray(命中事件) ? 命中事件 : [])
      .map((e) => `${e?.来源 ?? ''}\u0001${e?.日期 ?? ''}\u0001${e?.事件 ?? ''}\u0001${e?.起 ?? ''}`)
      .filter(Boolean),
  )
  if (要记.size === 0) return { ok: true, 更新: 0 }

  const 库 = 读事件库(文件)
  if (库.version === 0) return { ok: false, 更新: 0, 错误: '事件库不存在' }

  const 时间 = new Date(Number.isFinite(Number(现在)) ? Number(现在) : Date.now()).toISOString()
  let 更新 = 0
  const 改过 = 库.事件们.map((e) => {
    const 键 = `${e?.来源 ?? ''}\u0001${e?.日期 ?? ''}\u0001${e?.事件 ?? ''}\u0001${e?.起 ?? ''}`
    if (!要记.has(键)) return e
    更新 += 1
    return { ...e, lastHit: 时间 }
  })
  if (更新 === 0) return { ok: true, 更新: 0 }

  const w = await 写事件库(文件, { 事件们: 改过, 统计: 库.统计 })
  if (!w.ok) return { ok: false, 更新: 0, 错误: w.错误 }
  return { ok: true, 更新 }
}

/**
 * 事件库默认容量上限。
 *
 * 为什么要有：事件库原来是只增不减的。按当前密度（7 个来源+日期 → 40 条事件
 * → 100KB），一年约 15MB。空间不算大，但**从不过期清理**意味着三年前的事
 * 还躺在里面参与排序，越攒越乱。
 *
 * 定 2 万条的依据：实测筛一次 5 万条 21ms，2 万条约 8ms ——
 * 远低于人类感知，也留够余量。
 */
export const 默认事件上限 = 20000

/**
 * 按上限裁剪事件，优先保留「还有人提起的、近期的」。
 *
 * 淘汰顺序（先淘汰排后面的）：
 *   1. 进遗忘层的先走 —— 都满 12 层没人提了，留着占地方
 *   2. 被检索过的后走 —— lastHit 存在说明它真被用过
 *   3. 新的后走 —— 同条件下近期信息更有用
 *
 * @param {Array<object>} 事件们
 * @param {number} 上限
 * @param {number} [现在]
 * @returns {{保留:Array<object>, 淘汰:number, 上限:number}}
 */
export function 裁剪事件 (事件们, 上限 = 默认事件上限, 现在 = Date.now()) {
  const 全 = Array.isArray(事件们) ? 事件们 : []
  const 限 = Number(上限)
  if (!Number.isFinite(限) || 限 <= 0 || 全.length <= 限) {
    return { 保留: 全, 淘汰: 0, 上限: Number.isFinite(限) ? 限 : 0 }
  }
  const 优先级 = (e) => {
    const 衰 = 算衰减({ lastHit: e?.lastHit, at: 取事件时间(e) }, 现在)
    const 在遗忘层 = 衰.归档 ? 1 : 0
    const 被用过 = e?.lastHit ? 1 : 0
    const 日 = Number(String(e?.日期 || '').replace(/-/g, '')) || 0
    // 在遗忘层扣一大截 → 最先被淘汰；被用过加一档；日期越大越新
    return 在遗忘层 * -1e13 + 被用过 * 1e12 + 日
  }
  const 排好 = [...全].sort((a, b) => 优先级(b) - 优先级(a))
  return { 保留: 排好.slice(0, 限), 淘汰: 全.length - 限, 上限: 限 }
}

/**
 * 从事件库里彻底删掉指定的事件。
 *
 * 这是「遗忘层」的出口之一：用户在遗忘层看到某件事，决定不要了。
 *
 * 为什么要有确认步骤在**调用方**（不是这里）：这个函数只管删。
 * 工具层负责先说清楚「要删的是哪几条」，用户确认了再调。
 * 一个能静默删数据、还不告诉你删了什么的接口太危险。
 *
 * @param {string} 文件 事件库路径
 * @param {Array<string>} 身份们 要删的事件身份键（见 事件身份）
 * @returns {Promise<{ok:boolean, 删了:number, 没找到:string[], 错误?:string}>}
 */
export async function 彻底遗忘 (文件, 身份们) {
  const 要删 = new Set((Array.isArray(身份们) ? 身份们 : []).filter(Boolean).map(String))
  if (要删.size === 0) return { ok: false, 删了: 0, 没找到: [], 错误: '没有指定要遗忘哪些事件' }

  const 库 = 读事件库(文件)
  if (库.version === 0) return { ok: false, 删了: 0, 没找到: [...要删], 错误: '事件库不存在或版本不兼容' }

  const 命中 = new Set()
  const 留下 = []
  for (const e of 库.事件们) {
    const 键 = `${e?.来源 ?? ''}\u0001${e?.日期 ?? ''}\u0001${e?.事件 ?? ''}\u0001${e?.起 ?? ''}`
    // 也允许用「事件名」直接指定（用户看到的是名字，不是身份键）
    if (要删.has(键) || 要删.has(String(e?.事件 ?? ''))) { 命中.add(要删.has(键) ? 键 : String(e?.事件 ?? '')); continue }
    留下.push(e)
  }

  const 没找到 = [...要删].filter((k) => !命中.has(k))
  if (没找到.length === 要删.size) {
    return { ok: false, 删了: 0, 没找到, 错误: '一条都没匹配上，什么都没删' }
  }

  const w = await 写事件库(文件, { 事件们: 留下, 统计: { ...(库.统计 || {}), 合计: 留下.length } })
  if (!w.ok) return { ok: false, 删了: 0, 没找到, 错误: w.错误 }
  return { ok: true, 删了: 命中.size, 没找到 }
}

/**
 * 把指定事件「救回来」：更新 lastHit 让它回到第 1 层。
 *
 * 这是遗忘层的另一个出口：用户看到某件事差点被忘掉，
 * 觉得还该留着 → 救回来。下次检索时它是满权。
 *
 * 注意：这只改 lastHit，不复制数据、不改内容 ——
 * 救回来和「重新提炼一遍」是两回事，后者会重新花钱。
 *
 * @param {string} 文件 事件库路径
 * @param {Array<string>} 身份们 要救回的事件（身份键或事件名）
 * @param {number} [现在]
 * @returns {Promise<{ok:boolean, 救回:number, 没找到:string[], 错误?:string}>}
 */
export async function 救回 (文件, 身份们, 现在 = Date.now()) {
  const 要救 = new Set((Array.isArray(身份们) ? 身份们 : []).filter(Boolean).map(String))
  if (要救.size === 0) return { ok: false, 救回: 0, 没找到: [], 错误: '没有指定要救回哪些事件' }

  const 库 = 读事件库(文件)
  if (库.version === 0) return { ok: false, 救回: 0, 没找到: [], 错误: '事件库不存在或版本不兼容' }

  const 时间 = new Date(Number.isFinite(Number(现在)) ? Number(现在) : Date.now()).toISOString()
  const 命中 = new Set()
  const 改过 = 库.事件们.map((e) => {
    const 键 = `${e?.来源 ?? ''}\u0001${e?.日期 ?? ''}\u0001${e?.事件 ?? ''}\u0001${e?.起 ?? ''}`
    const 名 = String(e?.事件 ?? '')
    if (要救.has(键) || 要救.has(名)) {
      命中.add(要救.has(键) ? 键 : 名)
      return { ...e, lastHit: 时间 }
    }
    return e
  })

  const 没找到 = [...要救].filter((k) => !命中.has(k))
  if (没找到.length === 要救.size) {
    return { ok: false, 救回: 0, 没找到, 错误: '一条都没匹配上，什么都没改' }
  }

  const w = await 写事件库(文件, { 事件们: 改过, 统计: 库.统计 })
  if (!w.ok) return { ok: false, 救回: 0, 没找到, 错误: w.错误 }
  return { ok: true, 救回: 命中.size, 没找到 }
}
