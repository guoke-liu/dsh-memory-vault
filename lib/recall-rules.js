/** 预设清单，给 UI 下拉框用。 */
export function 预设清单 () {
  return Object.keys(内置预设).map((名) => ({ 名, 说明: 内置预设[名].说明 }))
}

/** 安全编译一个正则：不合法返回 null（不抛）。 */
function 试编译 (源, 标志 = '') {
  try {
    return new RegExp(String(源), 标志)
  } catch {
    return null
  }
}

/**
 * 解析出实际生效的规则。
 *
 * 「基础预设名 + 用户增量」的合成规则：
 *   · 用户没填的字段 → 用预设的
 *   · 用户填了的字段 → **完全替换**预设的（不是叠加）
 *     为什么替换而不是叠加：叠加后用户想删掉预设里的某个词就做不到，
 *     只能不断往回加例外。替换语义清晰：填了就是我的，没填才用预设的。
 *
 * @param {object} 配置 来自 settings 的那几个字段
 * @returns {{话题词: string, 应答词: string, 约定词: string, 播报正则: string[], 有用阈值: number, 核心阈值: number, 预设名: string}}
 */
export function 解析规则 (配置 = {}) {
  const 预设名 = 内置预设[配置.规则预设] ? 配置.规则预设 : '技术向'
  const 预设 = 内置预设[预设名]
  const 取串 = (v, 兜底) => (typeof v === 'string' && v.trim() ? v.trim() : 兜底)
  const 取阈值 = (v, 兜底) => (Number.isFinite(Number(v)) && Number(v) >= 0 ? Number(v) : 兜底)

  let 播报 = 预设.播报正则
  if (Array.isArray(配置.自定义播报正则)) {
    const 洗过 = 配置.自定义播报正则.map((x) => String(x || '').trim()).filter(Boolean)
    if (洗过.length) 播报 = 洗过
  }

  return {
    预设名,
    话题词: 取串(配置.自定义话题词, 预设.话题词),
    应答词: 取串(配置.自定义应答词, 预设.应答词),
    约定词: 取串(配置.自定义约定词, 预设.约定词),
    播报正则: 播报,
    有用阈值: 取阈值(配置.自定义有用阈值, 预设.有用阈值),
    核心阈值: 取阈值(配置.自定义核心阈值, 预设.核心阈值),
  }
}

/**
 * 校验一份规则：每个正则都要能编译，阈值要合理。
 *
 * @param {object} 规则 解析规则() 的输出
 * @returns {{ok:boolean, 错误:string[]}}
 */
export function 校验规则 (规则 = {}) {
  const 错误 = []
  const 验 = (名, 源) => {
    if (!源) { 错误.push(`${名} 不能为空`); return }
    if (!试编译(源)) 错误.push(`${名} 不是合法正则：${String(源).slice(0, 60)}`)
  }
  验('话题词', 规则.话题词)
  验('应答词', 规则.应答词)
  验('约定词', 规则.约定词)
  for (const r of Array.isArray(规则.播报正则) ? 规则.播报正则 : []) {
    if (!试编译(r)) 错误.push(`播报正则 不合法：${String(r).slice(0, 60)}`)
  }
  if (!(Number(规则.有用阈值) >= 0)) 错误.push('有用阈值 必须是非负数')
  if (!(Number(规则.核心阈值) >= 0)) 错误.push('核心阈值 必须是非负数')
  if (Number(规则.核心阈值) < Number(规则.有用阈值)) 错误.push('核心阈值 不能低于有用阈值')
  return { ok: 错误.length === 0, 错误 }
}

/**
 * 从云端拉预设。
 *
 * 【安全边界】这里**只能拉预设**（纯正则字符串 + 阈值），不能拉代码。
 * 拉下来的东西要过三道关才落地：
 *   ① 必须是 JSON，且顶层含 预设 对象
 *   ② 每个预设的字段类型要对（正则必须是字符串，阈值必须是数字）
 *   ③ 每个正则必须能编译（坏正则会让整个筛选崩掉）
 * 任何一关不过 → 整体丢弃，本地保持原样。宁可这次不更新，也不要装进坏规则。
 *
 * 为什么不做成「下载脚本并执行」：那等于把本地执行权限交给远端。
 * 预设是数据，数据可以校验；代码不能。这条边界不开放。
 *
 * @param {string} 地址 http(s) URL
 * @param {{超时毫秒?:number, 允许的域名?: string[]}} [选项]
 * @returns {Promise<{ok:boolean, 预设?:object, 错误?:string}>}
 */
export async function 拉云端预设 (地址, 选项 = {}) {
  const url = String(地址 || '').trim()
  if (!url) return { ok: false, 错误: '未提供地址' }
  if (!/^https?:\/\//i.test(url)) return { ok: false, 错误: '只支持 http/https 地址' }

  // 只允许 https（除非显式放行 http）—— 规则会影响本地数据的分层，
  // 明文传输等于谁都能在中途改。本地回环例外，方便自测。
  const 是本地 = /^https?:\/\/(127\.0\.0\.1|localhost)[:/]/i.test(url)
  if (!/^https:\/\//i.test(url) && !是本地 && 选项.允许明文 !== true) {
    return { ok: false, 错误: '为了安全只支持 https；本地调试可用 http://127.0.0.1' }
  }

  const 超时 = Number(选项.超时毫秒) > 0 ? Number(选项.超时毫秒) : 15000
  const 控制器 = new AbortController()
  const 计时器 = setTimeout(() => 控制器.abort(), 超时)
  try {
    const 响应 = await fetch(url, { signal: 控制器.signal, headers: { Accept: 'application/json' } })
    if (!(响应.status >= 200 && 响应.status < 300)) {
      return { ok: false, 错误: `HTTP ${响应.status}` }
    }
    const 文本 = await 响应.text()
    let 数据 = null
    try { 数据 = JSON.parse(文本) } catch { return { ok: false, 错误: '返回的不是合法 JSON' } }
    if (!数据 || typeof 数据 !== 'object' || !数据.预设 || typeof 数据.预设 !== 'object') {
      return { ok: false, 错误: '返回内容里没有「预设」对象' }
    }

    // 逐条校验，收集通过的和拒绝的
    const 通过 = {}
    const 拒绝 = []
    for (const [名, p] of Object.entries(数据.预设)) {
      if (!p || typeof p !== 'object') { 拒绝.push(`${名}: 不是对象`); continue }
      const 字段错 = []
      for (const k of ['话题词', '应答词', '约定词']) {
        if (typeof p[k] !== 'string' || !p[k].trim()) 字段错.push(`${k} 缺失或非字符串`)
      }
      for (const k of ['有用阈值', '核心阈值']) {
        if (!Number.isFinite(Number(p[k]))) 字段错.push(`${k} 不是数字`)
      }
      const 播报 = Array.isArray(p.播报正则) ? p.播报正则 : []
      const 验 = 校验规则({
        话题词: p.话题词, 应答词: p.应答词, 约定词: p.约定词,
        播报正则: 播报, 有用阈值: p.有用阈值, 核心阈值: p.核心阈值,
      })
      字段错.push(...验.错误)
      if (字段错.length) { 拒绝.push(`${名}: ${字段错.join('；')}`); continue }
      通过[名] = {
        说明: typeof p.说明 === 'string' ? p.说明.slice(0, 200) : '',
        话题词: p.话题词,
        应答词: p.应答词,
        约定词: p.约定词,
        播报正则: 播报.map(String),
        有用阈值: Number(p.有用阈值),
        核心阈值: Number(p.核心阈值),
      }
    }
    if (Object.keys(通过).length === 0) {
      return { ok: false, 错误: '没有任何预设通过校验：' + 拒绝.slice(0, 3).join('；') }
    }
    return { ok: true, 预设: 通过, 拒绝 }
  } catch (e) {
    return { ok: false, 错误: `请求失败：${e?.message || e}` }
  } finally {
    clearTimeout(计时器)
  }
}
