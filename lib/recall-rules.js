// ============================================================================
// recall-rules.js —— 打分规则的可配置定义、预设与云端更新
//
// 【这个模块负责什么】
//   把 recall-screen.js 里写死的规则抽出来，变成可以：
//     · 用设置页改（用户自己的话题词、应答词、阈值）
//     · 选预设（技术向 / 生活向 / 宽松 / 严格）
//     · 从云端拉新版（预设与规则随 git 更新，用户不必手动改代码）
//
// 【为什么这样设计】
//   · 规则的「重要」标准高度依赖场景。一个写代码的群，「部署/接口/报错」是重点；
//     一个家庭群，「吃药/复查/接孩子」才是重点。写死一套等于强迫所有人接受
//     同一种判断 —— 这是开源工具最容易被诟病的地方。
//
//   · 预设是「起点」不是「终点」：用户选一个预设，然后在此基础上改自己的词。
//     所以存储结构是「基础预设名 + 用户增量」，而不是把预设整个拷贝一份 ——
//     这样预设升级（新增词）时，用户仍能吃到新词，不会因为早先拷贝过就被冻结。
//
//   · 云端更新只更新**预设**，绝不覆盖用户自己写的词。
//     用户词存在独立字段里，与预设分开放，这是硬边界。
//
//   · 云端更新校验很严：只接受纯数据（正则字符串），并且逐条编译试跑。
//     一个坏正则能让整个筛选崩掉，不能信任远端内容。
//
// 【对外导出】
//   · 内置预设 —— { 技术向, 生活向, 宽松, 严格 } 四个预设
//   · 解析规则(配置) —— 预设 + 用户增量 → 实际生效的规则对象
//   · 校验规则(规则) —— 编译全部正则，返回 { ok, 错误[] }
//   · 拉云端预设(地址, 选项) —— 下载 + 校验 + 返回可用预设，失败不改动本地
//   · 预设清单() —— 预设名与说明，给 UI 用
// ============================================================================

