// 主动回忆提示器：告诉模型「什么时候该自己去翻记忆」。
//
// 背景：记忆仓库的工具只是「摆在那儿」，模型不一定会用。实测鱼（QQ 机器人）
// 只在被明确要求时才搜，平时遇到「你还记得吗」「上次那个」这类话，会直接凭上下文编，
// 或者干脆说「我忘了」。
//
// 这个模块用 systemPrompt.context() 追加一段常驻引导（**不是 section** ——
// section 会改系统提示词，让整段 prompt 缓存失效，实测贵 20 倍）。
//
// 设计要点：
//   · 提示要**具体**：说清「看到哪类话 → 调哪个工具」，别写「适时使用记忆工具」这种废话
//   · 提示要**短**：每轮都随上下文走，长了既贵又容易被忽略
//   · 没有记忆库时不要注入（避免空库还引导它去搜）
//   · 内容基本不变 → 宿主的 context 只在内容变了才追加，缓存友好

/**
 * 造一段「主动回忆」引导文本。
 *
 * @param {object} opts
 * @param {() => Promise<boolean>|boolean} [opts.有记忆] 库里有没有东西；返回 false 则输出空串
 * @returns {() => Promise<string>} 每次调用返回当前该注入的文本（可能为空串）
 */
export function 造回忆引导({ 有记忆 } = {}) {
  const 正文 = [
    '【记忆仓库】你有一个外置记忆库，存着对方以前发过的图片和聊天记录。',
    '',
    '**看到下面这些信号，先调工具查，别凭印象答、也别直接说「我忘了」：**',
    '- 对方提到「以前」「上次」「之前」「那天」「你说过」→ 先 `chat_search` 搜关键词',
    '- 对方问「还记得吗」→ 先搜，搜到就说搜到的，搜不到再说没找到',
    '- 对方提到某张图、某个表情 → 先 `memory_search` 搜描述',
    '- 对方问「我发过什么」「最近发的」→ 调 `memory_recent`',
    '- 提到某个人的名字但你想不起是谁 → 调 `person_list`',
    '',
    '**查的时候：**',
    '- 关键词用对方原话里最具体的两三个字，别自己改写（「宝宝」就搜「宝宝」，别扩成「宝宝这件事」）',
    '- 搜不到就换个词再搜一次，还是没结果再如实说「没找到」',
    '- 搜到多条不确定哪条对，就把候选说出来问对方，别自己挑一条当定论',
  ].join('\n')

  return async function 当前引导() {
    try {
      if (typeof 有记忆 === 'function') {
        const 有 = await 有记忆()
        if (!有) return ''
      }
      return 正文
    } catch {
      return ''   // 出任何问题都不注入，绝不影响对话
    }
  }
}
