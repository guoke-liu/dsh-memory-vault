// ============================================================================
// recall-topics.js —— 群聊的话题聚类（**模糊**版，不切事件）
//
// 【为什么群聊不切事件】
//   私聊是一对一，天然串行：一件事说完再说下一件，按时间切就很好。
//
//   群聊不是。实测 2026-11-03 群 730783833 的原始对话：
//
//     00:02 企鹅：图其实画出来了但是发不出来，上传超时      ← 事件 ①
//     00:05 九尾：按新要求，画一张调月莉音                  ← 事件 ②
//     00:07 灰灰：中分背带鸡运球？这什么鬼画面              ← 事件 ③
//     00:11 Hua_J：这78都啥                                ← 事件 ④
//
//   同一分钟内三条不同的线并行。按时间切，必然把 ①②③ 切进一段。
//   这不是阈值调不好的问题 —— **群聊里本来就同时存在多个事件**，
//   任何「把时间段切开」的算法都无法还原它们。
//
// 【那怎么办：不还原事件，只找话题】
//   群聊真正有用的信息不是「发生了哪件事」，而是「这段时间在聊什么」。
//   用户问「上次群里说画图那事怎么解决的」，他要的是**那几条相关消息**，
//   不是一个结构完整的事件。
//
//   所以这里做的是：从一群消息里找出反复出现的名词短语，聚成话题，
//   每个话题带上它的消息。群聊的产物是**话题**，不是事件 ——
//   名字、结构、检索方式都不一样，不要混用。
//
// 【为什么不用模型】
//   群聊量大（一天 2200 条）且噪声高，全量送模型太贵；
//   话题聚类是纯统计，零成本，先做减法再谈提炼。
// ============================================================================

/**
 * 中文虚词 / 口头禅的 2 字片段黑名单。
 *
 * 为什么要黑名单：2 字滑窗切中文会产生大量「这个」「那个」「就是」
 * 这类片段，它们出现频率最高，聚类会全聚到它们身上。
 * 这是最容易让话题聚类变成废话的地方。
 */
import { readFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { 时刻转秒 } from './recall-events.js'

const 虚词 = new Set([
  '这个', '那个', '就是', '不是', '可以', '没有', '什么', '怎么', '还是', '但是',
  '因为', '所以', '然后', '现在', '今天', '明天', '昨天', '时候', '一个', '我们',
  '你们', '他们', '她们', '自己', '已经', '还有', '这些', '那些', '这样', '那样',
  '知道', '觉得', '应该', '可能', '好像', '真的', '一下', '一直', '怎么', '为什',
  '是的', '对啊', '好吧', '哈哈', '嘿嘿', '呵呵', '呜呜', '嗯嗯', '哈哈', '真的',
  '不过', '而且', '或者', '如果', '虽然', '其实', '反正', '确实', '或者', '要不',
  '一点', '有点', '非常', '特别', '比较', '应该', '需要', '不用', '不要', '不会',
])

/**
 * 词频表：词 → 档位（数字越小越常见，0 最常见）。
 *
 * 这份表用来判断「一个 2 字组合到底是不是词」，比黑名单可靠得多。
 *
 * 实测（2026-11-04）：2 字滑窗切出来的「的是」「是我」「我的」「我这」
 * **根本不在词频表里** —— 因为它们是硬凑的组合，不是词；
 * 而「日记」「服务器」「直接」「尾巴」「出来」都在表里。
 * 用「在不在表里」当判据，比维护一张永远列不全的虚词黑名单准得多。
 */
let 词频表 = null
function 取词频 () {
  if (词频表) return 词频表
  词频表 = new Map()
  try {
    const p = join(dirname(fileURLToPath(import.meta.url)), '..', 'data', 'freq.txt')
    for (const 行 of readFileSync(p, 'utf8').split('\n')) {
      const m = 行.trim().split(/\s+/)
      if (m.length === 2) 词频表.set(m[0], Number(m[1]))
    }
  } catch {
    // 读不到词频表也不该让功能挂掉：退化成「只靠虚词黑名单」
    词频表 = new Map()
  }
  return 词频表
}

/** 档位门槛：超过这个档位算「罕见词」，更适合当话题线索。 */
export const 常见词档位 = 45

/**
 * 从一段文字里抽「名词性片段」。
 *
 * 做法：英文词整词取；中文按 2 字滑窗取，然后过三道筛：
 *   1. 不在虚词黑名单里
 *   2. 在词频表里（说明它是个真词，不是硬凑的组合）
 *   3. 档位 > 常见词档位（说明不是「出来」「可以」这类高频虚词）
 *
 * 第 2、3 道是这套里最要紧的 —— 少了它们，话题会聚成一堆
 * 「出来」「我这」「的是」这种废话（实测踩过）。
 *
 * @param {string} 文本
 * @returns {string[]} 片段列表（可重复，调用方自己统计频次）
 */
export function 抽片段 (文本) {
  const s = String(文本 ?? '')
  const 出 = []
  const 频 = 取词频()

  // 英文 / 型号：整词，长度 3 以上（避免 the、of 这类）
  for (const w of s.match(/[a-zA-Z][a-zA-Z0-9_+#.-]{2,}/g) || []) {
    出.push(w.toLowerCase())
  }

  // 中文：只在这两个汉字的连续片段上滑窗，跨标点的凑不成词
  for (const 段 of s.split(/[^\u4e00-\u9fff]+/)) {
    for (let i = 0; i + 2 <= 段.length; i++) {
      const w = 段.slice(i, i + 2)
      if (虚词.has(w)) continue
      // 词频表为空时（读不到文件）跳过这两道，退化成老行为
      if (频.size > 0) {
        if (!频.has(w)) continue // 不是真词
        if (频.get(w) <= 常见词档位) continue // 太常见，没区分度
      }
      出.push(w)
    }
  }
  return 出
}

/**
 * 把一批消息聚成话题。
 *
 * @param {Array<{时间?:string, 昵称?:string, 内容?:string, 日期?:string}>} 消息们
 * @param {{最少次数?:number, 最多话题?:number, 最多消息每话题?:number}} [选项]
 * @returns {Array<{话题:string, 片段:Array<string>, 命中:number, 消息数:number, 消息:Array<object>}>}
 */
export function 聚话题 (消息们, 选项 = {}) {
  const 最少次数 = Number.isFinite(Number(选项.最少次数)) ? Number(选项.最少次数) : 3
  const 最多话题 = Number.isFinite(Number(选项.最多话题)) ? Number(选项.最多话题) : 8
  const 每话题上限 = Number.isFinite(Number(选项.最多消息每话题)) ? Number(选项.最多消息每话题) : 15
  // 时间窗：同一话题内间隔超过这么久，就算另一次讨论。
  //
  // 默认 2 小时，不是 30 分钟 —— 这是实测调出来的（2026-11-04）：
  //   30 分 → 63 段，其中 19 段不足 3 条（切太碎，全是碎片）
  //   60 分 → 34 段，10 段不足 3 条
  //   120 分 → 17 段，4 段不足 3 条（粒度合适）
  // 群聊里同一个话题的讨论往往断断续续（说完一句去聊别的，过会儿又回来），
  // 窗口定太短会把一次讨论切成一地碎片。
  const 时间窗 = Number.isFinite(Number(选项.时间窗秒)) ? Number(选项.时间窗秒) : 7200

  const 全部 = (Array.isArray(消息们) ? 消息们 : []).filter((m) => String(m?.内容 || '').trim())
  if (全部.length === 0) return []

  // ── 1. 统计片段频次 ────────────────────────────────────────────────
  const 频次 = new Map()
  const 片段到消息 = new Map() // 片段 → Set(消息下标)
  for (let i = 0; i < 全部.length; i++) {
    const 片段集 = new Set(抽片段(全部[i].内容))
    for (const w of 片段集) {
      频次.set(w, (频次.get(w) || 0) + 1)
      if (!片段到消息.has(w)) 片段到消息.set(w, new Set())
      片段到消息.get(w).add(i)
    }
  }

  // ── 1.5 每个片段被几个人说过 ──────────────────────────────────────
  //
  // 这一层是防「口癖」的：实测「尾巴」出现 90 次，但只有 2 个人说
  // （一个人是机器人、一个人是它的主人），那是角色设定，不是群里的话题。
  // 而「日记」「token」「模型」有 4-7 个人说 —— 那才是真有人在讨论。
  //
  // 光看词频分不开它们（尾巴 55 档 / 日记 56 档，几乎一样），
  // 「多少人说过」才是可靠信号。
  const 说过的人数 = new Map() // 片段 → Set(昵称)
  for (let i = 0; i < 全部.length; i++) {
    const 谁 = String(全部[i]?.昵称 || '').trim() || '(无名)'
    for (const w of new Set(抽片段(全部[i].内容))) {
      if (!说过的人数.has(w)) 说过的人数.set(w, new Set())
      说过的人数.get(w).add(谁)
    }
  }

  // ── 2. 挑出够频繁的片段 ────────────────────────────────────────────
  //
  // 太短的片段（单字）在这套规则里不会出现；2 字片段只要出现够多就是话题线索。
  // 但纯数字串要排除 —— 「2026」「11」「03」这种满屏都是，没有区分度。
  const 最少人 = Number.isFinite(Number(选项.最少人)) ? Number(选项.最少人) : 3
  const 候选 = [...频次.entries()]
    .filter(([w, n]) => n >= 最少次数 && !/^\d+$/.test(w))
    // 至少要有几个人说过，一个人反复说的属于口癖或角色设定
    .filter(([w]) => (说过的人数.get(w)?.size || 0) >= 最少人)
    .sort((a, b) => {
      // 排序看「几人说」再看出「次数」：多人提及的比单人狂说的更像话题
      const 人差 = (说过的人数.get(b)?.size || 0) - (说过的人数.get(a)?.size || 0)
      return 人差 !== 0 ? 人差 : b[1] - a[1]
    })

  if (候选.length === 0) return []

  // ── 3. 合并：一个片段覆盖的消息若大半被已选话题覆盖，就不单列 ───────
  //
  // 为什么合并：「画图」「画的」「画一张」会一起出现，各自成话题就是三份废话。
  // 判据是消息集合的重叠程度，而不是字符串相似 —— 字符串像不代表聊的是同一件事。
  const 话题们 = []
  const 已覆盖 = new Set()
  for (const [w, n] of 候选) {
    if (话题们.length >= 最多话题) break
    const 消息集 = 片段到消息.get(w) || new Set()
    let 新消息数 = 0
    for (const i of 消息集) if (!已覆盖.has(i)) 新消息数 += 1
    // 新消息少于该片段命中的一半，说明它讲的事已经被别的话题覆盖了
    if (新消息数 < Math.max(1, Math.ceil(消息集.size / 2))) continue

    话题们.push({
      话题: w,
      片段: [w],
      命中: n,
      人数: 说过的人数.get(w)?.size || 0,
      消息集,
    })
    for (const i of 消息集) 已覆盖.add(i)
  }

  // ── 4. 每个话题按时间窗折叠成「几次讨论」────────────────────────────
  //
  // ⚠️ 这一步是实测补上的（2026-11-04）。
  // 第一版把话题的所有消息直接放一起，结果：
  //   【日记】50 条 分布在 10:22:13 ~ 11:35:12
  //   【gemini】34 条 分布在 10:26:39 ~ 16:40:16
  // 话题跨了 6-11 小时 —— 那已经不是「一次讨论」，是「一整天都在说的词」。
  // 用户问「上次说日记那事怎么定的」，拿回 50 条散落 11 小时的碎片，
  // 等于没检索。
  //
  // 做法：把话题的消息按时间排序，间隔超过 时间窗 就断开 ——
  // 一个话题变成若干「时间段」，每段是一次集中的讨论。
  return 话题们.flatMap((t) => {
    // ⚠️ 必须按**时间**排序，不能按原始行号排序。
    //
    // 实测踩过（2026-11-04）：聊天文件本身不是严格按时间写的 ——
    // 群 934074044 的 11-03 有 705 行，其中 6 处时间倒挂
    // （12:07 的消息写在 12:53 后面、08:39 排在最后）。
    // 按行号排序再算时间窗，会切出「起 12:53:48 → 止 08:39:23」这种
    // 结束时间早于开始时间的段。
    //
    // 按 秒 → 时间字符串 → 行号 三级排序，保证时间单调。
    const 下标 = [...t.消息集].sort((a, b) => {
      const 秒a = 时刻转秒(全部[a]?.时间)
      const 秒b = 时刻转秒(全部[b]?.时间)
      // 时间读不出来的排最后，不要插在中间打乱单调性
      if (秒a === null && 秒b === null) return a - b
      if (秒a === null) return 1
      if (秒b === null) return -1
      return 秒a - 秒b || a - b
    })
    const 带秒 = 下标.map((i) => ({ i, 秒: 时刻转秒(全部[i]?.时间) }))

    const 时段们 = []
    let 当前 = []
    const 收尾 = () => { if (当前.length) { 时段们.push(当前); 当前 = [] } }
    for (const x of 带秒) {
      if (当前.length === 0) { 当前.push(x); continue }
      const 上 = 当前[当前.length - 1]
      // 时间读不出来时不作断点依据（宁可合并不乱切）
      if (上.秒 !== null && x.秒 !== null && x.秒 - 上.秒 > 时间窗) {
        收尾()
        当前.push(x)
        continue
      }
      当前.push(x)
    }
    收尾()

    // 丢掉太碎的段：只有 1-2 条消息的「讨论」没有检索价值，
    // 留着只会让结果列表里全是碎片。门槛复用 最少次数。
    return 时段们.filter((段) => 段.length >= 最少次数).map((段) => {
      const 取 = 段.slice(0, 每话题上限).map((x) => 全部[x.i])
      return {
        话题: t.话题,
        片段: t.片段,
        命中: 段.length,
        人数: new Set(取.map((m) => String(m?.昵称 || '').trim()).filter(Boolean)).size,
        消息数: 段.length,
        起: String(取[0]?.时间 || ''),
        止: String(取[取.length - 1]?.时间 || ''),
        消息: 取,
        // 同一话题被切成几段时，调用方能看出「这是第几次讨论」
        同话题段数: 时段们.length,
      }
    })
  }).sort((a, b) => (a.起 < b.起 ? -1 : a.起 > b.起 ? 1 : 0))
}

/**
 * 群聊话题的「值得记」分数。
 *
 * 群聊噪声大，光有话题还不够 —— 有的「话题」只是口头禅的变体。
 * 这里看一眼实际内容判断值不值得留。
 *
 * @param {{消息:Array<object>, 消息数:number, 命中:number}} 话题
 * @returns {number} 0..1
 */
export function 话题价值分 (话题) {
  const 消息们 = Array.isArray(话题?.消息) ? 话题.消息 : []
  if (消息们.length === 0) return 0

  const 正文 = 消息们.map((m) => String(m?.内容 || '')).join('')
  const 字数 = 正文.replace(/\s/g, '').length
  if (字数 < 15) return 0

  // ⚠️ 为什么「命中次数」只占很小权重（0.15，原来是 0.4）
  //
  // 实测踩过（2026-11-04）：原来按命中次数给 0.4 分，
  // 结果是**大群的小事得分高、小群的正事得分低**：
  //   大群 2195 条：【模型】命中 28 → 1.00
  //   小群  139 条：话题最多命中 5 → 全部低于 0.5 被过滤掉
  // 于是 19 个「来源+日期」里有 8 个一条事件都没有 —— 全是不太活跃的群。
  // 命中次数衡量的是「这个群有多热闹」，不是「这是不是件事」。
  //
  // 现在按「有多少人参与 + 内容里有没有实质信息」主导：
  //   · 两个人以上在说 → 是讨论，不是自言自语
  //   · 有数字/决定词 → 有实质内容
  // 这样小群的正事能过线，大群的碎词也上不去。
  let 分 = 0

  // 被提到的次数：只作为「持续性」的轻微加成
  分 += Math.min(Number(话题.命中) || 0, 10) / 10 * 0.15

  // 参与人数：群聊里一个话题只有一个人说，很可能是自言自语
  const 人数 = new Set(消息们.map((m) => String(m?.昵称 || '').trim()).filter(Boolean)).size
  if (人数 >= 2) 分 += 0.30
  if (人数 >= 4) 分 += 0.15

  // 内容里有没有实质信息
  if (/\d/.test(正文)) 分 += 0.15
  if (/说好|答应|决定|定了|记得|别忘|必须|改成|修好|搞定|完成|解决|新写|优化|插件|仓库|部署/.test(正文)) 分 += 0.25

  return Math.min(分, 1)
}
