/**
 * 取模型配置：设置页优先，回落 llm.json。
 *
 * 三种情况：
 *   ① 设置里填了 baseURL + 模型名（key 可选）→ 用设置里的。
 *      key 允许为空：有些本地模型（Ollama、vLLM）不需要 key。
 *   ② 设置没填 → 读同目录下的 llm.json（兼容早期配置，也方便从日记插件迁移）。
 *   ③ 都没有 → 返回 null，调用方退回规则筛选。
 *
 * 为什么不强制要求 key：批量打分层是可选功能，本地跑个 7B 模型
 * 完全可行，那种场景下强制填 key 是无意义的门槛。
 *
 * @param {string} 配置目录
 * @param {object} 设置 settings.read() 的结果
 * @returns {Promise<object|null>}
 */
export async function 取模型配置 (配置目录, 设置 = {}) {
  const 有设置 = (设置.模型接口地址 && String(设置.模型接口地址).trim())
    && (设置.模型名称 && String(设置.模型名称).trim())
  if (有设置) {
    return {
      baseURL: String(设置.模型接口地址).trim(),
      apiKey: String(设置.模型密钥 || '').trim(),
      model: String(设置.模型名称).trim(),
      timeoutMs: 120000,
      温度: 设置.模型温度,
      最大输出: 设置.模型最大输出,
      系统提示词: 设置.系统提示词,
      批大小: 设置.模型批大小,
      批间隔毫秒: 设置.模型批间隔毫秒,
    }
  }
  // 设置没填，回落 llm.json
  try {
    const fs = await import('node:fs/promises')
    const p = path.join(配置目录, 'llm.json')
    const v = JSON.parse(await fs.readFile(p, 'utf8'))
    if (v && v.baseURL && v.model) return v
  } catch { /* 没有就算了 */ }
  return null
}

/** 把检索命中渲染成人读文本。 */
function 渲染命中 (结果) {
  const 行 = []
  for (const r of 结果) {
    const 标签段 = r.标签.length ? ` [${r.标签.join(',')}]` : ''
    行.push(`· [${来源标签(r.来源)}] ${r.日期} ${r.id}${标签段} ${r.标题 || ''}`)
    const 正文 = String(r.内容 || '')
    行.push(`  ${正文.length > 240 ? 正文.slice(0, 240) + '…' : 正文}`)
    行.push(`  分：总 ${r.分数.总分}（词面 ${r.分数.词面} / 向量 ${r.分数.向量} / 时效 ${r.分数.时效} / 重要度 ${r.分数.重要度}）`)
  }
  // 有聊天摘要时提示「这不是全文」：分层库只存摘要，全文在聊天记录里。
  // 不提示的话，模型会把摘要当完整原话引用，答出来的话就短了一截。
  const 有聊天 = 结果.some((r) => r.id && String(r.id).startsWith('chat-'))
  if (有聊天) {
    行.push('')
    行.push('（提示：标 chat- 的是聊天摘要，不是全文。要看当时完整原话，用 chat_search 按关键词搜当天的聊天记录。）')
  }
  return 行.join('\n')
}

/** 把下钻拿到的原始聊天渲染成文本。 */
function 渲染原文 (命中) {
  const 行 = ['', '—— 以下是记忆仓库里的原始聊天 ——']
  for (const h of 命中) {
    const 群 = h.群 ? ` @群${h.群}` : ''
    // 聊天检索返回的是整行原文（`[HH:MM:SS] 昵称(pid): 内容`），没有单独的
    // 日期/时间字段 —— 那就把整行原样贴出来，别拼出一串 undefined。
    if (!h.时间 && !h.昵称) {
      行.push(`[${h.日期}]${群} ${h.内容}`)
      continue
    }
    行.push(`[${h.日期} ${h.时间}] ${h.昵称}(${h.pid})${群}: ${h.内容}`)
  }
  return 行.join('\n')
}

/**
 * 读日记库全部条目。目录不存在 / 读不到 → 返回空数组。
 *
 * 只读，不关心日记插件怎么实现 —— 文件布局是契约，代码不是。
 */
function 读日记 (日记根, 导入目录 = '') {
  // 两个来源读同一套布局：日记库（别的插件的）+ 导入目录（本插件写的）。
  // 分开读再合并，互不影响：日记库没有或坏了，导入的数据照样能用。
  const 条目 = []
  for (const 根目录 of [日记根, 导入目录]) {
    if (!根目录) continue
    读一套(根目录, 条目)
  }
  return 条目
}

/** 读一个根目录下的 entries/<来源>/<日期>.json，追加到 条目。 */
function 读一套 (根目录, 条目) {
  const 根 = path.join(根目录, 'entries')
  let 来源目录们
  try {
    来源目录们 = readdirSync(根)
  } catch {
    return
  }
  for (const name of 来源目录们) {
    const dir = path.join(根, name)
    let st
    try { st = statSync(dir) } catch { continue }
    if (!st.isDirectory()) continue
    // 目录名 → 来源 key。两种命名都要认：
    //   private / group-<群号>  —— 日记库的既有布局
    //   其它任意名字            —— 导入数据的来源名（dayone、notion、imported…）
    //
    // 早先只认前两种，其它一律 continue 跳过 —— 结果是导入成功了、
    // 文件也写对了，但检索一条都读不到，而且两边各自看都正常。
    // 认不出的名字原样当来源，比静默跳过强：多读一点无关数据无害，
    // 少读用户刚导入的东西是致命伤。
    let key = ''
    if (name === 'private') key = 'private'
    else {
      const m = name.match(/^group[-_]([A-Za-z0-9_-]+)$/)
      if (m) key = `group:${m[1]}`
      else if (/^[A-Za-z0-9_\-\u4e00-\u9fa5]+$/.test(name)) key = name
    }
    if (!key) continue
    let names
    try { names = readdirSync(dir) } catch { continue }
    for (const n of names.sort()) {
      const m = n.match(/^(\d{4}-\d{2}-\d{2})\.json$/)
      if (!m) continue
      let v
      try {
        v = JSON.parse(readFileSync(path.join(dir, n), 'utf8'))
      } catch { continue }
      if (!v || !Array.isArray(v.entries)) continue
      for (const e of v.entries) {
        if (!e || typeof e !== 'object' || typeof e.text !== 'string') continue
        条目.push({
          来源: key,
          日期: m[1],
          id: String(e.id || ''),
          title: String(e.title || ''),
          text: e.text,
          tags: Array.isArray(e.tags) ? e.tags.map(String) : [],
          at: String(e.at || ''),
        })
      }
    }
  }
}

/**
 * 直接搜本插件的聊天记录（下钻用）。
 *
 * 复用 chatlog.js 的 搜索记录 —— 合并在同一个插件里，不必再探测接口。
 * 返回形状对齐 搜索记录 的真实约定：{ date, groupId, line, text }，
 * 内容在 text，整行在 line，昵称与 pid 只能从 line 里拆。
 */
async function 搜聊天 (仓库根, 查询, { chatType, groupId, limit = 10, 起, 止 } = {}) {
  const hits = await 搜索记录(仓库根, 查询, {
    chatType,
    groupId,
    // ⚠️ 只按人问、没有关键词也没有日期时（「某人最后一句说了什么」），
    // 上层的过滤完全在 JS 里做，这里必须先读够行数再筛 —— 只读 limit 行，
    // 那个人说的话很可能一条都没落在前几行里，结果就是「查无此人」。
    // 所以这种情况没有任何过滤条件时，把读取上限顶到 200 行。
    limit: Math.max(1, Math.min(
      (!String(查询 || '').trim() && !起 && !止) ? 200 : Number(limit) || 10,
      200,
    )),
    // 日期范围要透传：不透传的话，「起了/止了」在降级分支里等于没传，
    // 用户拿到的是整个仓库里最新的几条，看起来就像系统没听懂日期。
    起,
    止,
  })
  return (Array.isArray(hits) ? hits : []).map((h) => {
    const 行 = String(h.line || '')
    const m = 行.match(/^\[(\d{1,2}:\d{2}(?::\d{2})?)\]\s+(.+?)\(([^)]*)\):\s?([\s\S]*)$/)
    return {
      日期: h.date || '',
      时间: m ? m[1] : '',
      昵称: m ? m[2] : '',
      pid: m ? m[3] : '',
      内容: String(h.text || (m ? m[4] : 行)),
      群: h.groupId || null,
      整行: 行,
    }
  })
}

/**
 * 按人翻聊天原文（只在「给了人、但给不出关键词也没给日期」时用）。
 *
 * 为什么不复用 搜索记录：那个函数只认关键词，没有关键词就返回空。
 * 「某人最后一句说了什么」本来就不该有关键词 —— 于是这条路上永远是空集，
 * 用户得到「聊天里也没搜到」。实测踩过（2026-11-04 第二张截图）。
 *
 * 为什么按「有这个人出现的日子」倒着找：一天两千多条消息，只读最新一天
 * 很可能什么都没读到（那个人今天还没说话）。所以按天往前翻，凑够就停，
 * 最多翻 7 天 —— 再多就不是「最近说了什么」这个问题了。
 *
 * @param {string} 仓库根
 * @param {string} 来源参数 '*' / private / group / group:<id>
 * @param {string[]} 词们 昵称碎片（拆人名 的结果）
 * @param {number} 上限 最多要几条
 * @param {number} 每天读多少行
 */
async function 按人翻聊天 (仓库根, 来源参数, 词们, 上限 = 20, 每天读多少行 = 500) {
  const 出 = []
  try {
    const { readdirSync, existsSync } = await import('node:fs')
    const path = (await import('node:path')).default
    const 目录们 = []
    if (来源参数 === '*' || 来源参数 === 'private') 目录们.push(path.join(仓库根, 'chat', 'private'))
    if (来源参数 === '*' || 来源参数 === 'group' || 来源参数.startsWith('group:')) {
      const 群根 = path.join(仓库根, 'chat', 'group')
      const 群号 = /^group:\d+$/.test(来源参数) ? 来源参数.slice(6) : ''
      if (existsSync(群根)) {
        for (const g of readdirSync(群根)) {
          if (群号 && g !== 群号) continue
          目录们.push(path.join(群根, g))
        }
      }
    }
    // 两轮：第一轮只读每天最后 500 行（绝大多数情况够）；不够再把整天读一遍
    for (const 每天行数 of [每天读多少行, Infinity]) {
      for (const 目录 of 目录们) {
        if (!existsSync(目录)) continue
        const 日期们 = readdirSync(目录)
          .map((f) => (f.match(/^(\d{4}-\d{2}-\d{2})\.txt$/) || [])[1])
          .filter(Boolean)
          .sort()
          .reverse()
          .slice(0, 7)
        for (const 日期 of 日期们) {
          const 行们 = await 搜聊天(仓库根, '', {
            chatType: 目录.includes(path.join('chat', 'private')) ? 'private' : 'group',
            groupId: /^group:\d+$/.test(来源参数) ? 来源参数.slice(6) : undefined,
            起: 日期, 止: 日期, limit: Number.isFinite(每天行数) ? 每天行数 : 200,
          })
          for (const h of 行们) {
            if (!昵称对得上(h.昵称, 词们)) continue
            出.push({ ...h, 时间戳: `${h.日期}T${h.时间 || ''}` })
          }
          // 去重（两轮会读到同样的行）
          if (出.length >= 上限 && Number.isFinite(每天行数)) break
        }
        if (出.length >= 上限 && Number.isFinite(每天行数)) break
      }
      if (出.length >= 上限) break
    }
  } catch { /* 翻不动就当成没找到 */ }
  const 见过 = new Set()
  return 出
    .filter((x) => {
      const k = `${x.日期} ${x.时间} ${x.整行}`
      if (见过.has(k)) return false
      见过.add(k)
      return true
    })
    .sort((a, b) => b.时间戳.localeCompare(a.时间戳))
    .slice(0, 上限)
}

/**
 * 渲染「按时间取」的结果。
 *
 * ⚠️ 必须显式交代「按什么筛的、筛掉多少」。
 *
 * 主人 2026-11-04：按时间取的结果必须显示按人筛过、筛后 0 条，
 * 不许静默丢条件。实测踩过：带了「人」，但代码只按时间返回了别人的话，
 * 标题还写着「按时间倒序」，看起来像个正常结果 —— 比直接报错更坏。
 *
 * @param {object} p
 */
function 渲染时间结果 ({ 条, 仓库根, 来源参数, 起日0, 止日0, 只要某人0, 从查询, 按时间读聊天 }) {
  const 范围 = `${起日0 || '不限'} ~ ${止日0 || '不限'}`
  const 条件尾巴 = 只要某人0 ? `，人=${只要某人0}` : ''
  if (条.length === 0) {
    // 「没有内容」和「你说的人对不上任何人」是两回事。
    // 只回一句「没有内容」，模型只能照着答「没找到」，用户就以为数据丢了。
    const 名 = 拆人名(只要某人0)
    const 未筛 = 只要某人0
      ? 按时间读聊天(仓库根, { 来源: 来源参数, 起: 起日0, 止: 止日0, 上限: 200 })
      : []
    const 出现过的 = [...new Set(未筛.map((x) => x.昵称))].slice(0, 20)
    const 行 = [`按时间查（${范围}${条件尾巴}）：没有内容。`]
    if (只要某人0) {
      行.push('')
      if (未筛.length > 0) 行.push(`这个时间段里有 ${未筛.length} 条消息，但没有一条是「${只要某人0}」说的。`)
      else 行.push('这个时间段里没有任何消息。')
      if (名.称谓) {
        行.push(`历史记录里没有存过「${名.称谓}」这类身份 —— 记不了「谁是群主」，`)
        行.push('请改填具体昵称（对方可能会改名，现用的名字在 person_list 里能查到）。')
      }
      if (出现过的.length) 行.push(`这个时间段里说过话的人：${出现过的.join('、')}`)
    }
    return { 找到: false, 命中数: 0, 下钻过: false, 下钻原因: '', 原文数: 0, text: 行.join('\n') }
  }

  const 行 = [`按时间倒序（${范围}${条件尾巴}）：${条.length} 条`]
  // 只要给了人，就写清筛了多少 —— 否则用户分不清「这就是全部的」还是「筛过的」
  //
  // ⚠️ 这里不能拿「按人读聊天」和「不按人读聊天」两次结果对比。
  // 实测踩过（云端真数据）：`按时间读聊天` 有 200 条上限，
  // 「这个时间段共 200 条」其实是「我只读了 200 条」，
  // 「筛后 0 条」更是荒谬 —— 下面明明列着 6 条南瓜鸡的话。
  // 两次调用各自被上限截断，相减得到的数字没有任何意义。
  //
  // 现在改成人话：只报「这次返回了几条」，多的话直接说「只显示前 N 条」。
  if (只要某人0) {
    const 多吗 = 条.length >= (从查询.要几条 || 20)
    行.push(`条件：人=${只要某人0}（返回 ${条.length} 条${多吗 ? '，只显示最新的这些' : ''}）`)
  }
  // 从整句提问里拆出来的条件要明说，让用户看得见「系统以为你在问什么」
  const 拆来说 = []
  if (从查询.人) 拆来说.push(`人=${从查询.人}`)
  if (从查询.时间段) 拆来说.push(`时间=${从查询.时间段}（${从查询.起}）`)
  if (从查询.只看最近) 拆来说.push('要最近的')
  if (拆来说.length) 行.push(`从提问里识别出：${拆来说.join('、')}`)
  行.push('')
  for (const x of 条) {
    行.push(`[${x.日期} ${x.时间}] ${x.昵称}：${String(x.内容).slice(0, 200)}`)
  }
  return { 找到: true, 命中数: 条.length, 下钻过: false, 下钻原因: '', 原文数: 0, text: 行.join('\n') }
}

/**
 * 从一整句自然语言里认出「谁 / 什么时候 / 要什么」。
 *
 * 【为什么要有这一步】
 *
 * 主人 2026-11-04 第二张截图，鱼答「我没找到」。我一直以为断在参数上，
 * 其实断在**模型根本不会拆**：它最自然的做法是把整句扔进 query：
 *
 *   memory_recall { query: "南瓜鸡昨晚最后一句说的什么" }
 *
 * 云端实测这条路返回「事件库 40 条，命中 0 条」—— 整串当关键词去和事件名
 * 做子串匹配，自然语言永远匹配不上。这就是截图里那句「我没找到」。
 *
 * 所以这里补一层纯规则拆解（零成本、不调模型、不联网）：
 *
 *   南瓜鸡昨晚最后一句说的什么
 *     ↓
 *   人=南瓜鸡  起=止=昨天  只看最近=true  剩余=""
 *
 * 【为什么不靠模型拆】
 * 开源版要能零 LLM 运行（这是底线）。而且这类句子结构高度固定，
 * 规则认得又快又稳，还能把「认出来的是什么」原样告诉用户 ——
 * 猜错了用户一眼看得见，比模型默默拆错强。
 *
 * 【认不出就原样返回】
 * 拆不出任何东西时 剩余 = 原句，后续流程和以前完全一样，不会因为
 * 这层不认而把功能弄坏。
 *
 * @param {string} 原文
 * @param {Date} [现在] 参照时间（测试用）
 * @returns {{人:string, 起:string, 止:string, 只看最近:boolean, 时间段:string, 剩余:string}}
 */
export function 拆询问 (原文, 现在 = new Date()) {
  const 空 = { 人: '', 起: '', 止: '', 只看最近: false, 时间段: '', 剩余: String(原文 ?? '').trim() }
  let s = String(原文 ?? '').trim()
  if (!s) return 空

  const 出 = { 人: '', 起: '', 止: '', 只看最近: false, 时间段: '', 剩余: '' }

  // ── 只看最近：问「最后一句」「最近说了什么」──
  // 这几个词一旦出现，就不是在问相关度，而是在问时间。
  // 「最后 3 句」「最后三条」也算 —— 数字可有可无。
  // ⚠️ 判定必须在**剥掉时间词之前**做吗？不，两种都行 —— 但正则别写严。
  // 实测踩过：写成 `最后[句条]` 时「最后一句」因为中间夹着「一」而不匹配，
  // 「南瓜鸡昨晚最后一句说的什么」整句因此没被认成「问时间」。
  if (/最后\s*[*一二三四五六七八九十\d]*\s*[句条]|最后(说的|讲了|说了)|结尾那句|最近(说的|说了|讲了)|(说|讲)了?(什么|啥)/.test(s)) {
    出.只看最近 = true
  }
  // 那句「最后 N 句」里的数字是用户要几条，顺手记下来
  const 条数 = s.match(/最后\s*(\d+)\s*[句条]/)
  if (条数) 出.要几条 = Math.max(1, Math.min(Number(条数[1]) || 0, 30))

  // ── 什么时候：只认能算成确定日期的说法 ──
  // 「昨天」这种相对词必须在这里算掉：工具层的 规范日期 明确不猜相对词，
  // 因为模型自己也能算，但实测模型经常干脆不传日期。
  const 今天 = 日期串(现在)
  const 相对 = [
    [/前天/, -2], [/昨天|昨晚|昨夜/, -1], [/今天|今天早上|今早/, 0],
  ]
  for (const [re, 偏移] of 相对) {
    const m = s.match(re)
    if (!m) continue
    const d = 推日(现在, 偏移)
    出.起 = 出.起 || d
    出.止 = 出.止 || d
    出.时间段 = m[0]
    s = s.replace(re, ' ')
    break
  }
  // 明确写出来的日期：2026-11-03 / 11月3日
  if (!出.止) {
    const m = s.match(/(\d{4})[-/](\d{1,2})[-/](\d{1,2})/)
    const 规 = m ? 规范日期(`${m[1]}-${m[2]}-${m[3]}`) : ''
    if (规) {
      出.起 = 规
      出.止 = 规
      出.时间段 = m[0]
      s = s.replace(m[0], ' ')
    }
  }
  if (!出.止) {
    const m = s.match(/(\d{1,2})月(\d{1,2})[日号]/)
    const 规 = m ? 规范日期(`${现在.getFullYear()}-${m[1]}-${m[2]}`) : ''
    if (规) {
      出.起 = 规
      出.止 = 规
      出.时间段 = m[0]
      s = s.replace(m[0], ' ')
    }
  }

  // ── 谁：从「说话 / 发言 / 说的」前面的那一段里找人名 ──
  //
  // 「南瓜鸡昨晚最后一句说的什么」→ 剥离时间词后变成
  // 「南瓜鸡 最后一句说的什么」，人名就在「最后一句」前面。
  const 谁 = s.match(/^(.*?)\s*(?:最后|最近|那[句条]|说过|说的|讲了|的话|说)/)
  let 候选人 = 谁 ? 谁[1] : ''
  // 「搜群主…」这种：开头是检索动词，剥掉再找名
  候选人 = 候选人.replace(/^(搜一下|搜搜|搜|查一下|查查|查|找一下|找找|找|看看|回忆一下)\s*/,'')
  if (!候选人) {
    // 换一种说法：「昨晚南瓜鸡说了什么」→ 时间词后面紧跟的就是人名
    const m = s.match(/^(?:的)?\s*([^\s，。？?、]{2,8})\s*(?:最后|最近|说|讲|发言|聊)/)
    候选人 = m ? m[1] : ''
  }
  候选人 = 清人名(候选人)
  if (候选人 && !是虚词(候选人)) {
    出.人 = 候选人
    s = s.replace(候选人, ' ')
  }

  // ── 要什么：认完的都要剥掉，剩下的才是真正的关键词 ──
  //
  // 剥不干净会留下一堆「的」「什么」「说的」去参与匹配，
  // 那等于没拆。所以这里把已知的问句骨架词统统去掉。
  s = s.replace(/最后(一|1)?句|最后一条|最近(说的|说了|讲了|发的)|结尾那句/g, ' ')
  s = s.replace(/说(的|了)?(什么|啥|话)?|讲(的|了)?(什么|啥)?|发言|聊(的|了)?(什么|啥)?/g, ' ')
  s = s.replace(/^(那|那么|这个|那个|关于)+/g, ' ')
  // 「搜」「晚上」「啥」这类残渣不参与匹配，剥掉
  s = s.replace(/^(搜一下|搜搜|搜|查一下|查查|查|找一下|找找|找|看看)\s*/,'')
  s = s.replace(/(上午|下午|晚上|早上|中午|凌晨|夜里|以前|之前|上次|那次)/g, ' ')
  s = s.replace(/[的是了吗呢吧啊，。？！?！、\s]+/g, ' ')
  s = s.trim()
  // 剩下的东西如果只是「什么」「啥」这种，那就不算关键词
  if (/^(什么|啥|什么话|啥话|话)$/.test(s)) s = ''
  出.剩余 = s

  return 出
}

/** 两个字的虚词不进人名候选 */
function 是虚词 (v) {
  return /^(那个|这个|谁|啥|什么|他|她|他们|她们|大家|群里|刚才|里面|那边)$/.test(v)
}

/** 把人名候选洗干净：去掉标点和「的」这类粘连 */
function 清人名 (v) {
  return String(v ?? '')
    .replace(/[的了吧呢啊，。？！?！、\s]/g, '')
    .replace(/^(那|那么|这个|那个|搜一下|搜搜|搜|查一下|查查|查|找一下|找找|找|看看)/, '')
    // 「昨天」「晚上」这类时间残渣粘在人名里就去掉
    .replace(/(昨晚|昨夜|昨天晚上|昨天|前天|今天|上午|下午|晚上|早上|中午|凌晨|夜里|以前|之前|上次|那次)/g, '')
    .trim()
}

/** Date → YYYY-MM-DD */
function 日期串 (d) {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

/** 今天往前/后推 N 天 */
function 推日 (现在, 偏移) {
  const d = new Date(现在.getTime())
  d.setDate(d.getDate() + 偏移)
  return 日期串(d)
}

/**
 * 什么都没搜到时该怎么说。
 *
 * 只说「聊天里也没搜到」最省事，但用户看不出是「真没有」还是「你问的人
 * 对不上任何一个」—— 实测踩过（2026-11-04 截图）：鱼答「我没找到」，
 * 用户以为数据丢了，实际是同一个人改了名。
 */
function 没搜到的说明 (人原, 起, 止) {
  const 行 = ['聊天里也没搜到。']
  const 拆过 = 拆人名(人原)
  if (拆过.称谓) {
    行.push(`（历史记录里没有存过「${拆过.称谓}」这类身份 —— 记不了「谁是群主」，请改填具体昵称。）`)
  } else if (拆过.原文) {
    行.push(`（没有昵称含「${拆过.原文}」的消息。对方可能改过名，可以先用 person_list 看现用昵称。）`)
  }
  if (起 || 止) 行.push(`（日期范围：${起 || '不限'} ~ ${止 || '不限'}）`)
  return 行.join('\n')
}

/**
 * memory_recall 的执行体。
 *
 * @param {{args: object, 日记根: string, 仓库根: string, 说?: Function}} p
 */
export async function 跑检索 ({ args, 日记根, 仓库根, 分层库文件 = '', 导入目录 = '', 事件库文件 = '', 说 = () => {} }) {
  const 查 = String(args.query ?? '').trim()
  // ⚠️ query 不是唯一入口。
  //
  // 主人 2026-11-04 要求三种检索都支持：按事件问、按人问、按结果问。
  // 后两种根本不需要 query —— 「宝宝上次说要我做什么」查的是人，
  // 「那些最后没解决的事」查的是结果状态。
  // 原来这里一律要求 query 非空，实测把这两种检索直接挡死，报「query 不能为空」。
  const 有人 = String(args.人 ?? '').trim()
  const 要未解决 = args.只看未解决 === true
  const 要遗忘层 = args.只看遗忘层 === true
  // ⚠️ 四个入口都要算数。漏一个的表现是「传了这个参数却提示要你给条件」——
  // 实测踩过：加了 只看遗忘层 之后忘了把它算进这个判断，
  // 结果用户想看看有什么快被忘了，得到的却是「至少要给一个条件」。
  // ⚠️ 每加一个入口参数都要同步加到这里。
  // 漏了的表现是「传了参数却提示要你给条件」—— 已经踩过两次
  // （只看遗忘层、起/止+按时间）。只要有过召回行为就算数。
  const 有时间范围 = !!(String(args.起 ?? '').trim() || String(args.止 ?? '').trim())
  const 是按时间查 = args.按时间 === true
  // ⚠️ 这里必须在「拆询问」**之前**判断，但「拆询问」之后要复查一次。
  //
  // 实测踩过（2026-11-04）：query 给了「小鱼儿」这种只是人名的串，
  // 入口检查看到 query 非空就放行；接着拆询问把「小鱼儿」拆没了
  // （它只认「XX最后一句」这种骨架），剩余变成空串、人也是空 ——
  // 于是这次请求既没有人也没有关键词，却一路走到了按时间取，
  // 最后返回了当天所有消息，条件全丢。
  //
  // 所以要能接受两个形态：原始参数什么都没有，**或**拆完之后什么都没剩下。
  if (!查 && !有人 && !要未解决 && !要遗忘层 && !有时间范围 && !是按时间查) {
    return {
      找到: false, 命中数: 0, 下钻过: false, 下钻原因: '', 原文数: 0,
      text: [
        '至少要给一个条件：',
        '  query         搜什么',
        '  人            谁的',
        '  起 / 止       哪个日期范围（如 2026-11-03）',
        '  按时间        按时间倒序取最近几条（问「最后一句」用这个）',
        '  只看未解决    找没结论的事',
        '  只看遗忘层    看快被忘掉的事',
      ].join('\n'),
    }
  }
  // 来源：不传默认私聊（群聊里说的不一定是本人）
  const 原样 = String(args.来源 ?? '').trim()
  let 来源参数
  if (原样 === '*') 来源参数 = '*'
  // 「群聊」两个字也是合法输入：模型不知道群号时最容易这么填。
  // 以前这种写法会被当成「不认识的写法」落到默认值 private，
  // 用户明明要搜群聊，得到的却是私聊里查无此项。实测踩过。
  else if (/^(group|群聊|群)$/i.test(原样)) 来源参数 = 'group'
  else if (/^\d+$/.test(原样)) 来源参数 = `group:${原样}`
  else if (原样.startsWith('group:')) 来源参数 = 原样
  else 来源参数 = 'private'

  const limit = Math.max(1, Math.min(Number(args.limit) || 8, 30))
  const 深度 = String(args.深度 ?? 'auto').toLowerCase()

  // ── 把整句询问拆成「谁 / 什么时候 / 要什么」─────────────────────
  //
  // 主人 2026-11-04 第二张截图，鱼答「我没找到」。查下来真正的原因不是
  // 「最后一句」也不是「群主」—— 是**模型根本没按参数拆**。
  // 它最自然的做法是把整句话扔进 query：
  //
  //   memory_recall { query: "南瓜鸡昨晚最后一句说的什么" }
  //
  // 而检索层把整串当成一个关键词去和事件名做子串匹配，自然语言永远匹配不上，
  // 于是返回「命中 0 条」—— 和截图里那句「我没找到」一模一样。
  //
  // 所以这里先做一次纯规则的拆解（零成本、不调模型）：认出人名、相对日期、
  // 以及「最后一句」这类模式，转成后面各层真正认得的参数。
  // 参数里已经写了的，以参数为准，不覆盖。
  const 从查询 = 拆询问(查)
  // 拆完什么都不剩、也没有拆出任何条件 → 说明「查」本来就是个普通关键词/人名，
  // 原样保留，别把用户给的东西吃掉。（「小鱼儿」这种纯粹的人名就是这一类。）
  const 拆出条件 = !!(从查询.人 || 从查询.起 || 从查询.只看最近)
  const 用查 = (从查询.剩余 || '').trim() || (拆出条件 ? '' : 查)
  // ⚠️ 参数里没给「人」时，把 query 本身也当作人名候选 ——
  // 模型经常只把名字扔进 query（`{ query: "小鱼儿", 按时间: true }`），
  // 而 拆询问 只认「XX最后一句」这种骨架，光一个人名它拆不出人来。
  // 不补这一手，`按时间 + 止 + query:"小鱼儿"` 就会退化成「那天所有消息」，
  // 人这个条件被静默吞掉。实测踩过。
  const 起日0 = 规范日期(args.起) || 从查询.起
  const 止日0 = 规范日期(args.止) || 从查询.止
  const 按时间取 = args.按时间 === true || 从查询.只看最近 === true
  const 人有效 = 有人 || 从查询.人
    || (按时间取 && 查 && /^[\u4e00-\u9fa5A-Za-z0-9_]{2,12}$/.test(查) ? 查 : '')

  // ── 按时间取：直接在聊天原文上做 ──────────────────────────────────
  //
  // ⚠️ 必须放在「没有日记库就降级」**和事件层**之前。
  //
  // 实测踩过两次：
  //   ① 问「昨天最后一句说什么」时 query 为空，空 query 会直接掉进降级分支，
  //      「起/止/按时间」根本没机会执行 —— 用户拿到「聊天里也没搜到」，
  //      明明那条消息就在文件里。
  //   ② 带 按时间 + 人的请求被事件层先接走，事件层的「人」按参与人整串匹配
  //      对不上，返回 0，再落到聊天原文时「人」又被丢了 ——
  //      用户要「南瓜鸡昨晚最后一句」，拿到的是那天最后几条**所有人**的话。
  //
  // 按时间取不需要相关度、不需要索引、不需要事件，直接读那几天的聊天文件，
  // 所以放在所有其他逻辑之前是对的。
  const 只要某人0 = String(人有效 ?? '').trim()
  if (按时间取 === true && (起日0 || 止日0 || 只要某人0)) {
    try {
      const { 按时间读聊天 } = await import('./recall-ingest.js')
      const 条 = 按时间读聊天(仓库根, {
        来源: 来源参数,
        起: 起日0,
        止: 止日0,
        人: 只要某人0,
        上限: 从查询.要几条 || limit,
      })
      return 渲染时间结果({ 条, 仓库根, 来源参数, 起日0, 止日0, 只要某人0, 从查询, 按时间读聊天 })
    } catch (e) {
      说(`按时间查失败：${e?.message || e}`)
      // 失败就往下走原来的路，不要让一个可选能力把检索搞挂
    }
  }

  // ── 事件层优先 ───────────────────────────────────────────────────
  //
  // 事件是「一件事」，比「一条消息」更接近用户问的东西。
  // 实测对比：「上次说日记那事怎么定的」——
  //   查消息 → 返回 50 条零散的消息
  //   查事件 → 返回「【日记】群里 48 条讨论 10:22-11:35」一条，带起因和结论
  //
  // ⚠️ 事件层是**可选**的：没有 events.json（没跑过提炼）就自然跳过，
  // 检索退回原来的分层逻辑。不能因为事件层不存在就让整个检索失败。
  // ⚠️ 按时间查已经在上面的分支里 return 了，走不到这里；
  // 这里再判断一次是为了防以后有人调换顺序。
  //
  // 实测踩过（2026-11-04）：问「11-03 最后 3 句」，事件层先返回了
  // 【光顾着回话】这种相关度匹配的事件 —— 用户要的是「那天最后说了什么」，
  // 拿到的却是「和查询词最像的事」。
  // 事件层是按「一件事」组织的，它没有「最后一句」这个概念；
  // 要精确到句子，必须走聊天原文。
  if (事件库文件 && args.按时间 !== true) {
    try {
      const { 读事件库, 筛事件 } = await import('./recall-events-store.js')
      const 库 = 读事件库(事件库文件)
      if (库.事件们.length > 0) {
        // 三种检索方式都用上：查询词 + 人 + 未解决
        const 命中们 = 筛事件(库.事件们, {
          查询: 用查,
          // 事件层的人和消息层用的是同一套规则吗？不是 —— 这里必须用**完整昵称**。
          // 事件是靠名字命名的（「和龙娘讨论画图」），拿单个字去子串匹配，
          // 一个「鱼」字能命中几十条事件。宁可少匹配，不要乱匹配。
          人: 拆人名(String(args.人 ?? '').trim()).名,
          未解决: args.只看未解决 === true,
          来源: 来源参数 === '*' ? '' : 来源参数,
          // 只看遗忘层：快被忘掉的事单独列出来，让用户决定救回来还是彻底删
          只看遗忘层: args.只看遗忘层 === true,
          上限: limit,
        })
        // ⚠️ 命中 0 条不是终点，是「事件层帮不上忙」的信号。
        //
        // 实测踩过两次，方向相反：
        //   ① 以前是「命中 0 条也当答案返回」，看遗忘层时报「未配置日记库…」，
        //      用户不知道事件层参与了 —— 那条已经用「只看遗忘层」单独处理。
        //   ② 后来又矫枉过正：问「南瓜鸡昨晚最后一句说的什么」，事件层拿整串
        //      自然语言去子串匹配必然 0 命中，然后**直接返回**，
        //      后面明明能按时间从聊天原文查到，却连试都没试。
        //
        // 所以规则是：**命中 0 条就往下走**，让原文检索接着找。
        // 只要往下走了，最后的输出就来自原文层，用户看到的是真实结果，
        // 不会误以为「事件层没参与」—— 因为它本来就没给出东西。
        const 用事件层 = 库.事件们.length > 0 && 命中们.length > 0
        if (用事件层) {
          // 标题按实际条件拼：只按人查时不能写「搜索：（空）」。
          // 用户看到一串空条件会以为功能坏了。
          const 条件说 = [
            查 ? `「${查}」` : '',
            有人 ? `人=${有人}` : '',
            要未解决 ? '只看未解决' : '',
          ].filter(Boolean).join(' + ')
          const 行 = [`${条件说}（事件库 ${库.事件们.length} 条，命中 ${命中们.length} 条）`, '']
          for (const e of 命中们) {
            const 标 = e.提炼方式 === '日记' ? '日记' : e.提炼方式 === '话题' ? '群聊话题' : '聊天'
            // 日期与时间分开显示。
            // 日记事件的「起」是 ISO 时间戳（2026-11-03T05:35:16.754Z），
            // 直接拼在日期后面会变成「2026-11-03 2026-11-03T05:35...」这种鬼样子 ——
            // 实测就是这么显示的。这里把 ISO 提取成 HH:MM 再拼。
            const 起时间 = 转时分(e.起)
            const 止时间 = 转时分(e.止)
            const 时段 = 起时间 ? ` ${起时间}${止时间 && 止时间 !== 起时间 ? '-' + 止时间 : ''}` : ''
            // 遗忘层要显眼地标出来：用户在这里做决定（救回 / 彻底忘掉）
            const 标记 = e.遗忘层 ? ' 🗑 遗忘层' : ''
            行.push(`【${e.事件}】[${标}] ${e.日期}${时段}${标记}`)
            if (e.起因) 行.push(`  起因：${e.起因}`)
            for (const g of (Array.isArray(e.经过) ? e.经过 : []).slice(0, 2)) 行.push(`  经过：${g}`)
            if (e.结果) 行.push(`  结果：${e.结果.length > 80 ? e.结果.slice(0, 80) + '…' : e.结果}`)
            if (Array.isArray(e.参与人) && e.参与人.length) 行.push(`  参与：${e.参与人.slice(0, 5).join('、')}`)
            if (Array.isArray(e.标签) && e.标签.length) 行.push(`  标签：${e.标签.join(' ')}`)
            行.push('')
          }
          if (args.只看遗忘层 === true) {
            行.push('这些事已经很久没人提起了（第 12 层 = 遗忘层）。')
            行.push('救回来：memory_forget_events { 救回: ["事件名"] }')
            行.push('彻底忘掉：memory_forget_events { 彻底遗忘: ["事件名"] }')
          } else {
            // ⚠️ 事件被检索到了，要记下来 —— 否则时间衰减不可逆。
          //
          // 不记的话：事件一路下沉，沉到遗忘层就再也回不来，
          // 因为「被提及」这个本该救命的信号从来没被存过。
          // 用户明明搜到过、看过、用过，系统却当他从没问过。
          //
          // 失败只影响「下次该不该把这个事件算新鲜」，不影响这次结果 ——
          // 用户来是要答案的，不能因为记一笔失败就让他拿不到东西。
          if (args.只看遗忘层 !== true) {
            try {
              const { 记事件命中 } = await import('./recall-events-store.js')
              const r = await 记事件命中(事件库文件, 命中们)
              if (!r.ok) 说(`记录事件命中失败（不影响本次结果）：${r.错误}`)
            } catch (e) {
              说(`记录事件命中失败（不影响本次结果）：${e?.message || e}`)
            }
          }

          行.push('事件是提炼结果；需要原话时按上面的日期和时间去记忆仓库翻。')
          }
          return {
            找到: true,
            命中数: 命中们.length,
            下钻过: false,
            下钻原因: '',
            原文数: 0,
            text: 行.join('\n'),
          }
        }
      }
    } catch (e) {
      // 事件库坏了不该让检索失败 —— 记一笔然后走原来的路
      说(`事件层检索失败，退回分层检索：${e?.message || e}`)
    }
  }

  // ── 有日记库就查索引；没有就直接搜聊天 ─────────────────────────────
  const 日记条目 = 读日记(日记根, 导入目录)
  if (日记条目.length === 0) {
    // 降级：直接搜原始聊天。此时没法做「四因子打分」，
    // 但至少能回答「以前提过没有」。
    // ⚠️ 这里以前把「人」整个丢掉了，而且 来源='*' 会被当成「只搜群聊」。
    //
    // 实测踩过（2026-11-04 第二张截图）：用户问「南瓜鸡昨晚最后一句」，
    // 模型很可能不用 按时间，而是给 query 或 人 —— 只要 query 是空的，
    // 就会走到这条降级分支。改之前它既不认「人」，也不认「*」，
    // 用户得到的永远是「聊天里也没搜到」。
    const 降级人 = 拆人名(只要某人0).词们
    // ⚠️ 「只按人问」时，聊天检索层连一行都不会给。
    //
    // 实测踩过（2026-11-04 第二张截图）：模型完全可能不带 query、只带 人，
    // 这时 搜索记录 因为「没有关键词也没有日期」直接返回空 ——
    // 于是按人过滤拿到的是空集，「那个人明明说过话」却答「聊天里也没搜到」。
    // 只有人这一个条件时，就去读当天的（或最近的）聊天原文再筛。
    const 只按人 = 降级人.length > 0 && !用查 && !起日0 && !止日0
    let 命中 = []
    if (只按人) {
      命中 = await 按人翻聊天(仓库根, 来源参数, 降级人, limit)
    } else {
      命中 = await 搜聊天(仓库根, 查, {
        chatType: 来源参数 === '*' ? undefined : 来源参数 === 'private' ? 'private' : 'group',
        groupId: 来源参数.startsWith('group:') ? 来源参数.slice(6) : undefined,
        // 只有单向的日期过滤（没有 按时间）也在这里生效，否则起了/止了却不起作用
        起: 起日0 || undefined,
        止: 止日0 || undefined,
        limit: 降级人.length ? Math.max(limit * 4, 40) : limit,
      })
    }
    // 按人过滤放在拿到结果之后：聊天检索层只认 pid，不认昵称碎片
    if (降级人.length) 命中 = 命中.filter((h) => 昵称对得上(h.昵称, 降级人)).slice(0, limit)
    // 降级提示必须说清「损失了什么」，否则用户会以为这就是完整功能。
    // 实测少写这一层，用户搜不到重点时第一反应是「这插件不好用」，
    // 而不是「我少配了一项」。
    // 降级分支也要记命中：没配日记库的用户同样有分层库，
    // 他们的聊天索引也参与衰减。不记的话，这批用户的
    // 「被检索就回满层」这条规则永远不会生效 —— 只有降级路径
    // 的用户会觉得衰减机制"没装上"。实测踩过。
    if (命中.length > 0 && 分层库文件) {
      try {
        const { 读分层库, 写回命中 } = await import('./recall-ingest.js')
        const 库 = await 读分层库(分层库文件)
        const 时间集 = new Set(命中.map((h) => `${h.日期}\u0001${h.时间}`))
        const 命中条目 = 库.条目
          .filter((e) => e && e.指纹 && 时间集.has(`${e.日期}\u0001${e.时间}`))
          .map((e) => ({ ...e, lastHit: new Date().toISOString() }))
        if (命中条目.length) await 写回命中(分层库文件, 命中条目)
      } catch { /* 记账失败不影响返回 */ }
    }
    const 头 = 日记根
      ? `日记库里没有条目（${日记根}），已直接搜原始聊天。` +
        '\n注意：没有日记时，检索退化为纯关键词匹配 —— 没有四因子打分、没有时间衰减、也不会判断置信度。' +
        '\n想要完整的跨来源重点检索，需要配置日记库目录（支持小鱼日记的格式）。'
      : '未配置日记库目录，已直接搜原始聊天。' +
        '\n注意：没有日记时，检索退化为纯关键词匹配 —— 没有四因子打分、没有时间衰减、也不会判断置信度。' +
        '\n可在设置页填「日记库目录」启用完整检索；不填也能用，只是效果弱一些。'
    return {
      找到: 命中.length > 0,
      命中数: 命中.length,
      下钻过: true,
      下钻原因: '没有日记库，直接搜聊天原文',
      原文数: 命中.length,
      text: [头, 命中.length ? 渲染原文(命中) : 没搜到的说明(只要某人0, 起日0, 止日0)].join('\n'),
    }
  }

  // ── 并入分层后的聊天 ──────────────────────────────────────────────
  //
  // 聊天不直接进索引，而是走「分层库」：只有 memory_score_chats 跑过、
  // 且层级达标的条目才会并进来，并且带 层级 字段 —— rank.js 据此把
  // 聊天排在日记之后。
  //
  // 读不到分层库不是错误：没跑过分层就没有聊天条目，检索照常用日记。
  // 也不该因此报警 —— 分层是可选功能，默认就是没跑的。
  let 聊天条目 = []
  if (分层库文件) {
    try {
      const 库 = await 读分层库(分层库文件)
      聊天条目 = 并入索引条目(库.条目)
    } catch {
      聊天条目 = []
    }
  }
  const 索引 = 建索引([...日记条目, ...聊天条目])
  const 现在 = Date.now()
  // 印象分：影响排序但不改变「能不能搜到」——
  // 一个跟鱼互动多的人说的话排前面，但搜不到的东西不会因为印象分冒出来。
  let 印象表 = null
  try {
    const { 算印象分 } = await import('./recall-impression.js')
    const 全部条目 = 索引?.条目 || 索引?.index?.条目 || []
    // 只从聊天条目里取（日记条目的昵称字段是空的）
    const 有过艾特的 = 全部条目.filter((e) => /@/.test(String(e?.text || e?.内容 || '')))
    if (有过艾特的.length > 0) {
      印象表 = 算印象分(有过艾特的.map((e) => ({
        昵称: e.昵称 || '',
        内容: e.text || e.内容 || '',
        日期: e.日期 || '',
        时间: e.时间 || '',
      }))).按人
    }
  } catch { /* 印象分算不出来不影响检索 */ }

  // ── 时间范围 / 按时间取 ────────────────────────────────────────────
  //
  // 主人 2026-11-04 截图暴露的问题：问「搜群主昨天晚上最后一句说话的啥」，
  // 鱼翻了三次都没答对 —— 因为它根本没有「时间范围」和「按时间取」这两个概念。
  //
  // 三件事：
  //   起/止    只看某段日期的内容（闭区间）
  //   人       只看某个人说的话
  //   按时间   按时间倒序，不看相关度（问「最后一句」就用这个）
  const 起日 = 起日0
  const 止日 = 止日0
  const 只要某人 = String(人有效 ?? '').trim()

  // 先按日期/人过滤候选，再做相关度打分 —— 顺序不能反。
  // 反过来（先打分再过滤）会把大量时间外的条目算进来又丢掉，白算；
  // 更重要的是「按时间取」根本不看分数，先算分纯属浪费。
  let 候选 = 索引.条目
  if (起日 || 止日) {
    候选 = 候选.filter((e) => {
      const d = String(e?.日期 || e?.at || '').slice(0, 10)
      if (!d) return false // 没日期的没法判断在不在范围内，排除
      if (起日 && d < 起日) return false
      if (止日 && d > 止日) return false
      return true
    })
  }
  // 人的匹配用碎片（拆人名），不用整串相等：
  // 聊天条目存的是**当时**的昵称，人格天天改。实测同一个号一天内
  // 叫过「GPT6Astra / 龙娘 / 限时接入Claude / 魔丸」，用户用哪个名字问
  // 都该找得到。匹配规则和 按时间读聊天 共用同一套，两处不能各写一份。
  const 人词们 = 只要某人 ? 拆人名(只要某人).词们 : []
  if (人词们.length) {
    候选 = 候选.filter((e) => {
      const 谁 = String(e?.昵称 || '')
      // 空昵称的是日记条目，按人过滤时排除（日记不是「某人说的话」）
      return 谁 && 昵称对得上(谁, 人词们)
    })
  }
  const 索引用 = 候选 === 索引.条目 ? 索引 : { ...索引, 条目: 候选 }

  // 按时间取：不看相关度，直接按时间倒序。
  // 这是「最后一句」「最近说了什么」的正确解法 ——
  // 相关度排序回答不了「最后」，它只回答「最像」。
  if (按时间取) {
    const 排好 = 候选.slice().sort((a, b) => {
      const ta = String(a?.at || `${a?.日期 || ''}T${a?.时间 || '00:00:00'}`)
      const tb = String(b?.at || `${b?.日期 || ''}T${b?.时间 || '00:00:00'}`)
      return tb.localeCompare(ta)
    }).slice(0, limit)
    const 行 = []
    const 条件 = [起日 || 止日 ? `时间 ${起日 || '不限'} ~ ${止日 || '不限'}` : '', 只要某人 ? `人=${只要某人}` : '']
      .filter(Boolean).join('，')
    行.push(`按时间倒序${条件 ? '（' + 条件 + '）' : ''}：候选 ${候选.length} 条，取最近 ${排好.length} 条`)
    行.push('')
    for (const e of 排好) {
      const 时 = String(e?.at || `${e?.日期 || ''} ${e?.时间 || ''}`).replace('T', ' ')
      行.push(`[${时}] ${e?.昵称 || ''}：${String(e?.text || e?.内容 || '').slice(0, 200)}`)
    }
    if (排好.length === 0) {
      行.push('这个范围内没有内容。')
      // 同上：区分「范围里没事」和「你说的人对不上任何人」
      if (只要某人 && 候选.length === 0) {
        const 名 = 拆人名(只要某人)
        const 出现过的 = [...new Set(索引.条目.map((e) => String(e?.昵称 || '')).filter(Boolean))].slice(0, 20)
        if (名.称谓) {
          行.push(`历史记录里没有存过「${名.称谓}」这类身份 —— 记不了「谁是群主」，请改填具体昵称。`)
        } else {
          行.push(`「${只要某人}」没有匹配到任何条目。`)
        }
        if (出现过的.length) 行.push(`索引里出现过的人：${出现过的.join('、')}`)
      }
    }
    return { 找到: 排好.length > 0, 命中数: 排好.length, 下钻过: false, 下钻原因: '', 原文数: 0, text: 行.join('\n') }
  }

  const 结果 = 检索(索引用, 查, { 来源: 来源参数, limit, 现在, 印象表 })
  const 置信 = 判置信度(结果)

  // 记一次命中：进了返回结果就算「被检索过」，层级回到第 1 层。
  // 这一步有副作用（改 lastHit），所以放在检索出口，不放进纯函数的打分里。
  // 只有聊天条目有 lastHit 概念（日记是原文，不是索引条目）。
  if (结果.结果.length > 0) {
    try {
      const { 记命中 } = await import('./recall-decay.js')
      记命中(结果.结果, 索引.条目, 现在)
      // 写回分层库。只在「本次有命中且确实改到了东西」时才写，
      // 避免每次检索都重写一个 1.6MB 的 JSON（那是很贵的 IO）。
      // 两次检索之间进程重启会丢掉这一次的命中 —— 可以接受：
      // 丢一次命中最多让那几条晚一个月降级，不影响整体衰减正确性。
      if (分层库文件) {
        const { 写回命中 } = await import('./recall-ingest.js')
        const 命中条目 = 索引.条目.filter((e) => e && e.lastHit)
        await 写回命中(分层库文件, 命中条目)
      }
    } catch { /* 记命中/写回失败不影响本次返回 —— 检索结果比记账重要 */ }
  }

  const 头 = `搜索：${查}（来源：${来源参数 === '*' ? '全部' : 来源标签(来源参数)}）`
  const 统计 = 结果.命中数 > 0
    ? `命中 ${结果.命中数} 条，显示 ${结果.结果.length} 条 | 最高分 ${结果.分数分布.最高}`
    : '索引里没有命中'

  // ── 要不要下钻 ────────────────────────────────────────────────────
  const 要下钻 = 深度 !== 'off' && 置信.下钻
  let 原文 = []
  let 下钻原因 = 置信.理由
  if (要下钻) {
    try {
      原文 = await 搜聊天(仓库根, 查, {
        // '*' 是「全部来源」，不能落到「只搜群聊」
        chatType: 来源参数 === '*' ? undefined : 来源参数 === 'private' ? 'private' : 'group',
        groupId: 来源参数.startsWith('group:') ? 来源参数.slice(6) : undefined,
        起: 起日 || undefined,
        止: 止日 || undefined,
        limit: 10,
      })
      下钻原因 = `${置信.理由} → 已下钻，捞出 ${原文.length} 条原文`
    } catch (e) {
      下钻原因 = `${置信.理由} → 下钻失败：${e?.message || e}`
    }
  }

  const 段 = [头, 统计]
  if (结果.结果.length > 0) 段.push('', 渲染命中(结果.结果))
  if (原文.length > 0) 段.push(渲染原文(原文))
  段.push('', `判断：${下钻原因}`)

  return {
    找到: 结果.命中数 > 0 || 原文.length > 0,
    命中数: 结果.命中数,
    下钻过: 要下钻,
    下钻原因,
    原文数: 原文.length,
    text: 段.join('\n'),
  }
}

/**
 * memory_coverage 的执行体。
 *
 * @param {{args: object, 日记根: string, 仓库根: string, 说?: Function}} p
 */
export async function 跑覆盖率 ({ args, 日记根, 仓库根, 导入目录 = '', 说 = () => {} }) {
  const 日记条目 = 读日记(日记根, 导入目录)
  if (日记条目.length === 0) {
    return {
      ok: false, 聊天行数: 0, 日记条数: 0, 漏记数: 0,
      text: 日记根
        ? `日记库里没有条目（${日记根}），覆盖率检查需要日记做对照，暂时不可用。`
        : '未配置「日记库目录」，覆盖率检查需要日记做对照，暂时不可用。可在设置里填日记库路径。',
    }
  }

  const 聊天根 = path.join(仓库根, 'chat')
  const 行们 = []
  const 读了 = []

  // 收来源目录：不传就是 private + 所有群
  const 原样 = String(args.来源 ?? '').trim()
  const 目录们 = []
  if (!原样) {
    const 私 = path.join(聊天根, 'private')
    try { if (statSync(私).isDirectory()) 目录们.push(私) } catch { /* 没有私聊 */ }
    try {
      for (const g of readdirSync(path.join(聊天根, 'group'))) 目录们.push(path.join(聊天根, 'group', g))
    } catch { /* 没有群 */ }
  } else {
    const key = /^\d+$/.test(原样) ? `group:${原样}` : 原样
    目录们.push(key === 'private' ? path.join(聊天根, 'private') : path.join(聊天根, 'group', key.slice(6)))
  }

  const 走 = (dir) => {
    let names
    try { names = readdirSync(dir) } catch { return }
    for (const n of names.sort()) {
      const p = path.join(dir, n)
      let st
      try { st = statSync(p) } catch { continue }
      if (st.isDirectory()) { 走(p); continue }
      if (!n.endsWith('.txt')) continue
      try {
        行们.push(...读聊天行(readFileSync(p, 'utf8')))
        读了.push(n)
      } catch { /* 单个文件读不了就跳过，不让整个检查失败 */ }
    }
  }
  for (const d of 目录们) 走(d)

  if (行们.length === 0) {
    return {
      ok: false, 聊天行数: 0, 日记条数: 日记条目.length, 漏记数: 0,
      text: `记忆仓库里没读到聊天记录（${聊天根}）。覆盖率检查需要聊天做对照。`,
    }
  }

  const 词典 = await 载入词典()
  const 统计 = 统计聊天(行们, 词典)

  // 门槛自适应：样本少时死守 15 条会「报平安」，那比报噪声糟得多
  const 指定 = Number(args.最少消息)
  const 自动门槛 = 行们.length < 100 ? Math.max(2, Math.floor(行们.length / 8)) : 15
  const 生效门槛 = Number.isFinite(指定) && 指定 > 0 ? 指定 : 自动门槛
  const 自动人数 = 行们.length < 100 ? 1 : 3

  const 漏 = 找漏记(统计, 拼日记全文(日记条目), {
    词频: 词典.词频,
    最少提及: 生效门槛,
    最少人数: 自动人数,
    上限: Math.max(1, Math.min(Number(args.上限) || 20, 100)),
  })

  const 段 = [
    `覆盖率检查：读了 ${读了.length} 个聊天文件、${行们.length} 条消息，对账 ${日记条目.length} 条日记`,
    `词表：${词典.来源 || '未载入'}${词典.缺.length ? `（缺：${词典.缺.join('；')}）` : ''}`,
    `判定门槛：至少 ${生效门槛} 条消息、${自动人数} 个不同的人提过${行们.length < 100 ? '（样本少，已自动下调）' : ''}`,
  ]
  if (漏.length === 0) {
    段.push('', '没有发现漏记：聊得多的话题都在日记里出现过。')
  } else {
    段.push('', `发现 ${漏.length} 个「聊得多但从没记过」的话题：`, '')
    for (const x of 漏) 段.push(`· ${x.词} —— ${x.消息数} 条消息 / ${x.人数} 个人提过`)
    段.push('', '提示：这些是候选，不是「必须记」。值得记的用日记工具记下来；')
    段.push('只是口头禅或闲聊的忽略即可。')
  }

  return {
    ok: true,
    聊天行数: 行们.length,
    日记条数: 日记条目.length,
    漏记数: 漏.length,
    text: 段.join('\n'),
  }
}

/**
 * 把各种时间写法统一成 HH:MM。
 *
 * 事件里的时间来自三个地方，格式各不相同：
 *   · 聊天原文：'05:35:16'
 *   · 日记条目：'2026-11-03T05:35:16.754Z'（ISO）
 *   · 话题段：同样来自聊天原文
 * 显示时统一成 HH:MM，认不出来就返回空串（宁可少显示，不要显示一串乱码）。
 *
 * @param {string} t
 * @returns {string}
 */
function 转时分 (t) {
  const s = String(t ?? '').trim()
  if (!s) return ''
  // 已经是 HH:MM:SS 或 HH:MM
  const 短 = s.match(/^(\d{1,2}):(\d{2})/)
  if (短) return `${短[1].padStart(2, '0')}:${短[2]}`
  // ISO 时间戳
  const iso = s.match(/T(\d{2}):(\d{2})/)
  if (iso) return `${iso[1]}:${iso[2]}`
  return ''
}


/**
 * 把各种日期写法规范成 YYYY-MM-DD。认不出来返回空串。
 *
 * 支持：
 *   '2026-11-03'   原样
 *   '11-03'        补当前年份
 *   '11/03'        斜杠也认
 *
 * 为什么不做「昨天」「前天」这种：那需要知道「现在」是哪天，
 * 而模型传参数时更该直接算好日期 —— 让工具自己猜「昨天」，
 * 跨天、时区、服务器时间不准时全是坑。
 *
 * @param {string} v
 * @returns {string}
 */
export function 规范日期 (v) {
  const s = String(v ?? '').trim()
  if (!s) return ''
  let m = s.match(/^(\d{4})[-/](\d{1,2})[-/](\d{1,2})$/)
  if (m) return 拼日期(m[1], m[2], m[3])
  m = s.match(/^(\d{1,2})[-/](\d{1,2})$/)
  if (m) return 拼日期(new Date().getFullYear(), m[1], m[2])
  return ''
}

/**
 * 拼日期，并校验它真实存在。
 *
 * 为什么要校验：`2026-13-45` 格式完全对，但那天不存在。
 * 原样返回的话，过滤时会一条都匹配不上 —— 用户看到「这个范围内没有内容」，
 * 以为是数据问题，实际是日期写错了。宁可返回空串让调用方知道参数无效。
 */
function 拼日期 (年, 月原, 日原) {
  const 月 = Number(月原)
  const 日 = Number(日原)
  if (!(月 >= 1 && 月 <= 12)) return ''
  if (!(日 >= 1 && 日 <= 31)) return ''
  const t = new Date(Date.UTC(Number(年), 月 - 1, 日))
  if (Number.isNaN(t.getTime())) return ''
  // 回读校验：2026-02-30 会被 Date 归一成 3 月 2 日，回读就能发现
  const 规整月 = t.getUTCMonth() + 1
  const 规整日 = t.getUTCDate()
  if (规整月 !== 月 || 规整日 !== 日) return ''
  return `${年}-${String(月).padStart(2, '0')}-${String(日).padStart(2, '0')}`
}

