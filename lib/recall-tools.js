/**
 * 把用户给的「人」拆成真正用来匹配的关键词。
 *
 * 【为什么需要这个】
 *
 * 主人 2026-11-04 的第二张截图：他问「@鱼 南瓜鸡昨晚最后一句说的什么」，
 * 鱼回「我没找到，用『养鱼』搜也搜不出他昨晚最后那句」。
 *
 * 「最后一句」本身是对的 —— 真正断掉的是**前半截**：没有任何一条消息
 * 带着「群主」这个身份字段，所以「谁算群主」这一步从来没成功过。
 *
 * 退一步的做法是把「群主」当成昵称去匹配 —— 没用，那从来不是谁的昵称。
 * 再退一步是忽略这个词、返回全网最新的几条 —— 那是错的答案，比没有更坏。
 *
 * 所以这里做两件事：
 *   1. 认出「群主」「管理员」这类**身份称谓**（称谓）
 *   2. 把昵称按字截断，得到「南瓜」「瓜鸡」这类**可匹配的碎片** ——
 *      因为聊天行里存的是**当时的昵称**，而人天天改名。实测群 730783833
 *      里同一个号一天内叫过「GPT6Astra / 龙娘 / 限时接入Claude / 魔丸」，
 *      用户用哪个名字问都该找得到。
 *
 * @param {string} v 用户填的「人」
 * @returns {{原文:string, 称谓:string, 名:string, 词们:string[]}}
 */
export function 拆人名 (v) {
  const 原文 = String(v ?? '').trim()
  if (!原文) return { 原文: '', 称谓: '', 名: '', 词们: [] }
  // 「群主龙娘」这种：称谓在前，名在后
  // 「管理人」是「管理 人」，不是「管理员 人」—— 长的放前面才不会被截错
  const 掐头 = 原文.match(/^(群管理员|管理员|群主|管理|admin)\s*(.+)$/i)
  const 称谓 = 认身份(原文)
  let 名 = 原文
  if (称谓) {
    名 = ''
  } else if (掐头) {
    名 = 掐头[2].trim()
  }
  // 名字本身也可能只是「群主」「管理员」几个字（那谁都不是），
  // 这种碎片不能进匹配池，否则每个昵称里带「管理」的人都算他。
  const 假名 = new Set(['群主', '管理员', '管理', 'admin'])
  const 词们 = []
  if (名) {
    // 长的排前面：匹配时优先用完整名字
    for (let 长 = Math.min(4, 名.length); 长 >= 2; 长--) 词们.push(名.slice(0, 长))
    // 补上「跳过前缀」的碎片：「南瓜鸡」也能对上别的叫法
    for (let i = 1; i + 2 <= 名.length && i < 3; i++) 词们.push(名.slice(i))
  }
  const 去重 = [...new Set(词们)].filter((w) => w.length >= 2 && !假名.has(w.toLowerCase()))
  return { 原文, 称谓: 称谓 || (掐头 ? 认身份(掐头[1]) : ''), 名, 词们: 去重 }
}

/** 认身份称谓：群主 / 管理员。认不出返回空串。 */
export function 认身份 (v) {
  const s = String(v ?? '').trim()
  if (!s) return ''
  if (/^群\s*主$/.test(s)) return '群主'
  if (/^(群?管理员?|群管理|admin)$/i.test(s)) return '管理员'
  return ''
}

/**
 * 一条消息的昵称是否算「这个人」。
 *
 * 单独成函数是因为两个来源要共用同一套规则：
 * 聊天行里存的是**当时**的昵称（可能已经改了），人的主表里记的是**现在**的，
 * 两处都要能对上。
 */
export function 昵称对得上 (昵称, 词们) {
  const s = String(昵称 ?? '')
  if (!s) return false
  const 名单 = Array.isArray(词们) ? 词们 : [String(词们 ?? '')]
  return 名单.some((w) => w && s.includes(w))
}
