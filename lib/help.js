/**
 * 按用量算钱（单位：价格表里的币种，也就是美元）。
 *
 * 【为什么区分峰谷】官方峰谷差价正好一倍。一天的定时分层在中午和凌晨跑，
 * 差出来的钱是一半，不区分就等于系统性地多算或少算 50%。
 *
 * @param {{prompt:number, completion:number, 命中?:number}} 用量
 * @param {{入峰:number, 入谷:number, 出峰:number, 出谷:number, 命中峰:number, 命中谷:number}} 价
 * @param {{峰时?:boolean}} [选项]
 * @returns {number} 美元
 */
export function 算钱 (用量, 价, 选项 = {}) {
  const u = 用量 && typeof 用量 === 'object' ? 用量 : {}
  const p = 价 && typeof 价 === 'object' ? 价 : {}
  const 峰 = 选项.峰时 !== false
  const n = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0)
  const 入 = n(u.prompt)
  const 出 = n(u.completion)
  // 缓存命中部分单独计价。没上报命中就整段按未命中算 —— 宁可算贵一点：
  // 估算偏贵，用户顶多觉得「比想象中贵」；算偏便宜会让人以为不花钱，
  // 等看到真实账单时已经花出去了。这类数字必须往「保守」那边错。
  const 命中 = Math.min(n(u.命中), 入)
  const 未命中 = 入 - 命中
  const 入价 = 峰 ? n(p.入峰) : n(p.入谷)
  const 出价 = 峰 ? n(p.出峰) : n(p.出谷)
  const 命中价 = 峰 ? n(p.命中峰) : n(p.命中谷)
  return (未命中 * 入价 + 命中 * 命中价 + 出 * 出价) / 1e6
}

/**
 * 判断某个时刻是不是官方的高峰时段。
 *
 * 峰时按官方定义是 **UTC** 周一至周五 01:00–04:00 与 06:00–10:00。
 * 这里只管「星期 × 小时」，**不管中国法定节假日**（拿不到节假日表，
 * 也不该为了省几厘钱去联网拉）—— 所以节假日的估算会偏贵，这是有意的。
 *
 * @param {Date} [时刻] 默认现在
 * @returns {boolean}
 */
export function 是峰时 (时刻) {
  const t = 时刻 instanceof Date ? 时刻 : new Date()
  const 星期 = t.getUTCDay() // 0=周日
  if (星期 === 0 || 星期 === 6) return false
  const h = t.getUTCHours()
  return (h >= 1 && h < 4) || (h >= 6 && h < 10)
}

