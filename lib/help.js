/** 把结构化的帮助内容摊平成纯文本（给不支持富文本的地方、以及测试用）。 */
export function 帮助为文本 (内容 = 帮助内容) {
  const 行 = []
  for (const 节 of 内容) {
    if (节.标题) 行.push(`## ${节.标题}`)
    for (const p of 节.段落 || []) 行.push(p)
    for (const it of 节.条目 || []) 行.push(`· ${it.名}：${it.说明}`)
    if (节.标题) 行.push('')
  }
  return 行.join('\n').trim()
}
