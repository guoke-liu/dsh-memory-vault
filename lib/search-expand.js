// ============================================================================
// search-expand.js —— 中文近义扩展（纯函数，零依赖）
//
// 背景：切词() 用 2 字滑窗，query「宝宝不开心」→ [宝宝,宝不,不开,开心]，
// 而文档「今天宝宝很难过」只命中「宝宝」一个词，召回有盲区。
// 这里提供同义词组扩展：整词命中同义词组时，把组内其他词也加进查询词，
// 提高中文召回。二元组（滑窗产物）若不在任何同义词组里则不扩展，避免噪音。
//
// 纯函数：不读写文件、不改 globals，随便单测。
// ============================================================================

/**
 * 内置同义词组。每组是一个数组，组内词互相等价。
 * @returns {string[][]}
 */
export function 扩展词表() {
  return [
    ['不开心', '难过', '伤心', '难受', '郁闷', '委屈'],
    ['开心', '高兴', '快乐', '兴奋'],
    ['生气', '愤怒', '恼火'],
    ['累', '疲惫', '困'],
    ['害怕', '恐惧', '担心'],
    ['喜欢', '爱', '想'],
    ['考试', '测验'],
    ['宝宝', '宝贝'],
  ]
}

/**
 * 把 切词() 产出的词数组做近义扩展。
 * 规则：只对**整词命中**同义词组里某个词的项做扩展（二元组若不在任何
 * 同义词组里则天然不扩展，避免噪音）；原词全部保留；去重；保持顺序。
 *
 * @param {string[]} 词表 切词() 的输出
 * @returns {string[]} 扩展后的词数组（去重、保持顺序、原词全部保留）
 */
export function 扩展查询词(词表) {
  const 组 = 扩展词表()
  const 结果 = []
  const 见过 = new Set()
  for (const 词 of 词表) {
    if (typeof 词 !== 'string' || 词.length === 0) continue
    // 先加原词（保持顺序、去重）
    if (!见过.has(词)) { 结果.push(词); 见过.add(词) }
    // 找 词 整词命中的同义词组；命中则把组内其他词也加入
    for (const g of 组) {
      if (g.includes(词)) {
        for (const 同义词 of g) {
          if (!见过.has(同义词)) { 结果.push(同义词); 见过.add(同义词) }
        }
      }
    }
  }
  return 结果
}
