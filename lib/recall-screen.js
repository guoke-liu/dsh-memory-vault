// ============================================================================
// recall-screen.js —— 聊天消息分层筛选（规则版）
//
// 【这个模块负责什么】
//   给记忆仓库里的聊天消息打个「值不值得进检索库」的层级分。
//   三档：核心 / 有用 / 闲聊。纯规则，零依赖，不调任何模型。
//
// 【为什么这样设计】
//   · **这是默认路径，也是唯一必须存在的路径。**
//     开源用户可能根本没有模型 API —— 如果筛选依赖模型，这个功能对
//     一半用户就等于不存在。所以规则版是基本盘：它必须无依赖、离线可跑、
//     结果可解释。模型打分是在它之上的可选增强，不是替代。
//
//   · 为什么用规则而不是词表匹配：实测直接拿关键词判定，会把
//     「服务器好卡」和「服务器哪台」都判成技术讨论，但前者有信息、
//     后者是提问。所以规则看的是**句子的结构特征**：
//       有具体信息（长度、数字、专名、路径）> 有动作（答应了、定了、记得）
//       > 有情绪表达 > 纯应答。
//
//   · 为什么保留「闲聊」这一档而不是直接丢掉：检索时闲聊档仍然参与，
//     只是权重极低。丢掉的话，「谁说过一句玩笑」这种问题就彻底查不到了；
//     而用户真正想查的东西几乎不会只出现在闲聊档里，低权重已经够用。
//     真要屏蔽，调用方可以传 minLevel。
//
// 【对外导出】
//   · 分层 —— 三档常量
//   · 打分层(消息) —— 单条消息 → { 层级, 分, 命中特征 }
//   · 批量分层(消息们, 选项) —— 批量打分层
//   · 是机器人播报(内容) —— 供调用方预过滤
// ============================================================================

/** 三档层级。数字越大越重要。 */
export const 分层 = Object.freeze({
  闲聊: 0,
  有用: 1,
  核心: 2,
})

/** 层级的中文名，给日志和 UI 用。 */
export const 层级名 = Object.freeze({ 0: '闲聊', 1: '有用', 2: '核心' })

/**
 * 弱信号词：出现说明「可能在讨论事」，单靠它不足以升级。
 *
 * 收词原则：宽松。误收的代价只是多给一点分，
 * 而漏收会让真正的技术讨论掉进闲聊档 —— 后者代价大得多。
 */
const 话题词 = /服务器|部署|配置|安装|报错|错误|异常|崩了|重启|插件|接口|接口|脚本|代码|仓库|记忆|检索|日记|token|密钥|密码|账号|模型|接口|端口|域名|证书|备份|数据|数据库|日志|版本|更新|升级|修复|测试|调试|方案|架构|流程|规则|约定|决定|以后|下次|记得|说好|答应|定了|计划|安排|截止|提醒|别忘/

/** 应答词：整句几乎都是这些，就是闲聊。 */
const 应答词 = /^(嗯|恩|哦|噢|啊|哈|嘿|好|好的|行|行吧|可以|ok|OK|收到|了解|明白|对|是|是的|不是|没有|有|在|好的吧|好嘞|okay|yes|no|1|2|3|哈哈哈|哈哈|嘿嘿|呵|诶|唉|哎|草|笑死)$/

/** 机器人/系统播报特征（与 recall-coverage 的默认规则同源）。 */
const 播报特征 = [/^【[^】]{1,30}】/, /运行时长|状态[:：]|版本[:：]\s*\d/, /^https?:\/\//]

/**
 * 判断一条消息是不是机器人播报。
 *
 * @param {string} 内容
 * @returns {boolean}
 */
export function 是机器人播报 (内容, 规则) {
  const t = String(内容 || '').trim()
  if (!t) return true
  const r = 规则 && typeof 规则 === 'object' ? 规则 : 默认规则()
  const 源们 = Array.isArray(r.播报正则) ? r.播报正则 : []
  return 源们.some((源) => {
    const re = 编译(源)
    if (!re) return false
    try { return re.test(t) } catch { return false }
  })
}

/** 编译一个正则源码；失败返回 null（坏正则不该让整条流程崩）。 */
function 编译 (源) {
  if (源 instanceof RegExp) return 源
  try { return new RegExp(String(源)) } catch { return null }
}

/** 把内置默认规则转成与 recall-rules 一致的形状（避免循环依赖，这里抄一份）。 */
function 默认规则 () {
  return {
    话题词: 话题词.source,
    应答词: 应答词.source,
    约定词: '说好|答应|决定|定了|以后|下次|记得|别忘|截止|提醒|必须|约定',
    播报正则: 播报特征.map((r) => r.source),
    有用阈值: 2,
    核心阈值: 5,
  }
}

/**
 * 给一条消息打分层。
 *
 * 评分思路（每条都是实测定过的，不是拍的）：
 *   · 长度：短句几乎没有信息量。「嗯」「哈哈」占 16%（1369/8400），
 *     必须能被一句话刷掉。
 *   · 具体信息：数字、URL、路径、版本号、引号包起来的东西 —— 这些是
 *     「事实」的标志。「续费到下个月」「改 8080 端口」都带具体值。
 *   · 动作词：约定、决定、承诺。这类消息是日记最该记的东西。
 *   · 问句：提问本身不是知识，但「问什么」暴露了关注点，给一点点分。
 *     降权而不是归零 —— 有人问「那台机器怎么配的」，答案常在下一句。
 *
 * @param {{内容?: string, 昵称?: string, pid?: string}} 消息
 * @returns {{层级: number, 分: number, 特征: string[]}}
 */
export function 打分层 (消息, 规则) {
  const 原文 = String((消息 && 消息.内容) || '').trim()
  const 特征 = []
  // 规则可传入；不传就用内置默认（保持向后兼容，老调用点不必改）
  const r = 规则 && typeof 规则 === 'object' ? 规则 : 默认规则()

  if (!原文) return { 层级: 分层.闲聊, 分: 0, 特征: ['空'] }
  if (是机器人播报(原文, r)) return { 层级: 分层.闲聊, 分: -100, 特征: ['播报'] }

  // 应答词：整句就是这个 → 闲聊，不再往下算
  const 应答 = 编译(r.应答词)
  if (应答 && 应答.test(原文)) return { 层级: 分层.闲聊, 分: 0, 特征: ['应答'] }

  let 分 = 0

  // ① 长度
  const 长度 = 原文.length
  if (长度 >= 50) { 分 += 3; 特征.push('长') }
  else if (长度 >= 20) { 分 += 2; 特征.push('中长') }
  else if (长度 >= 10) { 分 += 1; 特征.push('短句') }
  else { 分 -= 1; 特征.push('极短') }

  // ② 具体信息
  if (/\d+/.test(原文)) { 分 += 1; 特征.push('数字') }
  if (/https?:\/\/|\.\w{2,4}\/|\/[a-z]+\//i.test(原文)) { 分 += 2; 特征.push('链接路径') }
  if (/「[^」]+」|"[^"]{2,}"/.test(原文)) { 分 += 1; 特征.push('引用') }

  // ③ 话题词（弱信号）
  const 话题 = 编译(r.话题词)
  const 话题命中 = 话题 ? 原文.match(话题) : null
  if (话题命中) { 分 += 2; 特征.push('话题:' + 话题命中[0]) }

  // ④ 动作/约定词（强信号，最高分）
  const 约定 = 编译(r.约定词)
  if (约定 && 约定.test(原文)) {
    分 += 3
    特征.push('约定')
  }

  // ⑤ 问句：给一点分，但不足以单独升级
  if (/[?？]/.test(原文)) { 分 -= 1; 特征.push('提问') }

  // ⑥ 纯表情/符号
  if (!/[\u4e00-\u9fa5a-zA-Z0-9]/.test(原文)) return { 层级: 分层.闲聊, 分: -5, 特征: ['符号'] }

  let 层级
  if (分 >= Number(r.核心阈值)) 层级 = 分层.核心
  else if (分 >= Number(r.有用阈值)) 层级 = 分层.有用
  else 层级 = 分层.闲聊

  return { 层级, 分, 特征 }
}

/**
 * 批量分层。
 *
 * @param {Array<{内容?: string}>} 消息们
 * @param {{最少层级?: number}} [选项] 最少层级以下的直接丢弃
 * @returns {Array<对象 & {层级:number, 分:number, 特征:string[]}>}
 */
export function 批量分层 (消息们, 选项 = {}) {
  const 最少 = Number((选项 && 选项.最少层级))
  const 门槛 = Number.isFinite(最少) ? 最少 : 分层.闲聊
  const 出 = []
  for (const m of Array.isArray(消息们) ? 消息们 : []) {
    const r = 打分层(m)
    if (r.层级 < 门槛) continue
    出.push({ ...m, 层级: r.层级, 分: r.分, 特征: r.特征 })
  }
  return 出
}

/**
 * 统计一批消息的分层分布，给日志与验收用。
 *
 * @param {Array<{层级:number}>} 消息们
 * @returns {{核心:number, 有用:number, 闲聊:number, 总数:number}}
 */
export function 分层分布 (消息们) {
  const 出 = { 核心: 0, 有用: 0, 闲聊: 0, 总数: 0 }
  for (const m of Array.isArray(消息们) ? 消息们 : []) {
    出.总数 += 1
    if (m.层级 === 分层.核心) 出.核心 += 1
    else if (m.层级 === 分层.有用) 出.有用 += 1
    else 出.闲聊 += 1
  }
  return 出
}
