/**
 * 建索引。
 *
 * df（document frequency）统计时**排除停用词**：停用词不进词表，
 * 分词时自然也不会把它们当候选词去贴。
 *
 * @param {Array<{来源:string, 日期:string, id:string, title?:string, text:string, tags?:string[], at?:string}>} 条目们
 * @returns {{条目: object[], df: Map<string, number>, 总数: number, 最长词表: Set<string>, 向量: Map<string, Float32Array>}}
 */
export function 建索引 (条目们) {
  const 条目 = Array.isArray(条目们) ? 条目们.filter((e) => e && typeof e === 'object') : []
  const 最长词表 = new Set()
  const df = new Map()

  // ── 第一步：收集候选词，按「在多少个不同段里出现」投票 ──────────────
  //
  // 为什么需要这一步：光靠长度截断管不住碎片。「服务器到期前」6 个字，
  // 是合法的中文前缀，但它显然不是词；「服务器」5 个字，是真词。
  // 长度分不出来，得看**它是不是反复独立出现**。
  //
  // 票源拆开计数，权重不同：
  //   · 标签票 ×3 —— 标签是人手工打的，最可信（「服务器」当标签出现过，
  //     那它就是词）
  //   · 段首票 ×2 —— 段首的前缀更可能是真词（中文词很少从句中冒出）
  //   · 段内票 ×1 —— 只作弱证据，句子碎片通常只能拿到这一票
  // 满分阈值 3：一个标签就能独立成立；一个段首词也成立；
  // 只在段中间出现过一次的碎片拿不到 3 分，进不了词表。
  const 票 = new Map()
  const 加票 = (w, n) => 票.set(w, (票.get(w) || 0) + n)

  for (const e of 条目) {
    // 标签：直接视为词，拿满票
    for (const t of (e.tags || [])) {
      const w = String(t).toLowerCase().trim()
      if (!w || 默认停用词.has(w)) continue
      if (!/^[a-z0-9\u4e00-\u9fa5]+$/.test(w)) continue
      加票(w, 3)
    }
    // 标题与正文：切段后，每个位置的前缀都按长度分档给票
    for (const 段 of 全部分段(e)) {
      for (let i = 0; i < 段.length; i++) {
        for (let len = 2; len <= 6 && i + len <= 段.length; len++) {
          const w = 段.slice(i, i + len)
          if (!/^[a-z0-9\u4e00-\u9fa5]+$/.test(w)) continue
          if (默认停用词.has(w)) continue
          // 长度越短越可信：「服务器」5 字比「服务器到期前」6 字更像词，
          // 因为越长的串越难在别处复现。所以短词给票，长词要复现给票。
          if (len <= 4) 加票(w, i === 0 ? 2 : 1)
          else 加票(w, i === 0 ? 2 : 1)
        }
      }
    }
  }

  // 第二步：过阈值的才是词。阈值 3 的含义：
  //   一个标签 = 3 票 → 成立
  //   一次段首出现 = 2 票 → 不够，需要再出现一次
  //   一次段中 = 1 票 → 要出现三次
  // 这条阈值让「服务器到期前」这种一次性碎片必然落选。
  const 阈值 = 3
  for (const [w, n] of 票) {
    if (n >= 阈值) 最长词表.add(w)
  }
  // 兜底：一条数据都没有真人标签时，阈值可能把整个词表清零。
  // 此时退化为「所有 2 字窗都算词」—— 相当于旧的滑窗行为，不会更差。
  if (最长词表.size === 0) {
    for (const e of 条目) for (const w of 切词(拼全文(e))) if (!默认停用词.has(w)) 最长词表.add(w)
  }

  // 第三步：df 用「有多少条日记包含这个词」统计。
  // 用 subsequ 判断而不是重新分词，避免依赖词表状态。
  for (const e of 条目) {
    const 全文 = 拼全文(e)
    for (const w of 最长词表) {
      if (全文.includes(w)) df.set(w, (df.get(w) || 0) + 1)
    }
  }

  const 索引 = { 条目, df, 总数: 条目.length, 最长词表, 向量: new Map() }
  for (const e of 条目) 索引.向量.set(e.id, 嵌入(拼全文(e), 索引))
  return 索引
}

/** 把标题+正文+标签拼成一段待切词的文本。 */
function 拼全文 (e) {
  return `${e.title || ''} ${e.text || ''} ${(e.tags || []).join(' ')}`
}

/**
 * 条目里有意义的「词段」：标题、正文、每个标签，以及正文里被标点切开的短句。
 *
 * 为什么要把它们拆开而不是整段当文本：最长匹配词表的词源必须是**真实
 * 边界的词**。如果把「腾讯云轻量服务器续费」整段丢进去，能收到的词只有
 * 2 字窗（服务/务器…），永远不会有「服务器」——因为没有任何一段正好是
 * 「服务器」到「服务器」。而标签「服务器」、正文里「服务器到期前」被
 * 逗号和句号切出的「服务器到期前」，才是「这个词真实出现过」的证据。
 *
 * 做法：以标点/空白为界切段，每段从每个起点取长度 2..8 的前缀都收进表。
 * 前缀而非子串 —— 中文词几乎总在段首或紧跟标点后，「量服务器」这种
 * 段中间的截断不是词，「服务器」在段首才能被收到。
 *
 * @param {object} e
 * @returns {string[]}
 */
function 全部分段 (e) {
  const 段 = []
  for (const s of [e.title || '', e.text || '', ...(e.tags || [])]) {
    const 串 = String(s).toLowerCase()
    for (const m of 串.matchAll(/[^\s\p{P}\p{S}]+/gu)) 段.push(m[0])
  }
  return 段
}

/**
 * 独立出现过的词：标签本身，或某一段的全部就是它。
 *
 * 这类词才有资格进「最长匹配」的第一优先级。像「腾讯云轻量服务器」
 * 这种在标题里连续出现的组合，虽然也是段内前缀，但它不是独立词条，
 * 让它参与最长匹配就会把「服务器」吞掉 —— 用户搜「服务器」时
 * 词面分反而算 0。宁可让它被拆成「腾讯云 / 轻量 / 服务器」。
 *
 * @param {object} e
 * @returns {Set<string>}
 */
function 独立词 (e) {
  const 出 = new Set()
  for (const t of (e.tags || [])) {
    const w = String(t).toLowerCase().trim()
    if (w) 出.add(w)
  }
  for (const 段 of 全部分段(e)) {
    if (段.length >= 2 && 段.length <= 6) 出.add(段)
  }
  return 出
}

/**
 * 把一段连续文字的所有前缀（长度 2..8）收进词表。
 *
 * 停用词不收：它不该成为最长匹配的命中目标。
 *
 * @param {string} 段
 * @param {Set<string>} 表
 */
function 收词进表 (段, 表) {
  // 上限 6 字而不是 8：中文实词极少超过 6 字，放到 8 会把
  // 「服务器到期前要续」这种半句话收成「词」，最长匹配优先贴它，
  // 反而把真正的词「服务器」吞掉。宁可少收长词，不可收句子碎片。
  for (let i = 0; i < 段.length; i++) {
    for (let len = 2; len <= 6 && i + len <= 段.length; len++) {
      const w = 段.slice(i, i + len)
      if (!/^[a-z0-9\u4e00-\u9fa5]+$/.test(w)) continue
      if (默认停用词.has(w)) continue
      表.add(w)
    }
  }
}

/**
 * 最长匹配分词：从左到右，每个位置取「词表里存在的最长子串」，
 * 取不到就前进一个字符。
 *
 * 为什么最大候选长度限 8：中文实词极少超过 8 字，不设上限会让每个位置
 * 都去做一次长串查找，数据量大时是纯粹的浪费。
 *
 * 为什么取不到要跳一个字符而不是整段放弃：遇到生词（人名、型号、新造词）
 * 时，只跳过生词的首字，后面的「服务器」还能正常贴上。整段放弃会让一句
 * 话停在第一个生词上。
 *
 * 停用词在这里丢弃，不进入返回结果 —— 它挡的是「分词走向」，不是粗暴删词。
 *
 * @param {string} 文本
 * @param {{最长词表?: Set<string>}} [索引]
 * @returns {string[]} 去重后的词
 */
export function 分词 (文本, 索引, 选项 = {}) {
  const 串 = String(文本 || '').toLowerCase()
  const 表 = 索引 && 索引.最长词表 instanceof Set ? 索引.最长词表 : null
  if (!表 || 表.size === 0) {
    // 没有词表就退回滑窗，至少不比旧行为差
    return 切词(串).filter((w) => !默认停用词.has(w))
  }
  // 偏好词：查询侧要的是「查询里真实出现的词」，不该被库里某个长词整段吞掉。
  // 例如库里记了「腾讯云轻量服务器」这一整词，搜「服务器」时若也贴成
  // 那个长词，词面分就永久为 0 —— 用户明明搜了这个词却算没命中。
  // 所以查询侧先算出自己的滑窗词，贴词时优先贴这些。
  const 偏好 = 选项 && 选项.偏好 instanceof Set ? 选项.偏好 : null
  const 出 = new Set()
  let i = 0
  while (i < 串.length) {
    let 命中 = ''
    const 上限 = Math.min(8, 串.length - i)
    // 第一轮：只找偏好词里的最长命中（查询侧用）
    if (偏好 && 偏好.size) {
      for (let len = 上限; len >= 2; len--) {
        const 段 = 串.slice(i, i + len)
        if (偏好.has(段) && 表.has(段)) { 命中 = 段; break }
      }
    }
    // 第二轮：常规最长匹配
    if (!命中) {
      for (let len = 上限; len >= 2; len--) {
        const 段 = 串.slice(i, i + len)
        if (表.has(段)) {
          命中 = 段
          break
        }
      }
    }
    if (命中) {
      if (!默认停用词.has(命中) && !/[\s\p{P}]/u.test(命中)) 出.add(命中)
      i += 命中.length
    } else {
      // 单位和英文/数字整词也收，否则「24」「d1」这类会被完全丢掉；
      // 中文单字多半是碎片，收了反而污染，所以中文单字一律跳过。
      const ch = 串[i]
      if (/[a-z0-9]/.test(ch)) {
        let j = i
        while (j < 串.length && /[a-z0-9]/.test(串[j])) j++
        const 词 = 串.slice(i, j)
        if (词.length >= 2 && !默认停用词.has(词)) 出.add(词)
        i = j
      } else {
        i += 1
      }
    }
  }
  return [...出]
}

/**
 * 本地哈希向量（signed hashing trick）。
 *
 * 为什么带符号：纯正数哈希下，两个无关词撞到同一维会互相「加温」，产生假相似；
 * 带符号时碰撞有一半概率互相抵消，高维下期望贡献为 0。
 *
 * 为什么要 IDF 加权：向量里若把「的」和「腾讯云」等权，任何两句中文都长得像。
 * 用 1/log(2+df) 加权后，高频虚词的贡献被压到接近零。
 *
 * @param {string} 文本
 * @param {{分词?: Function, df?: Map<string,number>, 最长词表?: Set<string>}} [索引]
 * @returns {Float32Array}
 */
export function 嵌入 (文本, 索引) {
  const 向量 = new Float32Array(EMBED_DIM)
  const 词们 = 分词(文本, 索引)
  if (词们.length === 0) return 向量
  const df = 索引 && 索引.df instanceof Map ? 索引.df : new Map()
  for (const 词 of 词们) {
    const n = df.get(词) || 1
    const 权 = 1 / Math.log(2 + n)
    const h = fnv1a(词)
    const 位 = h % EMBED_DIM
    // 取哈希的另一个独立部分决定正负：直接复用 h 的奇偶会和位分配相关，
    // 用 h2 更独立
    const h2 = fnv1a(词 + '\u0000s')
    const 号 = (h2 & 1) === 0 ? 1 : -1
    向量[位] += 号 * 权
  }
  // L2 归一化；全零直接返回（避免 0/0 = NaN）
  let 平方和 = 0
  for (let i = 0; i < EMBED_DIM; i++) 平方和 += 向量[i] * 向量[i]
  if (平方和 <= 0) return 向量
  const 模 = Math.sqrt(平方和)
  for (let i = 0; i < EMBED_DIM; i++) 向量[i] /= 模
  return 向量
}

/** FNV-1a 32 位哈希。零依赖、分布够用、确定性强（同样的词永远落同一维）。 */
function fnv1a (s) {
  let h = 0x811c9dc5
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    // 乘 16777619 用移位加法避免 32 位溢出精度问题
    h = (h + (h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24)) >>> 0
  }
  return h >>> 0
}

/**
 * 余弦相似度，clamp 到 [0,1]。
 *
 * 为什么负值一律算 0：这里的向量全由非零权重构成，负余弦只出现在哈希碰撞
 * 的偶然抵消里，没有任何「相反语义」的含义。留着负值会让无关条目拿到
 * 负分，反而拉低排序的稳定性。
 *
 * @param {Float32Array|number[]} a
 * @param {Float32Array|number[]} b
 * @returns {number} [0,1]
 */
export function 余弦 (a, b) {
  if (!a || !b || a.length !== b.length || a.length === 0) return 0
  let 点 = 0
  let 甲 = 0
  let 乙 = 0
  for (let i = 0; i < a.length; i++) {
    点 += a[i] * b[i]
    甲 += a[i] * a[i]
    乙 += b[i] * b[i]
  }
  if (甲 <= 0 || 乙 <= 0) return 0
  const 值 = 点 / (Math.sqrt(甲) * Math.sqrt(乙))
  if (!Number.isFinite(值)) return 0
  return Math.min(1, Math.max(0, 值))
}

/** 条目「几天前」：优先 at，退化到 日期；未来时间按 0 天算。 */
function 天数差 (条目, 现在) {
  const 原 = 条目.at || 条目.日期 || ''
  if (!原) return 0
  const t = Date.parse(原)
  if (!Number.isFinite(t)) return 0
  const 毫秒 = Math.max(0, 现在 - t)
  return 毫秒 / 86400000
}

/**
 * 单条三因子打分。
 *
 * 四个分项先各自算，再按权重加权。min-max 归一化需要「全集」视野：
 * 传了 `选项.全集`（一批条目的同名字段值）就按全集归一化，没传就各自
 * clamp 到 [0,1]。**没传全集的分数只适合单条预览，不适合跨条目比较。**
 *
 * @param {object} 条目
 * @param {{词表: string[], 查询向量: Float32Array}} 查询
 * @param {object} 选项
 * @param {{词面?:number, 向量?:number, 时效?:number, 重要度?:number}} [选项.权重]
 * @param {number} [选项.现在]
 * @param {{词面?:{最小:number,最大:number}, 向量?:{最小:number,最大:number}, 时效?:{最小:number,最大:number}, 重要度?:{最小:number,最大:number}}} [选项.全集]
 * @returns {{总分:number, 词面分:number, 向量分:number, 时效分:number, 重要度分:number}}
 */
export function 三因子打分 (条目, 查询, 选项 = {}) {
  const { 权重, 现在 = Date.now(), 全集, df } = 选项 || {}
  const 权 = 归一权重(权重)

  // ── 词面分：命中词的 IDF 占总 IDF 的比例 ──────────────────────────
  const 标题 = String(条目.title || '').toLowerCase()
  const 正文 = String(条目.text || '').toLowerCase()
  const 标签 = (条目.tags || []).map((t) => String(t).toLowerCase())
  let 总IDF = 0
  let 得IDF = 0
  const dfMap = df instanceof Map ? df : new Map()
  const 总数 = 选项.总数 || 1
  for (const w of 查询.词表 || []) {
    // ⚠️ df 查不到 ≠ df=1。
    //
    // 这是最容易写错的一行：`dfMap.get(w) || 1` 会把「语料里根本没有这个词」
    // 当成「这词只出现过一次」—— 也就是**最高的 IDF**。结果搜一个库里不存在的
    // 词，每条含该碎片的日记都拿到满分词面分，看起来像搜到了。
    // 语料里没有的词，它的 df 应该是 0，IDF 应该为 0（它不可能命中任何条目）。
    const 词df = dfMap.get(w)
    if (词df === undefined) continue
    const idf = Math.log((总数 + 1) / (词df + 0.5))
    const 有效 = Math.max(0, idf)
    总IDF += 有效
    let 加成 = 0
    if (正文.includes(w)) 加成 = 1
    if (标题.includes(w)) 加成 = Math.max(加成, 1.5)
    if (标签.some((t) => t === w || t.includes(w))) 加成 = Math.max(加成, 2)
    if (加成 > 0) 得IDF += 有效 * 加成
  }
  const 词面原 = 总IDF > 0 ? 得IDF / 总IDF : 0

  // ── 向量分 ────────────────────────────────────────────────────────
  const 向量原 = 余弦(条目向量取(条目, 选项), 查询.查询向量)

  // ── 时效分：每天 0.995 的指数衰减 ─────────────────────────────────
  const 时效原 = Math.pow(0.995, 天数差(条目, 现在))

  // ── 重要度分 ──────────────────────────────────────────────────────
  // ── 重要度：分层加权 ────────────────────────────────────────────
  //
  // 两类条目在同一套分数里竞争，但可信度不同：
  //   · 日记（没有 层级 字段）—— 人筛过才记的，重要度基线 0.5～1
  //   · 聊天（带 层级 0/1/2）—— 机器筛的，基线按档次给，且整体更低
  //
  // 为什么聊天必须更低：一条未被筛过的原话，内容再相关也不该压过
  // 一条被主人亲手记下的结论。实测混入 2479 条聊天后，搜「记忆仓库」
  // 排第一的变成了聊天原话，把「原话也留得住了」那条日记挤下去了 ——
  // 那不是用户想先看到的。
  //
  // 但也不能压成 0：聊天是「补充」，要能被搜到，只是排在日记之后。
  // 档次 2（核心）/1（有用）/0（闲聊）分别给 0.34 / 0.22 / 0.10，
  // 最高档也只有日记基线的一半多一点。
  let 重要度原
  if (Number.isFinite(Number(条目.层级))) {
    const lv = Math.max(0, Math.min(2, Math.round(Number(条目.层级))))
    重要度原 = [0.10, 0.22, 0.34][lv]
  } else {
    重要度原 = (条目.tags || []).length > 0
      ? Math.min(1, (条目.tags || []).length / 3)
      : 0.5
  }

  // ── 分层系数先乘到原始信号上，再做归一化 ─────────────────────────
  //
  // 为什么顺序这么重要：min-max 归一化会把「同批里的最大值」拉成 1。
  // 若先归一化再乘惩罚，2537 条聊天里的头名照样是 1，然后乘 0.75 还是
  // 比日记高 —— 惩罚形同虚设。而先把聊天的原始信号压下去，归一化的
  // 基准仍然是日记占优，顺序才真正起作用。
  //
  // 实测：不加这一步，单条聊天（0.701）能压过日记（0.692）；
  // 2537 条聊天一起进来时，前五名全是聊天。
  const 是聊天 = Number.isFinite(Number(条目.层级))
  const lv = 是聊天 ? Math.max(0, Math.min(2, Math.round(Number(条目.层级)))) : -1
  const 层系数 = 是聊天 ? [0.4, 0.6, 0.75][lv] : 1

  const 词面分 = 归一(词面原 * 层系数, 全集 && 全集.词面)
  const 向量分 = 归一(向量原 * 层系数, 全集 && 全集.向量)
  const 时效分 = 归一(时效原 * 层系数, 全集 && 全集.时效)
  // ⚠️ 重要度**不做 min-max 归一化**，只用绝对值。
  //
  // 实测踩到：日记重要度 0.5、聊天核心档 0.34，两者都在 [0,1] 区间。
  // 一旦做 min-max，这一维里最大值是 0.5（日记）、最小值 0.34（聊天），
  // 归一后聊天变 0、日记变 1 —— 本来只是想「压低聊天」，结果把
  // 「差距」放大成了「全有全无」，而且当同批只有聊天时（最常见的情况），
  // 归一化会给其中一条 1 分，看起来像「这条聊天非常重要」。
  //
  // 重要度的语义本来就是一个**绝对的先验**（日记比聊天可信），
  // 不该随同批其他条目浮动。所以这里直接用原值。
  const 重要度分 = Math.min(1, Math.max(0, Number.isFinite(重要度原) ? 重要度原 : 0))

  const 基础分 = 权.词面 * 词面分 + 权.向量 * 向量分 + 权.时效 * 时效分 + 权.重要度 * 重要度分

  // ── 分层惩罚：聊天整体乘一个系数 ──────────────────────────────────
  //
  // 光靠「重要度」这一维拉不开差距：它只占 10% 权重，聊天就算压到 0.34，
  // 跟日记的 0.5 也只差几分之一个 10%，实际排序几乎打平（实测 0.483 对 0.484）。
  // 而设计目标是「日记永远优先」，那必须是结构性的，不是微调。
  //
  // 所以对聊天再乘一个系数：核心档 0.75、有用档 0.6、闲聊档 0.4。
  // 效果：词面、向量都相同的情况下，日记必然排在聊天前面；
  // 而聊天要压过日记，得有明显更高的相关性（比如日记只擦边命中，
  // 聊天完整命中关键词）—— 这正是我们想要的交换条件。
  const 总分 = 基础分
  return { 总分, 词面分, 向量分, 时效分, 重要度分, 基础分 }
}

/** 条目向量：优先取索引预计算的，没给索引就现算。 */
function 条目向量取 (条目, 选项) {
  if (选项 && 选项.条目向量 instanceof Map) {
    const v = 选项.条目向量.get(条目.id)
    if (v) return v
  }
  return 嵌入(`${条目.title || ''} ${条目.text || ''} ${(条目.tags || []).join(' ')}`, 选项 && 选项.索引)
}

/** 权重归一：和不为 1 时按比例缩放；非法值回退默认。 */
function 归一权重 (权重) {
  const 合 = { ...默认权重, ...(权重 && typeof 权重 === 'object' ? 权重 : {}) }
  const 键 = Object.keys(默认权重)
  let 和 = 0
  for (const k of 键) {
    const v = Number(合[k])
    合[k] = Number.isFinite(v) && v >= 0 ? v : 默认权重[k]
    和 += 合[k]
  }
  if (和 <= 0) return { ...默认权重 }
  for (const k of 键) 合[k] /= 和
  return 合
}

/**
 * min-max 归一化。
 *
 * 没给范围时退化为 clamp —— 这是有意的降级：单条打分没有「同批其他条目」
 * 可参照，硬造一个 0..1 的范围反而是假精度。
 */
function 归一 (值, 范围) {
  const v = Number.isFinite(值) ? 值 : 0
  if (范围 && Number.isFinite(范围.最小) && Number.isFinite(范围.最大)) {
    if (范围.最大 - 范围.最小 <= 1e-12) {
      // ⚠️ 全批同值时不能一律给 0.5。
      //
      // 全批都是 0，意思是**这一维谁都没命中**（比如搜一个库里没有的词，
      // 所有条目的词面分都是 0）。此时给 0.5 等于宣布「每条都中了一半」，
      // 于是每条日记都能靠时效和重要度凑出个像样的总分，搜什么都能
      // 「搜到」73 条。这是最坏的失败模式：结果非空、看起来正常、全是错的。
      //
      // 正确的处理：全批都等于 0 就返回 0（这一维不贡献）；
      // 全批等于同一个非零值，说明这一维对所有条目无区分度，
      // 给 0.5 才是中位处理（不偏袒任何一条）。
      return Math.abs(范围.最大) <= 1e-12 ? 0 : 0.5
    }
    return Math.min(1, Math.max(0, (v - 范围.最小) / (范围.最大 - 范围.最小)))
  }
  return Math.min(1, Math.max(0, v))
}

/**
 * 来源 key 的人读标签。
 *
 * 'private' → '私聊'，'group:730783833' → '群 730783833'，其它原样返回。
 * 认不出的不猜 —— 猜错比原样显示更难排查。
 *
 * @param {unknown} s
 * @returns {string}
 */
export function 来源标签 (s) {
  const t = String(s ?? '')
  if (t === 'private') return '私聊'
  if (t.startsWith('group:')) return `群 ${t.slice(6)}`
  return t
}

/** 来源排序键。与 recall.js 同规矩：私聊在前，群按数字序。 */
function 来源序 (s) {
  const t = String(s ?? '')
  if (t === 'private') return [0, 0, '']
  if (t.startsWith('group:')) {
    const 号 = t.slice(6)
    return [1, /^\d+$/.test(号) ? Number(号) : Number.MAX_SAFE_INTEGER, 号]
  }
  return [1, Number.MAX_SAFE_INTEGER, '']
}

/**
 * 检索：过滤 → 逐条打分 → 排序 → 截断。
 *
 * 归一化分两步走：先对**整批候选**算各分项的 min/max，再用同一套范围
 * 给每条归一 —— 这正是 min-max 的要求，逐条独立归一等于放弃比较。
 *
 * @param {ReturnType<typeof 建索引>} 索引
 * @param {string} query
 * @param {object} [选项]
 * @param {number} [选项.limit]
 * @param {string|string[]} [选项.来源]
 * @param {string} [选项.tag]
 * @param {number} [选项.最低分] 低于这个总分的直接丢弃，默认 0.05
 * @param {number} [选项.现在]
 * @param {object} [选项.权重]
 * @returns {{结果: object[], 命中数: number, 平均分: number, 分数分布: {最高:number,最低:number,中位数:number}, 查询词: string[]}}
 */
export function 检索 (索引, query, 选项 = {}) {
  const { limit = 20, 来源, tag, 最低分 = 0.05, 现在 = Date.now(), 权重 } = 选项 || {}
  const 全条目 = (索引 && Array.isArray(索引.条目)) ? 索引.条目 : []

  // 来源 / 标签过滤
  //
  // '*' 是「全部来源」的写法，必须在这里就展开成真实来源列表。
  // 直接拿 '*' 去 includes 会一条都匹配不上 —— 表面上像「过滤后没结果」，
  // 实际是参数语义没兑现，这种静默空结果最难排查。
  const 原样来源 = Array.isArray(来源) ? 来源.filter(Boolean).map(String) : (来源 ? [String(来源)] : [])
  const 全部 = 原样来源.some((x) => x === '*' || x.toLowerCase() === 'all')
  const 来源组 = 全部
    ? [...new Set(全条目.map((e) => String(e.来源 ?? '')).filter(Boolean))]
    : 原样来源
  let 候选 = 全条目
  if (!全部 && 来源组.length) 候选 = 候选.filter((e) => 来源组.includes(String(e.来源 ?? '')))
  if (tag) {
    const t = String(tag).toLowerCase().trim()
    if (t) 候选 = 候选.filter((e) => (e.tags || []).some((x) => String(x).toLowerCase().includes(t)))
  }

  // 查询词与查询向量
  const 查询词 = 分词查询(query, 索引)
  let 查询向量 = 嵌入(query, 索引, { 分词器: 分词查询 })
  // ⚠️ 只有**真的没输查询**才走列举模式。
  // 输了一个词但它不在词表里（生词、新词、错字）时，绝不能也返回全部 ——
  // 那是「假装搜到了」。此时应退回 2 字滑窗去贴，贴着能命中就按它打分，
  // 一个都贴不到就老实返回 0 命中。
  const 原始查询非空 = String(query ?? '').trim().length > 0
  if (查询词.length === 0 && 原始查询非空) {
    // 退回滑窗：至少把查询里的 2 字窗拿来当词。
    // 向量也得跟着重算 —— 否则查询向量还是零，向量分恒为 0，
    // 「兜底」只是换了个名头的空操作。
    // 兜底词必须在语料里真实存在（df 里查得到）才算数。
    // 否则 df 取不到 → IDF 被算成最高值 → 每条含碎片的日记都拿高分，
    // 搜一个不存在的词会「召回」全部日记。这是最坏的失败模式：
    // 用户以为搜到了，拿到的是全部内容。
    const df表 = 索引 && 索引.df instanceof Map ? 索引.df : new Map()
    const 兜底词 = 切词(query).filter((w) => !默认停用词.has(w) && df表.has(w))
    if (兜底词.length > 0) {
      查询词.push(...兜底词)
      const 兜底向量 = new Float32Array(EMBED_DIM)
      const df = 索引 && 索引.df instanceof Map ? 索引.df : new Map()
      for (const 词 of 兜底词) {
        const n = df.get(词) || 1
        const 权 = 1 / Math.log(2 + n)
        const idx = fnv1a(词) % EMBED_DIM
        const 号 = (fnv1a(词 + '\u0000s') & 1) === 0 ? 1 : -1
        兜底向量[idx] += 号 * 权
      }
      let 平方和 = 0
      for (let i = 0; i < EMBED_DIM; i++) 平方和 += 兜底向量[i] * 兜底向量[i]
      if (平方和 > 0) {
        const 模 = Math.sqrt(平方和)
        for (let i = 0; i < EMBED_DIM; i++) 兜底向量[i] /= 模
        查询向量 = 兜底向量
      }
    }
  }
  // 走到这里查询词还是空，只有两种情况：
  //   · 用户真的没输查询 → 列举模式（下面这个分支）
  //   · 用户输了词但它不在库里（兜底也没贴上）→ **必须返回 0 命中**，
  //     绝不能掉进列举模式假装搜到了全部。这是最难发现的失败模式：
  //     结果非空、看起来正常，实际答的是另一个问题。
  if (查询词.length === 0 && 原始查询非空) {
    return {
      结果: [],
      命中数: 0,
      平均分: 0,
      分数分布: { 最高: 0, 最低: 0, 中位数: 0 },
      查询词: [],
    }
  }
  if (查询词.length === 0 && 为空向量(查询向量)) {
    // 空查询：列举模式，按时间倒序，不算分
    const 列 = 候选.slice().sort((a, b) => String(b.at || b.日期 || '').localeCompare(String(a.at || a.日期 || '')))
    const 上限 = 夹限数(limit)
    // 列举模式没有分数，给一个全零的分数壳 —— 包装() 期望 {条目, 分}
    const 结果 = 列.slice(0, 上限).map((e) => 包装({ 条目: e, 分: { 总分: 0, 词面分: 0, 向量分: 0, 时效分: 0, 重要度分: 0 } }))
    return { 结果, 命中数: 列.length, 平均分: 0, 分数分布: { 最高: 0, 最低: 0, 中位数: 0 }, 查询词: [] }
  }

  const 查询 = { 词表: 查询词, 查询向量 }
  const 公共 = {
    权重,
    现在,
    df: 索引.df,
    总数: 索引.总数 || 1,
    条目向量: 索引.向量,
    索引,
  }
  // 第一遍：拿原始分项值，算全集范围
  const 原始 = 候选.map((e) => ({
    条目: e,
    分: 三因子打分(e, 查询, 公共),
  }))
  const 范围 = {
    词面: 范围取(原始, '词面分'),
    向量: 范围取(原始, '向量分'),
    时效: 范围取(原始, '时效分'),
    重要度: 范围取(原始, '重要度分'),
  }
  // 第二遍：用全集范围归一
  //
  // ⚠️ 双零过滤：词面分和向量分**都为 0** 的条目直接出局。
  // 时效与重要度是「在相关条目之间」做排序微调用的，不是入场券 ——
  // 一条跟查询毫无字面与语义关系的日记，不能因为它「很新」「有标签」
  // 就挤进结果。不拦这一下，搜索「服务器」会返回刚记的奶茶，
  // 而且分数还不难看（实测 0.19）。
  const 打分过 = 原始
    .map((x) => ({ 条目: x.条目, 分: 三因子打分(x.条目, 查询, { ...公共, 全集: 范围 }) }))
    // ⚠️ 词面分必须 > 0 才入场。
    //
    // 早先的写法是「词面 > 0 **或** 向量 > 0」，等于给哈希向量开了后门：
    // 查询词在语料里根本不存在时，它们的哈希只会落在随机维度上，
    // 跟任何条目的余弦都是一个随机数（实测胡词能凑出 0.735）。
    // 哈希向量适合兜「同义改写」，不适合兜「这个词压根没有」。
    // 词面分为 0 说明查询词一个都没落到这条日记上，就不该算命中。
    .filter((x) => x.分.词面分 > 0)
    .filter((x) => x.分.总分 >= 最低分)

  打分过.sort((a, b) => {
    if (b.分.总分 !== a.分.总分) return b.分.总分 - a.分.总分
    const da = a.条目.at || a.条目.日期 || ''
    const db = b.条目.at || b.条目.日期 || ''
    if (db !== da) return db < da ? -1 : 1
    const ka = 来源序(a.条目.来源)
    const kb = 来源序(b.条目.来源)
    if (ka[0] !== kb[0]) return ka[0] - kb[0]
    if (ka[1] !== kb[1]) return ka[1] - kb[1]
    return ka[2] < kb[2] ? -1 : ka[2] > kb[2] ? 1 : 0
  })

  const 上限 = 夹限数(limit)
  const 结果 = 打分过.slice(0, 上限).map((x) => 包装(x))
  const 全分 = 打分过.map((x) => x.分.总分).sort((a, b) => a - b)
  return {
    结果,
    命中数: 打分过.length,
    平均分: 全分.length ? 全分.reduce((a, b) => a + b, 0) / 全分.length : 0,
    分数分布: {
      最高: 全分.length ? 全分[全分.length - 1] : 0,
      最低: 全分.length ? 全分[0] : 0,
      中位数: 中位数(全分),
    },
    查询词,
  }
}

/**
 * 查询侧分词：用「段内最长真实词」而不是 2 字滑窗当偏好。
 *
 * 为什么查询侧要区别于索引侧：索引侧要的是「这段文字里有哪些词」，
 * 越多越好；查询侧要的是「用户到底在问哪个东西」。搜「服务器」时，
 * 2 字滑窗会先贴出「服务」，于是「服务器」永远算没命中 —— 用户搜的
 * 那个词反而丢了。所以查询侧先从「整句里最长能贴出的词」出发，
 * 让「服务器」优先于「服务」。
 *
 * @param {string} 文本
 * @param {object} 索引
 * @returns {string[]}
 */
function 分词查询 (文本, 索引) {
  const 串 = String(文本 || '').toLowerCase()
  const 表 = 索引 && 索引.最长词表 instanceof Set ? 索引.最长词表 : null
  if (!表 || 表.size === 0) return 切词(串).filter((w) => !默认停用词.has(w))
  // 先把查串按标点切段，每段贴出最长词；贴不到就退 2 字窗
  const 出 = new Set()
  for (const m of 串.matchAll(/[^\s\p{P}\p{S}]+/gu)) {
    const 段 = m[0]
    let i = 0
    while (i < 段.length) {
      let 命中 = ''
      const 上限 = Math.min(8, 段.length - i)
      for (let len = 上限; len >= 2; len--) {
        const w = 段.slice(i, i + len)
        if (表.has(w)) { 命中 = w; break }
      }
      if (命中) {
        if (!默认停用词.has(命中)) 出.add(命中)
        i += 命中.length
      } else {
        i += 1
      }
    }
    // 段内一个词都贴不到（生词、新词）就退回滑窗，
    // 否则整句查询会被静默丢掉
    if (出.size === 0) for (const w of 切词(段)) if (!默认停用词.has(w)) 出.add(w)
  }
  return [...出]
}

/** 把内部条目包成对外结果。 */
function 包装 (x) {
  const e = x.条目
  return {
    来源: e.来源,
    日期: e.日期,
    id: e.id,
    标题: e.title || '',
    内容: e.text,
    标签: e.tags || [],
    时间: e.at || '',
    分数: {
      总分: 舍(x.分.总分),
      词面: 舍(x.分.词面分),
      向量: 舍(x.分.向量分),
      时效: 舍(x.分.时效分),
      重要度: 舍(x.分.重要度分),
    },
  }
}

/** 分数留三位小数：给模型看的文本里四位小数只是噪声。 */
function 舍 (v) {
  return Number.isFinite(v) ? Math.round(v * 1000) / 1000 : 0
}

function 范围取 (原始, 键) {
  let 最小 = Infinity
  let 最大 = -Infinity
  for (const x of 原始) {
    const v = x.分[键]
    if (!Number.isFinite(v)) continue
    if (v < 最小) 最小 = v
    if (v > 最大) 最大 = v
  }
  if (!Number.isFinite(最小) || !Number.isFinite(最大)) return { 最小: 0, 最大: 0 }
  return { 最小, 最大 }
}

function 中位数 (已排序) {
  if (已排序.length === 0) return 0
  const m = Math.floor(已排序.length / 2)
  return 已排序.length % 2 ? 已排序[m] : (已排序[m - 1] + 已排序[m]) / 2
}

function 夹限数 (n) {
  const v = Number(n)
  if (!Number.isFinite(v) || v <= 0) return 20
  return Math.max(1, Math.min(Math.floor(v), 100))
}

function 为空向量 (v) {
  if (!v) return true
  for (let i = 0; i < v.length; i++) if (v[i] !== 0) return false
  return true
}

/**
 * 判置信度：检索库自己够不够，还是要下钻记忆仓库捞原话。
 *
 * 三条触发条件分别对应三种失败模式：
 *   ① 命中 0 条 —— 词面、向量、标签全没对上，多半是日记里根本没记，
 *      但记忆仓库的原始聊天里可能说过；
 *   ② 最高分太低 —— 对上了但很勉强，属于「大概提过一句」的量级，
 *      细节一定在原话里；
 *   ③ 分数挤在一起 —— 这是最隐蔽的一种：命中好几条、分数都不低，
 *      但最高分和中位数差不到 0.05，说明检索库分不出哪条最相关。
 *      此时拿排第一的当真会误导，需要原话当上下文再判。
 *
 * 为什么不用模型来判：这三条都是纯数字判断，模型只会带来延迟和不确定性；
 * 而且模型看不到「检索库分不出高下」这种信息，它只会挑一条看起来合理的，
 * 反而把不确定性藏起来。
 *
 * @param {{命中数?:number, 分数分布?:{最高:number,最低:number,中位数:number}, 结果?: object[]}} 检索结果
 * @param {{最低分?:number, 挤在一起阈值?:number}} [选项]
 * @returns {{下钻: boolean, 理由: string}}
 */
export function 判置信度 (检索结果, 选项 = {}) {
  const { 最低分 = 0.35, 挤在一起阈值 = 0.05 } = 选项 || {}
  const r = 检索结果 || {}
  const 命中数 = Number(r.命中数) || (Array.isArray(r.结果) ? r.结果.length : 0)
  const 分布 = r.分数分布 || { 最高: 0, 最低: 0, 中位数: 0 }
  const 最高 = Number(分布.最高) || 0
  const 中位 = Number(分布.中位数) || 0

  if (命中数 === 0) {
    return { 下钻: true, 理由: '检索库没有命中，需要去记忆仓库捞原话' }
  }
  if (最高 < 最低分) {
    return { 下钻: true, 理由: `最高分只有 ${舍(最高)}（低于 ${最低分}），词面与语义都没对上，需要原话上下文` }
  }
  if (命中数 >= 3 && 最高 - 中位 < 挤在一起阈值) {
    return { 下钻: true, 理由: `命中 ${命中数} 条但分数过于接近（最高 ${舍(最高)}，中位 ${舍(中位)}），检索库分不出哪条最相关` }
  }
  return { 下钻: false, 理由: `检索库置信度足够（最高分 ${舍(最高)}，命中 ${命中数} 条）` }
}
