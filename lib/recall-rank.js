// ============================================================================
// rank.js —— 记忆检索库的打分核心：停用词 + 最长匹配 + 哈希向量 + 三因子
//
// 【这个模块负责什么】
//   索引日记条目，并按「词面 / 向量 / 时效 / 重要度」四路打分排序。
//   不选条目之外的东西、不读文件、不发请求 —— 谁给我条目集合，我就给谁排名。
//   另外提供一个「要不要下钻记忆仓库」的置信度判断，也是纯算术，不调模型。
//
// 【为什么这样设计】
//   · 三因子结构照 Generative Agents（Park et al. 2023）：
//     score = recency + importance + relevance。那篇论文的 relevance 是稠密
//     嵌入，这里拆成了「词面 + 向量」两路 —— 中文里词面命中往往比语义更像
//     「用户真在问这个词」，纯语义会把「服务器挂了」和「机器出问题」排在一起
//     却把真正写着「服务器」的条目排下去，那是这类系统最常见的召回错觉。
//     论文里 recency 用 0.995 每小时衰减，这里改成每天 0.995：日记的时间
//     粒度是天，按小时衰减会让三周前的条目直接沉到接近零，等于把历史抹掉。
//   · 最长匹配切词，不用 2 字滑窗：滑窗会把「今天去哪里」切成
//     今天/天去/去哪/哪里，「天去」这种跨词碎片在真实数据里大量出现，
//     既污染词面分也让 IDF 失真。最长匹配是拿索引里真实出现过的词去贴，
//     贴不出碎词。代价是没见过的词会被跳过 —— 所以词表从一个位置取不到
//     就退一个字符继续试，不是整段放弃。
//   · 哈希向量而非模型嵌入：向量只是为了兜住「字面不重合的改写」，
//     不值得为它引入 API key、网络依赖和每次检索的延迟。signed hashing
//     trick 用 +1/-1 抵消一部分碰撞，256 维对几十到几千条日记够用。
//   · 停用词只挡纯语法功能词：「的/了/是」这类词在每条日记里都出现，
//     IDF 本来就接近 0，但它们的**词面分分母**会把真实信号稀释；
//     稍等 —— 更准确地说：df 高 → IDF 低 → 贡献小，这已经是自动的，
//     停用词表的真正价值是**避免长查询被虚词主导分词走向**，以及让
//     「最少要命中一个实词」这类判断有依据。所以它挡的是分词与候选，
//     不是粗暴地删词。
//   · min-max 归一化要有「全集」才成立：单个条目自己跟自己比永远是 1。
//     所以检索() 先对整批候选算出每项的最大值，再逐条归一化。没给全集时
//     退化成 clamp 到 [0,1]，结果是「分数可比但偏乐观」，这在单条预览
//     场景下无害，在排序场景下调用方必须传全集 —— JSDoc 里写清了。
//
// 【对外导出】
//   · EMBED_DIM —— 哈希向量维度
//   · 切词(text) —— 与 recall.js 逐字一致的 2 字滑窗（对拍用）
//   · 默认停用词 —— 中文虚词表
//   · 建索引(条目们) —— 建 df / 最长词表 / 向量
//   · 分词(文本, 索引) —— 最长匹配切词，丢停用词
//   · 嵌入(文本, 索引) —— 本地哈希向量（IDF 加权 + L2 归一化）
//   · 余弦(a, b) —— clamp 到 [0,1] 的余弦
//   · 三因子打分(条目, 查询词, 选项) —— 四个分项 + 总分
//   · 检索(索引, query, 选项) —— 排序后的结果
//   · 判置信度(检索结果) —— 要不要下钻记忆仓库
// ============================================================================

/** 哈希向量维度。太小碰撞多，太大对几十条日记是浪费。 */
export const EMBED_DIM = 256

/** 单条打分用的总权重。和不必为 1，内部会归一。 */
export const 默认权重 = Object.freeze({ 词面: 0.4, 向量: 0.3, 时效: 0.2, 重要度: 0.1 })

/**
 * 2 字滑窗切词。与 recall.js 的 切词 逐字一致 —— 保留它是为了对拍：
 * 分词()（最长匹配）是改进版，但得有个「旧行为」当基准，出问题时能立刻
 * 判断是切词变了还是打分变了。
 *
 * @param {string} text
 * @returns {string[]}
 */
export function 切词 (text) {
  const 串 = String(text || '').toLowerCase()
  const 词 = new Set()
  for (const m of 串.matchAll(/[a-z0-9]{2,}/g)) 词.add(m[0])
  for (const m of 串.matchAll(/[\u4e00-\u9fa5]+/g)) {
    const s = m[0]
    if (s.length <= 2) {
      词.add(s)
      continue
    }
    for (let i = 0; i + 2 <= s.length; i++) 词.add(s.slice(i, i + 2))
  }
  return [...词]
}

