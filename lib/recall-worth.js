// ============================================================================
// recall-worth.js —— 让大模型判断「这段有没有值得记的东西」
//
// 【为什么需要这一步】
//
// 规则打不出「值不值得记」这个判断，实测已经很清楚（2026-11-04）：
//
//   大群 1171 行/天 → 【日记】【模型】【gemini】  ← 真有内容
//   中群  326 行/天 → 【米饭】【笑话】【客气】【游戏】 ← 全是闲聊
//
// 规则能算出「这个词出现了几次」「几个人说过」，但算不出
// 「米饭」那一段其实只是在报午饭吃什么，「游戏」那一段其实只是在瞎扯。
// 主人原话：「交给大模型分辨有没有重点要记的东西，纯闲聊的话不要记」。
//
// 【设计前提：没有模型也必须能用】
//
// 这是开源项目的硬约束，所以这里是**可选增强**，不是前提：
//   · 配了模型 → 先用规则粗筛（省 token），再让模型逐段判断值不值得记
//   · 没配模型 → 退回纯规则判断（原来的价值分），功能照常可用
//
// 【省钱的顺序：先规则粗筛，再送模型】
//
// 实测群的量：730783833 一天 2202 条消息、聚出 10 个话题段。
// 直接把所有段都送模型判断，一次几十次请求。
// 所以先用规则挡掉明显不可能的（价值分 < 粗筛线），再送模型看剩下的。
// 并且**只判断值不值得记，不重新提炼** —— 判断的输出极小（几十个 token），
// 提炼留给已有的日记/规则，不重复花钱。
// ============================================================================

/**
 * 默认粗筛线：规则分低于这个的，连送模型都不值得。
 *
 * 0.3 的依据：实测纯寒暄段（「抱」「乖宝宝在」）分数在 0.0-0.25，
 * 而「米饭」「笑话」这类闲聊段在 0.35-0.5 之间 —— 粗筛线必须低到能放它们过去，
 * 让模型来判，否则模型根本没机会否决。粗筛只挡「一定不是」的。
 */
export const 默认粗筛线 = 0.3

/**
 * 构造给模型的判断提示词。
 *
 * 要点：
 *   · 只让模型回答「值不值得记」，不让它总结 —— 输出小、便宜、判断准
 *   · 明确列出「不值得记」的样子（主人特别强调「纯闲聊的话不要记」）
 *   · 要求给出理由，这样用户能看到为什么被跳过，而不是黑箱
 *
 * @returns {string}
 */
export function 判断提示词 () {
  return [
    '你是一个记忆整理助手。下面是一段聊天记录。',
    '请判断：这段聊天里有没有**值得长期记住**的内容？',
    '',
    '值得记的内容包括：',
    '- 约定、决定、承诺（说好以后怎么做、定下什么方案）',
    '- 具体的事实与配置（端口号、路径、版本、账号、金额）',
    '- 某件事的来龙去脉（怎么出问题的、最后怎么解决的）',
    '- 人对某件事的态度或期望（喜欢什么、不想怎样）',
    '',
    '不值得记的内容（回答 false）：',
    '- 纯寒暄、打招呼、晚安、抱抱',
    '- 报天气、报时间、报吃了什么这种一过性的事',
    '- 群里的玩笑、玩梗、表情包、复读',
    '- 只有情绪没有具体内容的吐槽',
    '',
    '',
    '另外，如果这段聊天里有人 @ 了群里的机器人，请顺带判断说话人对它的态度：',
    '  "好"   —— 在夸它、感谢它、喜欢它',
    '  "坏"   —— 在骂它、嫌弃它、侮辱它',
    '  "中性" —— 只是提问、测试、闲聊，没有明显态度；或者这段里没人 @ 机器人',
    '注意：中文里的「大聪明」「真行」这类词常常是反讽，字面好实际是骂。',
    '拿不准就判「中性」—— 宁可不判，不要判错。',
    '',
    '只返回 JSON，不要任何解释文字，格式：',
    '{"值得记":true或false,"理由":"不超过20字","重点":"值得记时的概括","机器人态度":"好/坏/中性","态度理由":"不超过20字"}',
  ].join('\n')
}

/**
 * 从模型回复里解析判断结果。
 *
 * 模型经常不老实（包代码围栏、前后加话），所以按三种形态依次尝试。
 * 解析不出来时**默认当作值得记** —— 宁可多记一条，不要因为解析失败
 * 把真正的重点整段丢掉。这是有意的不对称。
 *
 * @param {string} 文本
 * @returns {{值得记:boolean, 理由:string, 重点:string, 解析成功:boolean}}
 */
export function 解析判断 (文本) {
  const s = String(文本 ?? '').trim()
  const 失败 = { 值得记: true, 理由: '模型回复解析失败，按值得记处理', 重点: '', 机器人态度: '中性', 态度理由: '', 解析成功: false }
  if (!s) return 失败

  const 候选 = [s]
  const 围栏 = s.match(/```(?:json)?\s*([\s\S]*?)```/i)
  if (围栏) 候选.push(围栏[1].trim())
  const 左 = s.indexOf('{')
  const 右 = s.lastIndexOf('}')
  if (左 >= 0 && 右 > 左) 候选.push(s.slice(左, 右 + 1))

  for (const 段 of 候选) {
    try {
      const o = JSON.parse(段)
      if (!o || typeof o !== 'object' || Array.isArray(o)) continue
      // 键名兼容几种常见写法
      const 值 = o.值得记 ?? o.worth ?? o.worthRemembering ?? o.keep
      if (typeof 值 !== 'boolean') continue
      // 机器人态度：同一次调用顺带返回，不额外花钱。
      // 没这个字段或值不认识 → 中性（宁可不判，不要判错）
      const 态 = String(o.机器人态度 ?? o.attitude ?? '').trim()
      const 机器人态度 = (态 === '好' || 态 === '坏') ? 态 : '中性'
      return {
        值得记: 值,
        理由: String(o.理由 ?? o.reason ?? '').slice(0, 40),
        重点: String(o.重点 ?? o.summary ?? '').slice(0, 80),
        机器人态度,
        态度理由: String(o.态度理由 ?? '').slice(0, 40),
        解析成功: true,
      }
    } catch { /* 试下一种形态 */ }
  }
  return 失败
}

/**
 * 判断一段值不值得记（调模型）。
 *
 * 失败时**不抛错**，返回 值得记: true —— 判断失败不该导致内容被丢掉。
 *
 * @param {Array<{时间?:string, 昵称?:string, 内容?:string}>} 消息们
 * @param {{baseURL:string, apiKey:string, model:string, 温度?:number}} 配置
 * @param {{超时毫秒?:number, 最多条数?:number, 日志?:Function}} [选项]
 * @returns {Promise<{值得记:boolean, 理由:string, 重点:string, 解析成功:boolean}>}
 */
export async function 判断值不值得记 (消息们, 配置, 选项 = {}) {
  const 说 = typeof 选项.日志 === 'function' ? 选项.日志 : () => {}

  const 全部 = (Array.isArray(消息们) ? 消息们 : []).filter((m) => String(m?.内容 || '').trim())
  // 空段直接判「不值得记」——这不需要模型
  if (全部.length === 0) return { 值得记: false, 理由: '空段', 重点: '', 解析成功: true }

  if (!配置 || !配置.baseURL || !配置.apiKey || !配置.model) {
    return { 值得记: true, 理由: '没有模型配置，跳过模型判断', 重点: '', 解析成功: false }
  }

  // 只送前 最多条数 条：判断「有没有重点」不需要看完整段，
  // 而群里一段可能有几十条，全送进去纯属浪费 token。
  const 最多 = Number.isFinite(Number(选项.最多条数)) ? Number(选项.最多条数) : 30
  const 取样 = 全部.slice(0, 最多)
  const 正文 = 取样
    .map((m, i) => `${i + 1}. ${m?.昵称 || ''}：${String(m?.内容 || '').slice(0, 200)}`)
    .join('\n')

  const 超时 = Number.isFinite(Number(选项.超时毫秒)) ? Number(选项.超时毫秒) : 30000
  const 控 = new AbortController()
  const 定时 = setTimeout(() => 控.abort(), 超时)
  try {
    const 地址 = String(配置.baseURL).replace(/\/$/, '')
    const 回 = await fetch(String(配置.baseURL).includes('/chat/completions')
      ? 地址
      : `${地址}/chat/completions`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${配置.apiKey}` },
      body: JSON.stringify({
        model: 配置.model,
        messages: [
          { role: 'system', content: 判断提示词() },
          { role: 'user', content: 正文 },
        ],
        temperature: Number.isFinite(Number(配置.温度)) ? Number(配置.温度) : 0,
        // 判断的输出极小，给 200 足够；给多了模型容易写废话
        max_tokens: 200,
      }),
      signal: 控.signal,
    })
    if (!回.ok) {
      const t = await 回.text().catch(() => '')
      说(`判断请求失败 HTTP ${回.status}：${t.slice(0, 80)}`)
      // 失败按「值得记」处理：宁可多记，不要因为一次网络抖动丢掉重点
      return { 值得记: true, 理由: `模型请求失败（HTTP ${回.status}），按值得记处理`, 重点: '', 解析成功: false }
    }
    const 数据 = await 回.json()
    const 文本 = 数据?.choices?.[0]?.message?.content
    if (typeof 文本 !== 'string' || !文本.trim()) {
      return { 值得记: true, 理由: '模型没返回内容，按值得记处理', 重点: '', 解析成功: false }
    }
    return 解析判断(文本)
  } catch (e) {
    const msg = e?.name === 'AbortError' ? `超时（${超时}ms）` : String(e?.message || e)
    说(`判断失败：${msg}`)
    return { 值得记: true, 理由: `模型调用失败（${msg}），按值得记处理`, 重点: '', 解析成功: false }
  } finally {
    clearTimeout(定时)
  }
}

/**
 * 批量判断：先用规则粗筛，再逐段问模型。
 *
 * 省钱的关键在这一层：
 *   · 规则分低于粗筛线 → 直接丢弃，不花 token
 *   · 剩下的才送模型（并发发，但有上限，避免打爆限流）
 *
 * @param {Array<{段:object, 规则分:number}>} 候选
 * @param {object|null} 配置 模型配置；null 表示不用模型
 * @param {{粗筛线?:number, 并发?:number, 日志?:Function, 停止条件?:Function,
 *   已判断?:(指纹:string)=>boolean,
 *   每段判完?:(指纹:string, 判定:object)=>void,
 *   指纹?:Function}} [选项]
 *   已判断：这条之前判过就不再花钱（配合投喂账本）
 *   每段判完：判完立刻回调记账 —— 中途被打断时，已花的钱不能白花
 *   指纹：从段算出身份键，默认用「来源+日期+事件名+起始时间」
 * @returns {Promise<{保留:Array<{段:object, 判断:object}>, 统计:object}>}
 */
export async function 批量判断 (候选, 配置, 选项 = {}) {
  const 说 = typeof 选项.日志 === 'function' ? 选项.日志 : () => {}
  const 粗筛线 = Number.isFinite(Number(选项.粗筛线)) ? Number(选项.粗筛线) : 默认粗筛线
  const 并发 = Math.max(1, Math.min(Number(选项.并发) || 3, 8))

  const 全部 = Array.isArray(候选) ? 候选 : []
  const 统计 = {
    候选: 全部.length,
    粗筛掉: 0,
    已判过: 0,
    送模型: 0,
    模型判闲聊: 0,
    保留: 0,
    用了模型: !!(配置 && 配置.baseURL && 配置.apiKey && 配置.model),
  }
  // 身份键：默认「来源+日期+事件名+起始时间」。
  // 用对象引用当键是不行的 —— 事件在流水线里被复制过，引用对不上（实测踩过）。
  const 取指纹 = typeof 选项.指纹 === 'function'
    ? 选项.指纹
    : (段) => `${段?.来源 || ''}\u0001${段?.日期 || ''}\u0001${段?.事件 || ''}\u0001${段?.起 || ''}`
  const 已判断 = typeof 选项.已判断 === 'function' ? 选项.已判断 : null
  const 每段判完 = typeof 选项.每段判完 === 'function' ? 选项.每段判完 : null

  // ── 粗筛：规则分太低的连问都不问 ─────────────────────────────────
  //
  // ⚠️ 例外：含 @ 别人家机器人的段不能粗筛掉。
  //
  // 实测踩过（2026-11-04）：`@龙娘 你个废物` 这种内容，规则价值分很低
  // （它不是「约定/决定/具体配置」），会被粗筛线 0.2 直接挡掉 ——
  // 于是「@ 别人机器人由模型打分」这条永远收不到数据，
  // 送模型 0 段，日志看着一切正常但什么都没判。
  //
  // 规则判不了这类内容，才要交给模型；现在反过来被规则挡在门外，逻辑就断了。
  const 待判 = []
  let 规则保送 = 0
  for (const x of 全部) {
    const 含机器人艾特 = typeof 选项.含机器人艾特 === 'function'
      ? 选项.含机器人艾特(x?.段)
      : false
    if (Number(x?.规则分) < 粗筛线 && !含机器人艾特) { 统计.粗筛掉 += 1; continue }
    if (含机器人艾特 && Number(x?.规则分) < 粗筛线) 规则保送 += 1
    待判.push(x)
  }
  if (规则保送 > 0) 说(`粗筛线放了 ${规则保送} 段（含 @ 别人家机器人，规则判不了，交给模型）`)

  // ── 已判断过的跳过：不重复花钱 ────────────────────────────────────
  //
  // 没有这一步的话，每跑一次事件提炼，所有话题都会重新送模型判断一遍 ——
  // 钱白花，而且账本上一条记录都没有，用户查不出钱花在哪。
  // 这正是主人 2026-11-04 要求「避免反复投喂」要防的事。
  //
  // ⚠️ 判过的不能简单「跳过」—— 那样重跑时这些事件就消失了
  // （实测踩过：第二次跑事件数从 1 变 0，因为全部被判过、全部跳过）。
  // 正确做法：判过的查账本，按**上次的结论**决定去留。
  let 待送 = 待判
  const 上次结论 = []
  if (已判断) {
    const 筛后 = []
    for (const x of 待判) {
      const 指纹 = 取指纹(x.段)
      const 有记录 = 已判断(指纹)
      if (有记录) {
        统计.已判过 += 1
        // 账本里记了结论：true=值得记、false=闲聊。
        // 老记录没有结论字段时按「值得记」处理（宁可多留）
        const 结论 = typeof 选项.取上次结论 === 'function' ? 选项.取上次结论(指纹) : null
        if (结论 !== false) 上次结论.push({ 段: x.段, 判断: { 值得记: true, 理由: '上次已判断过（值得记）', 重点: '', 解析成功: true, 来自缓存: true } })
        continue
      }
      筛后.push(x)
    }
    待送 = 筛后
  }

  // ── 没配模型：粗筛后的全部保留（退回原来的行为）───────────────────
  if (!统计.用了模型) {
    统计.保留 = 待送.length
    说(`未配模型：规则粗筛掉 ${统计.粗筛掉} 段，保留 ${统计.保留} 段`)
    return {
      保留: [...上次结论, ...待送.map((x) => ({ 段: x.段, 判断: { 值得记: true, 理由: '未配模型，按规则保留', 重点: '', 解析成功: false } }))],
      统计,
    }
  }

  // ── 送模型：有并发上限，失败按值得记处理 ─────────────────────────
  统计.送模型 = 待送.length
  const 结果 = []
  for (let i = 0; i < 待送.length; i += 并发) {
    if (typeof 选项.停止条件 === 'function' && 选项.停止条件()) break
    const 批 = 待送.slice(i, i + 并发)
    const 判定 = await Promise.all(批.map((x) => {
      const 消息们 = x.段?.消息 || x.段?.消息们 || []
      return 判断值不值得记(消息们, 配置, { ...选项 })
    }))
    for (let j = 0; j < 批.length; j++) {
      // 判完立刻记账（不管结论是记还是不记）——
      // 只要问过模型就花了钱，下次不该再问一遍。
       if (每段判完) {
        try { 每段判完(取指纹(批[j].段), 判定[j]) } catch { /* 记账失败不影响结果 */ }
      }
      if (判定[j].值得记) {
        结果.push({ 段: 批[j].段, 判断: 判定[j] })
      } else {
        统计.模型判闲聊 += 1
      }
    }
  }

  const 全部保留 = [...上次结论, ...结果]
  统计.保留 = 全部保留.length
  说(`模型判断：送 ${统计.送模型} 段，判为闲聊 ${统计.模型判闲聊} 段，保留 ${统计.保留} 段`
    + (统计.已判过 > 0 ? `（其中 ${统计.已判过} 段用上次结论，没再花钱）` : ''))
  return { 保留: 全部保留, 统计 }
}
