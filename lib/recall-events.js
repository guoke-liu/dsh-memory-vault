// ============================================================================
// recall-events.js —— 把一串聊天消息切成一件事一件事
//
// 【这个模块负责什么】
//   输入一批已经排好序的聊天消息，输出**事件段**：每段是一段连续的对话，
//   带着时间范围、参与者、消息列表。它不做提炼、不调模型、不读文件 ——
//   纯函数，同样的输入永远同样的输出。
//
//   提炼（写起因/经过/结果）由 recall-event-extract.js 做，
//   这里只负责「哪几条消息算同一件事」。
//
// 【为什么私聊和群聊要用两套切法】
//   实测 2026-11-03 的真实数据（见 CHANGELOG v1.5.3）：
//
//   私聊：一对一，天然串行。按时间断点切就很好 ——
//         397 条消息切出 22 段，每段都能读出一件完整的事。
//
//   群聊：多个事件**同时交错**。同一分钟内 A 在问画图、
//         B 在聊角色设定、C 在问「这啥」。按时间切，必然把三件事
//         切进同一段 —— 这不是阈值调不好的问题，是群聊的固有形态。
//         所以群聊不切「事件」，只做话题聚类，见 recall-topics.js。
//
// 【为什么不用「话题连续性」当主判据】
//   试过（2026-11-04）：相邻消息关键词重合度低于阈值就切。
//   结果 397 条切成 127 段 —— 聊天里「嗯」「对」「哈哈」这类短句
//   天然没有关键词，一刀一刀切下去，碎得没法用。
//   时间断点反而最贴合真实节奏：人说话本来就是一阵一阵的。
// ============================================================================

/**
 * 默认时间断点（秒）。
 *
 * 10 分钟的依据：实测私聊消息间隔中位数只有 6 秒，但一天里有大量
 * 「聊一阵、停一阵」的间隔。用 10 分钟切，397 条得 22 段，粒度合适；
 * 用 30 分钟只剩 14 段，明显把不同的事合并了。
 */
export const 默认断点秒 = 600

/**
 * 单段最多多少条 — 超过就要再细分。
 *
 * 实测最大的段落有 128 条（凌晨 02:27–02:58 连续聊了半小时）。
 * 128 条塞给模型，它根本分不清里面有几种话题，提炼出来的「经过」
 * 会变成大杂烩。所以超过 40 条就再切一次。
 */
export const 默认单段上限 = 40

/**
 * 机器人播报的特征。
 *
 * 这些不是「发生的事」，是系统通知 —— 整段都是播报的段必须整段丢掉，
 * 否则会提炼出「事件：DSH 重启了七次」这种毫无意义的东西。
 *
 * 实测 11-03 私聊 397 条里有 34 条是播报，占 8.6%；
 * 不滤掉的话 22 段里会有 10 段是纯播报。
 */
export const 播报特征 = [
  /DSH 已重启/,
  /新链接/,
  /通道测试/,
  /收到请忽略/,
  /token=/,
  /^https?:\/\//,
  /^(ping|pong|ok|test)$/i,
]

/**
 * 这条消息是不是机器人播报。
 * @param {string} 内容
 * @returns {boolean}
 */
export function 是播报 (内容) {
  const s = String(内容 ?? '').trim()
  if (!s) return true
  return 播报特征.some((r) => r.test(s))
}

/**
 * 检测一条消息是不是「转述 / 角色扮演」。
 *
 * 【为什么需要】
 *   实测（2026-11-04）群聊里有这种消息：
 *     [00:34] 灰灰: 记忆？我脑子里就一堆鱼食和代码，没别的。（群里）灰灰：我可没给谁灌输啥
 *   一条消息里塞了两个人的话：「（群里）灰灰：」后面那段是有人**扮演**灰灰说的，
 *   不是灰灰本人的原话。直接把整条当成「灰灰说的」当证据，
 *   会把别人的话记成鱼的记忆 —— 检索出来是错的，而且很难发现。
 *
 * 【为什么标记而不是剔除】
 *   一条扮演消息的前半段可能是真的（上面那条「我脑子里就一堆鱼食和代码」）。
 *   整条丢掉会连同真话一起丢。所以标出来，让检索层自己决定怎么用。
 *
 * @param {string} 内容
 * @returns {{扮演:boolean, 方式:string}}
 */
export function 检测扮演 (内容) {
  const s = String(内容 ?? '').trim()
  if (!s) return { 扮演: false, 方式: '' }

  // 形态一：（群里）某人：……  —— 实测最常见的写法
  if (/[（(]群里[）)]\s*[^：:\s]{1,20}\s*[：:]/.test(s)) return { 扮演: true, 方式: '群里转述' }
  // 形态二：（私聊）某人：……
  if (/[（(]私聊[）)]\s*[^：:\s]{1,20}\s*[：:]/.test(s)) return { 扮演: true, 方式: '私聊转述' }
  // 形态三：整句被引号包起来，且带说话人 —— 「某人说：…」
  if (/^[「『"]/.test(s) && /[」』"]\s*$/.test(s)) return { 扮演: true, 方式: '整句引用' }

  return { 扮演: false, 方式: '' }
}

/**
 * 把 "HH:MM:SS" 转成当天的秒数。格式不对返回 null。
 * @param {string} 时间
 * @returns {number|null}
 */
export function 时刻转秒 (时间) {
  const m = String(时间 ?? '').match(/^(\d{1,2}):(\d{2})(?::(\d{2}))?$/)
  if (!m) return null
  const h = Number(m[1])
  const mi = Number(m[2])
  const s = Number(m[3] || 0)
  if (h > 23 || mi > 59 || s > 59) return null
  return h * 3600 + mi * 60 + s
}

/**
 * 切事件（私聊用）。
 *
 * 做法：按时间断点切段 → 太长的段再细分 → 丢掉纯播报段。
 * 关掉播报过滤的段（全是播报）整段丢弃。
 *
 * @param {Array<{时间?:string, 昵称?:string, pid?:string, 内容?:string, 日期?:string}>} 消息们
 * @param {{断点秒?:number, 单段上限?:number, 滤播报?:boolean}} [选项]
 * @returns {Array<{起:string, 止:string, 日期:string, 条数:number,
 *   参与人:Array<string>, 消息:Array<object>, 切法:string}>}
 */
export function 切事件 (消息们, 选项 = {}) {
  const 断点 = Number.isFinite(Number(选项.断点秒)) ? Number(选项.断点秒) : 默认断点秒
  const 上限 = Number.isFinite(Number(选项.单段上限)) ? Number(选项.单段上限) : 默认单段上限
  const 滤播报 = 选项.滤播报 !== false

  const 全部 = Array.isArray(消息们) ? 消息们 : []

  // 先滤播报：整段都是播报的情况靠这一步直接消失，不用事后判断
  const 有效 = 滤播报 ? 全部.filter((m) => !是播报(m?.内容)) : 全部

  // ── 第一刀：时间断点 ─────────────────────────────────────────────
  const 粗段 = []
  let 当前 = []
  const 收尾 = (切法) => {
    if (当前.length) { 粗段.push({ 消息: 当前, 切法 }); 当前 = [] }
  }
  for (const m of 有效) {
    if (当前.length === 0) { 当前.push(m); continue }
    const 上 = 当前[当前.length - 1]
    const 上秒 = 时刻转秒(上.时间)
    const 本秒 = 时刻转秒(m.时间)
    // 时间读不出来的就不当断点信号 —— 宁可合并也不乱切
    if (上秒 !== null && 本秒 !== null && 本秒 - 上秒 > 断点) {
      收尾('时间断点')
      当前.push(m)
      continue
    }
    当前.push(m)
  }
  收尾('时间断点')

  // ── 第二刀：太长的段再细分 ───────────────────────────────────────
  //
  // 为什么用「均分」而不是又找一个断点：这些段本来就是连续聊出来的，
  // 段内没有明显的时间空档（否则第一刀已经切了）。均分是最不坏的切法 ——
  // 至少每段长度可控，模型能看清里面在聊什么。
  const 细分 = []
  for (const d of 粗段) {
    if (d.消息.length <= 上限) { 细分.push(d); continue }
    const 份数 = Math.ceil(d.消息.length / 上限)
    const 每份 = Math.ceil(d.消息.length / 份数)
    for (let i = 0; i < d.消息.length; i += 每份) {
      细分.push({ 消息: d.消息.slice(i, i + 每份), 切法: '超长细分' })
    }
  }

  // ── 收尾：补上时间范围和参与者 ───────────────────────────────────
  return 细分
    .filter((d) => d.消息.length > 0)
    .map((d) => {
      const 首 = d.消息[0]
      const 末 = d.消息[d.消息.length - 1]
      // 参与者按第一次出现的顺序去重，保留顺序比排序更能看出「谁先说的」
      const 人 = []
      for (const m of d.消息) {
        const 名 = String(m?.昵称 || m?.pid || '').trim()
        if (名 && !人.includes(名)) 人.push(名)
      }
      return {
        起: String(首?.时间 || ''),
        止: String(末?.时间 || ''),
        日期: String(首?.日期 || ''),
        条数: d.消息.length,
        参与人: 人,
        消息: d.消息,
        切法: d.切法,
        // 这段里有几条是「转述/扮演」——检索层据此判断证据可信度。
        // 整条丢掉会连同真话一起丢（扮演消息的前半段常常是真的），
        // 所以只标记，不剔除。
        扮演条数: d.消息.filter((m) => 检测扮演(m?.内容).扮演).length,
      }
    })
}

/**
 * 给事件段算一个「够不够格当一个事件」的分数。
 *
 * 为什么要筛：切出来的段里有很多是「宝宝」「嗯」「晚安」这种一句话的段落。
 * 每一段都送模型提炼，纯属白花钱 —— 而且提炼出来的「事件」是
 * 「用户叫了一声宝宝」，没有任何检索价值。
 *
 * 判据不是「越长越好」，而是「有没有信息」：
 *   · 只有应答（嗯、好的、哈哈）→ 0 分
 *   · 有一段实质内容（单条够长、说了件具体的事）→ 加分
 *   · 参与的人越多越像件事（至少两个人在讨论）
 *   · 带具体信息（数字、路径、决定词）加分
 *
 * ⚠️ 单条消息的长度要单独看，不能只看总和。
 * 实测踩过（2026-11-04）：「15:44 宝宝/在呢/饭吃上了没/嗯呢」这种寒暄
 * 加起来字数不少，但全是废话；而「我在群里认了：那拿扫帚的是我自己」
 * 只有两条、总字数不多，却是一件具体的事。按总和算会同时误判这两个。
 *
 * @param {{消息:Array<object>, 条数:number, 参与人:Array<string>}} 段
 * @returns {number} 0..1 的分数
 */
export function 事件价值分 (段) {
  const 消息们 = Array.isArray(段?.消息) ? 段.消息 : []
  if (消息们.length === 0) return 0

  const 正文们 = 消息们.map((m) => String(m?.内容 || ''))
  const 正文 = 正文们.join('')
  const 字数 = 正文.replace(/\s/g, '').length
  // 最长的那一条 —— 判断「这段里有没有一句话说了件实事」
  const 最长条 = Math.max(...正文们.map((t) => t.replace(/\s/g, '').length))

  // 全是短句且总字数也不多 → 纯寒暄
  if (字数 < 15) return 0
  // 没有一条像样的句子（都在 12 字以内）→ 寒暄堆，不是事
  if (最长条 < 12 && 字数 < 40) return 0

  let 分 = 0

  // 长度：20~200 字线性加分，超过 200 不再加（长不代表信息多）
  分 += Math.min(字数, 200) / 200 * 0.30

  // 有没有一句话说了件实事：单条超过 15 字算
  if (最长条 >= 15) 分 += 0.20
  // 有明显长句（25 字以上），信息量更足
  if (最长条 >= 25) 分 += 0.10

  // 多个参与者：一问一答比自言自语更像件事
  const 人数 = Array.isArray(段?.参与人) ? 段.参与人.length : 0
  if (人数 >= 2) 分 += 0.20

  // 具体信息：数字、路径、URL、版本号 —— 这些是「事实」的标志
  if (/\d/.test(正文)) 分 += 0.10
  if (/(?:[a-zA-Z]:)?[\\/][\w.-]+\.\w{1,5}/.test(正文) || /https?:\/\//.test(正文)) 分 += 0.10

  // 约定与决定：这类词出现说明这一段的结论值得记
  if (/说好|答应|决定|定了|以后|下次|记得|别忘|截止|提醒|必须|约定|改成|换成|修好|搞定|完成|认了|补了|还剩|还差/.test(正文)) 分 += 0.15

  return Math.min(分, 1)
}
