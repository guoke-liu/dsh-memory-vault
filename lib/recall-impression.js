// ============================================================================
// recall-impression.js —— 群友印象分：别人 @ 鱼时，说的是好话还是坏话
//
// 【这个模块负责什么】
//   从群聊里找出「@ 鱼」的消息，判断那条消息本身对鱼是好是坏，
//   按人累计成一个印象分。分数会轻微影响检索优先级 —— 好话和坏话**都往上抬**。
//
// 【为什么只认明确的信号】
//
//   主人 2026-11-04 定的：只认明确的好话和坏话，模糊的一律中性。
//
//   原因是实测数据里全是反讽的坑：
//     「@肥肥 大聪明」      —— 可能是夸，也可能是骂
//     「@迟迟」             —— 只有 @，没有内容
//   中文里「大聪明」「真行」「你了不起」这类词，字面是好的、意思是坏的。
//   规则判不出来，判错就等于把阴阳怪气记成了好评 —— 比不记更糟。
//
//   所以这里的原则是：**宁可不打分，也不打错分**。
//   只认那些几乎没有歧义的词（宝宝真乖 / 谢谢 / 爱你 / 滚 / 傻逼），
//   其余全部中性。这样印象分数量少，但每一条都是准的。
//
// 【为什么好坏都往上抬】
//
//   印象分不是「好感度排名」，是「这段关系里有没有值得翻出来的细节」。
//   一个人天天骂鱼，和一个人天天夸鱼，同样值得记住。
//   只抬高好话会把冲突藏起来 —— 而那些恰恰是最需要被记住的。
// ============================================================================

/** 明确的好话。这些词在中文里几乎没有反讽用法。 */
const 好话 = [
  /宝宝真乖/, /真乖/, /好棒/, /太棒了/, /厉害/, /谢谢/, /多谢/, /辛苦了/,
  /爱你/, /喜欢你/, /想你/, /亲亲/, /抱抱/, /贴贴/, /摸摸头/,
  /可爱/, /好可爱/, /真可爱/, /贴心/, /暖心/, /靠谱/,
  /做得对/, /干得好/, /加油/, /支持你/,
]

/** 明确的坏话。 */
const 坏话 = [
  /滚/, /傻[逼比б]/, /傻子/, /蠢/, /白痴/, /智障/, /脑残/,
  /废物/, /垃圾/, /恶心/, /讨厌/, /烦死了/, /别烦我/, /闭嘴/,
  /没用/, /废了/, /算了你/, /去死/, /妈的/, /操你/,
]

/**
 * 有歧义的词 —— 字面好、实际常是反讽，**故意不判**。
 *
 * 单独列出来是为了留下证据：以后有人问「为什么『大聪明』不算好话」，
 * 这里有答案。也是防止有人「顺手」把它加进好话列表。
 */
export const 歧义词 = [
  '大聪明', '真行', '你了不起', '佩服', '高手', '人才',
  '真棒呢', '厉害了我的', '可以啊你',
]

/**
 * 判断一条消息对鱼是好话、坏话还是中性。
 *
 * @param {string} 内容 去掉 @ 之后的消息正文
 * @returns {{倾向:'好'|'坏'|'中性', 依据:string}}
 */
export function 判断印象 (内容) {
  const s = String(内容 ?? '').trim()
  // 只有 @ 没有内容 → 没法判断
  if (!s) return { 倾向: '中性', 依据: '没有内容' }

  // 有歧义的词先查：命中了就直接中性，不再往下判。
  // 顺序很重要 —— 「大聪明」里没有好话词，但如果以后有人把「聪明」加进好话，
  // 这个前置检查能保证「大聪明」仍然不被判成好话。
  for (const w of 歧义词) {
    if (s.includes(w)) return { 倾向: '中性', 依据: `含歧义词「${w}」，不下判断` }
  }

  for (const r of 坏话) {
    if (r.test(s)) return { 倾向: '坏', 依据: `命中坏话：${r.source}` }
  }
  for (const r of 好话) {
    if (r.test(s)) return { 倾向: '好', 依据: `命中好话：${r.source}` }
  }
  return { 倾向: '中性', 依据: '没有明确的好/坏信号' }
}

/**
 * 从一条聊天消息里拆出「@ 了谁」和「@ 之后的内容」。
 *
 * QQ 的数据里 @ 的写法不统一，实测见过：
 *   `@小鱼儿 宝宝真乖`        正常带空格
 *   `@迟迟https://... 看看这个`  紧贴链接
 *   `@迟迟`                   只有 @
 *
 * @param {string} 内容
 * @returns {{艾特们:Array<string>, 正文:string}}
 */
export function 拆艾特 (内容) {
  const s = String(内容 ?? '')
  const 艾特们 = []
  // @ 后面跟一串非空白字符。
  //
  // ⚠️ 不能把 `.` `:` `/` 当终止符。实测数据里有这一条：
  //   `@迟迟https://github.com/x 看看这个`
  // 早先的正则把 `.` 当分隔，只截到 `@迟迟https://github`，
  // 剩下的 `.com/x 看看这个` 变成了「正文」—— 判断好坏时拿到的是残缺链接。
  // 现在只按空白和中文标点断，链接能整段保留。
  const 正则 = /@([^\s@，。！？、；：“”（）]{1,80})/g
  let m
  while ((m = 正则.exec(s)) !== null) {
    艾特们.push(m[1])
  }
  // 正文 = 去掉所有 @xxx 之后剩下的
  const 正文 = s.replace(正则, '').replace(/\s+/g, ' ').trim()
  return { 艾特们, 正文 }
}

/**
 * 从一批聊天消息里统计印象分。
 *
 * @param {Array<{时间?:string, 昵称?:string, 内容?:string, 日期?:string, 来源?:string}>} 消息们
 * @param {{鱼的叫法?:Array<string>, 最多保留?:number}} [选项]
 *   鱼的叫法：@ 后面出现这些词才算「艾特鱼」
 * @returns {{按人:Object<string, {好:number, 坏:number, 次数:number, 分数:number, 样例:Array}>, 合计:object}}
 */
export function 算印象分 (消息们, 选项 = {}) {
  const 叫法 = Array.isArray(选项.鱼的叫法) && 选项.鱼的叫法.length
    ? 选项.鱼的叫法.map(String)
    : ['小鱼儿', '过客家的小鱼儿', '迟迟', '肥肥', '大肥鱼', '鱼鱼']

  // 别人家机器人的叫法 —— 这些不算「艾特鱼」，留给模型判断
  const 别人机器人 = Array.isArray(选项.别人机器人) ? 选项.别人机器人.map(String) : []
  const 是别人机器人 = (a) => 别人机器人.some((r) => a.includes(r))
  const 最多样例 = Number.isFinite(Number(选项.最多保留)) ? Number(选项.最多保留) : 3

  const 按人 = {}
  let 总好 = 0
  let 总坏 = 0
  let 艾特总数 = 0
  const 统计 = { 别人机器人艾特: 0 }

  for (const msg of Array.isArray(消息们) ? 消息们 : []) {
    const { 艾特们, 正文 } = 拆艾特(msg?.内容)
    if (艾特们.length === 0) continue

    // ① 艾特鱼自己 → 规则判断（零成本、快）
    const 艾特鱼 = 艾特们.some((a) => 叫法.some((c) => a.includes(c)))
    // ② 艾特别人家机器人 → 跳过，交给模型（见 模型判断机器人艾特）
    //
    //    为什么这里要显式跳过：一个叫「小鱼儿」的被 @，和一个叫「龙娘」的
    //    被 @，本该走两条路。如果不跳过，别人机器人的消息会因为
    //    「没有明确好坏信号」被静默归成中性 —— 模型那一层就永远收不到它们。
    if (!艾特鱼) {
      if (艾特们.some(是别人机器人)) 统计.别人机器人艾特 += 1
      continue
    }
    艾特总数 += 1

    const 判定 = 判断印象(正文)
    if (判定.倾向 === '中性') continue // 中性不计分，也不占位

    const 谁 = String(msg?.昵称 || '').trim() || '(无名)'
    if (!按人[谁]) 按人[谁] = { 好: 0, 坏: 0, 次数: 0, 分数: 0, 样例: [] }
    const 记 = 按人[谁]
    记.次数 += 1
    if (判定.倾向 === '好') { 记.好 += 1; 总好 += 1 } else { 记.坏 += 1; 总坏 += 1 }
    // 样例：留着原文，让人能核对「凭什么这么判」
    if (记.样例.length < 最多样例) {
      记.样例.push({
        倾向: 判定.倾向,
        原文: String(msg?.内容 || '').slice(0, 100),
        日期: String(msg?.日期 || ''),
        时间: String(msg?.时间 || ''),
        依据: 判定.依据,
      })
    }
  }

  // 分数：好 +1、坏 +1（绝对值相加）
  //
  // 为什么不是「好减坏」：那样一个人夸 10 次骂 10 次会被算成 0 分，
  // 而实际上这恰恰是最值得注意的关系（又爱又恨）。
  // 印象分衡量的是「跟鱼的互动强度」，不是「好感净额」。
  for (const 记 of Object.values(按人)) {
    记.分数 = 记.好 + 记.坏
  }

  return {
    按人,
    合计: {
      艾特总数, 好: 总好, 坏: 总坏,
      有印象的: Object.keys(按人).length,
      // 留给模型的那部分：@ 了别人机器人的消息有几条
      别人机器人艾特: 统计.别人机器人艾特,
    },
  }
}

/**
 * 某个人的印象分对应的「优先级加成」。
 *
 * 好话坏话都往上抬，但**幅度很小** —— 印象分是锦上添花，
 * 不能盖过「这件事重不重要」这个主判据。
 *
 * 0 条 → +0
 * 1 条 → +0.05
 * 3 条 → +0.10
 * 5 条以上 → +0.15（封顶）
 *
 * @param {{分数?:number}|undefined} 记录
 * @returns {number} 0..0.15
 */
export function 印象加成 (记录) {
  const n = Number(记录?.分数) || 0
  if (n <= 0) return 0
  return Math.min(0.05 * n, 0.15)
}


// ============================================================================
// 别人家的机器人：交给模型判断
// ============================================================================
//
// 主人 2026-11-04：「艾特用户自己的机器人的，艾特别人机器人的则由大模型
// 筛选的时候打分」。
//
// 为什么要分两套：
//   · @鱼自己 —— 规则就够。「宝宝真乖」「滚」这种明确信号，规则判得又快又准
//   · @别人家的机器人（@龙娘 / @grok / @限时接入Gemini）—— 内容五花八门，
//     「查询好感度」「is it true」这种，规则完全没法判是好是坏，得看语境
//
// 实测群里的例子：
//   [21:37] 柳如烟: @龙娘 我头像叫什么名字
//   [18:54] 灵千梦: @grok is it true
//   [19:03] hah:    @限时接入Gemini 查询好感度

/** 判断「@ 别人家机器人」时的倾向 —— 提示词。 */
export function 机器人艾特提示词 () {
  return [
    '下面是一条群聊消息，它 @ 了群里的某个机器人（不是说话的人自己的机器人）。',
    '请判断这条消息对这个机器人的态度：',
    '  "好"   —— 在夸它、感谢它、喜欢它',
    '  "坏"   —— 在骂它、嫌弃它、侮辱它',
    '  "中性" —— 只是提问、测试、闲聊，没有明显态度',
    '注意：中文里的「大聪明」「真行」这类词常常是反讽，字面好实际是骂。',
    '拿不准就判「中性」—— 宁可不判，不要判错。',
    '',
    '只返回 JSON，不要解释：',
    '{"倾向":"好"或"坏"或"中性","理由":"不超过20字"}',
  ].join('\n')
}

/**
 * 解析模型对「@ 别人机器人」的判断。
 *
 * 解析失败一律返回「中性」—— 这个方向的不对称和规则层一致：
 * 宁可少记一条，也不能把骂人记成夸奖。
 *
 * @param {string} 文本
 * @returns {{倾向:'好'|'坏'|'中性', 理由:string, 解析成功:boolean}}
 */
export function 解析机器人判断 (文本) {
  const s = String(文本 ?? '').trim()
  const 失败 = { 倾向: '中性', 理由: '解析失败，按中性处理', 解析成功: false }
  if (!s) return 失败

  const 候选 = [s]
  const 围栏 = s.match(/```(?:json)?\s*([\s\S]*?)```/i)
  if (围栏) 候选.push(围栏[1].trim())
  const 左 = s.indexOf('{')
  const 右 = s.lastIndexOf('}')
  if (左 >= 0 && 右 > 左) 候选.push(s.slice(左, 右 + 1))

  for (const 段 of 候选) {
    try {
      const o = JSON.parse(段)
      if (!o || typeof o !== 'object') continue
      const 倾向 = String(o.倾向 ?? o.attitude ?? '').trim()
      if (倾向 === '好' || 倾向 === '坏' || 倾向 === '中性') {
        return { 倾向, 理由: String(o.理由 ?? o.reason ?? '').slice(0, 40), 解析成功: true }
      }
    } catch { /* 试下一种 */ }
  }
  return 失败
}

/**
 * 用模型判断一条「@ 别人家机器人」的消息是什么态度。
 *
 * 模型不可用或失败时返回「中性」—— 绝不让一次网络抖动
 * 变成一条凭空的印象记录。
 *
 * @param {string} 内容 完整消息
 * @param {{baseURL:string, apiKey:string, model:string, 温度?:number}} 配置
 * @param {{超时毫秒?:number}} [选项]
 * @returns {Promise<{倾向:'好'|'坏'|'中性', 理由:string, 解析成功:boolean}>}
 */
export async function 模型判断机器人艾特 (内容, 配置, 选项 = {}) {
  const s = String(内容 ?? '').trim()
  if (!s) return { 倾向: '中性', 理由: '没有内容', 解析成功: true }
  if (!配置 || !配置.baseURL || !配置.apiKey || !配置.model) {
    return { 倾向: '中性', 理由: '没有模型配置', 解析成功: false }
  }

  const 超时 = Number.isFinite(Number(选项.超时毫秒)) ? Number(选项.超时毫秒) : 30000
  const 控 = new AbortController()
  const 定时 = setTimeout(() => 控.abort(), 超时)
  try {
    const 地址 = String(配置.baseURL).replace(/\/$/, '')
    const 回 = await fetch(String(配置.baseURL).includes('/chat/completions')
      ? 地址
      : `${地址}/chat/completions`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${配置.apiKey}` },
      body: JSON.stringify({
        model: 配置.model,
        messages: [
          { role: 'system', content: 机器人艾特提示词() },
          { role: 'user', content: s.slice(0, 500) },
        ],
        temperature: 0,
        max_tokens: 120,
      }),
      signal: 控.signal,
    })
    if (!回.ok) return { 倾向: '中性', 理由: `HTTP ${回.status}`, 解析成功: false }
    const 数据 = await 回.json()
    const 文本 = 数据?.choices?.[0]?.message?.content
    if (typeof 文本 !== 'string') return { 倾向: '中性', 理由: '模型没返回内容', 解析成功: false }
    return 解析机器人判断(文本)
  } catch (e) {
    const msg = e?.name === 'AbortError' ? `超时（${超时}ms）` : String(e?.message || e)
    return { 倾向: '中性', 理由: msg, 解析成功: false }
  } finally {
    clearTimeout(定时)
  }
}
